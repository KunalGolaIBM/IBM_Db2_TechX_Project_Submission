import React from 'react';
import { Cpu, Radio, FlaskConical, Sparkles } from 'lucide-react';

/**
 * Data-source badges — the integrity layer.
 * SIMULATED data must ALWAYS be visibly labelled wherever readings appear.
 */

/** Amber "SIMULATED" chip — synthetic demo data, not real measurements. */
export const SimulatedBadge = ({ small = false }) => (
  <span
    title="Synthetic demo data generated by the simulator — NOT a real field measurement"
    className={`inline-flex items-center gap-1 font-bold uppercase tracking-wider border border-amber-400/40 bg-amber-400/10 text-amber-300 rounded-md ${small ? 'text-[9px] px-1.5 py-0.5' : 'text-[10px] px-2 py-1'}`}
  >
    <FlaskConical size={small ? 9 : 11} /> Simulated
  </span>
);

/** Green "SENSOR" chip — real measurement ingested from a device. */
export const DeviceBadge = ({ small = false }) => (
  <span
    title="Real measurement ingested from a field sensor via /api/ingest"
    className={`inline-flex items-center gap-1 font-bold uppercase tracking-wider border border-emerald-400/40 bg-emerald-400/10 text-emerald-300 rounded-md ${small ? 'text-[9px] px-1.5 py-0.5' : 'text-[10px] px-2 py-1'}`}
  >
    <Cpu size={small ? 9 : 11} /> Sensor
  </span>
);

/** Teal "MIXED" chip — series contains both simulated and device data. */
export const MixedBadge = ({ small = false }) => (
  <span
    title="This series mixes SIMULATED demo data with real device readings — treat with caution"
    className={`inline-flex items-center gap-1 font-bold uppercase tracking-wider border border-teal-400/40 bg-teal-400/10 text-teal-300 rounded-md ${small ? 'text-[9px] px-1.5 py-0.5' : 'text-[10px] px-2 py-1'}`}
  >
    <Radio size={small ? 9 : 11} /> Mixed
  </span>
);

/** Smart badge: pick the right label from a readings array or source string. */
export const SourceBadge = ({ readings, source, small = false }) => {
  if (source) {
    if (source === 'simulated' || source === 'device') {
      return source === 'simulated' ? <SimulatedBadge small={small} /> : <DeviceBadge small={small} />;
    }
    return <MixedBadge small={small} />;
  }
  if (!readings || readings.length === 0) return null;
  const anyDevice = readings.some((r) => r.data_source === 'device');
  const anySim = readings.some((r) => r.is_simulated);
  if (anyDevice && anySim) return <MixedBadge small={small} />;
  if (anyDevice) return <DeviceBadge small={small} />;
  return <SimulatedBadge small={small} />;
};

