-- Least-privilege runtime access for the NSIN backend on IBM Db2.
--
-- Run once as the schema owner (db2inst1) after the first start has created the tables:
--   db2 connect to NSIN
--   db2 -tvf least_privilege.sql
-- Then run the backend with DB2_USER=nsinapp, DB2_SCHEMA=DB2INST1.
-- (scripts/db2_least_privilege.sh does all of this for the Docker setup.)
--
-- The role gets data access only: no CREATE, ALTER, DROP, GRANT or catalog administration.

CREATE ROLE NSIN_APP;

GRANT CONNECT ON DATABASE TO ROLE NSIN_APP;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE DB2INST1.USERS TO ROLE NSIN_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE DB2INST1.TRUSTED_CONTACTS TO ROLE NSIN_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE DB2INST1.RESPONDERS TO ROLE NSIN_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE DB2INST1.INCIDENTS TO ROLE NSIN_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE DB2INST1.INCIDENT_STATUS_HISTORY TO ROLE NSIN_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE DB2INST1.LOCATION_EVENTS TO ROLE NSIN_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE DB2INST1.CHILD_JOURNEYS TO ROLE NSIN_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE DB2INST1.ELDER_CHECKINS TO ROLE NSIN_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE DB2INST1.ASSISTANCE_REQUESTS TO ROLE NSIN_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE DB2INST1.COMMUNITY_HAZARDS TO ROLE NSIN_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE DB2INST1.AI_ANALYSIS_RECORDS TO ROLE NSIN_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE DB2INST1.AUDIT_EVENTS TO ROLE NSIN_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE DB2INST1.SAFETY_PROTOCOLS TO ROLE NSIN_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE DB2INST1.INCIDENT_EMBEDDINGS TO ROLE NSIN_APP;

-- The audit trail is append-only for the application: it may add and read events, never edit or erase them.
REVOKE UPDATE, DELETE ON TABLE DB2INST1.AUDIT_EVENTS FROM ROLE NSIN_APP;

GRANT ROLE NSIN_APP TO USER NSINAPP;
