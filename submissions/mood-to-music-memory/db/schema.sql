CREATE TABLE MOODS (
    MOOD_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    MOOD_CODE VARCHAR(64) NOT NULL UNIQUE,
    DISPLAY_NAME VARCHAR(128) NOT NULL,
    DESCRIPTION VARCHAR(512)
);

CREATE TABLE PLAYBACK_PROFILES (
    PROFILE_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PROFILE_CODE VARCHAR(64) NOT NULL UNIQUE,
    VOLUME_PERCENT SMALLINT NOT NULL,
    SPEED_MULTIPLIER DECIMAL(4,2) NOT NULL DEFAULT 1.00,
    FADE_IN_SECONDS SMALLINT NOT NULL DEFAULT 2,
    CONSTRAINT PROFILE_VOLUME_RANGE CHECK (VOLUME_PERCENT BETWEEN 0 AND 100),
    CONSTRAINT PROFILE_SPEED_RANGE CHECK (SPEED_MULTIPLIER BETWEEN 0.50 AND 2.00)
);

CREATE TABLE PLAYLISTS (
    PLAYLIST_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PLAYLIST_NAME VARCHAR(256) NOT NULL,
    DESCRIPTION VARCHAR(1000),
    PROFILE_ID BIGINT NOT NULL,
    IS_ACTIVE CHAR(1) NOT NULL DEFAULT 'Y',
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PLAYLIST_ACTIVE_FLAG CHECK (IS_ACTIVE IN ('Y', 'N')),
    CONSTRAINT PLAYLIST_PROFILE_FK FOREIGN KEY (PROFILE_ID)
        REFERENCES PLAYBACK_PROFILES (PROFILE_ID)
);

CREATE TABLE MOOD_PLAYLISTS (
    MOOD_ID BIGINT NOT NULL,
    PLAYLIST_ID BIGINT NOT NULL,
    PRIORITY SMALLINT NOT NULL DEFAULT 1,
    PRIMARY KEY (MOOD_ID, PLAYLIST_ID),
    CONSTRAINT MOOD_PLAYLIST_MOOD_FK FOREIGN KEY (MOOD_ID)
        REFERENCES MOODS (MOOD_ID),
    CONSTRAINT MOOD_PLAYLIST_PLAYLIST_FK FOREIGN KEY (PLAYLIST_ID)
        REFERENCES PLAYLISTS (PLAYLIST_ID)
);

CREATE TABLE SONGS (
    SONG_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    SONG_TITLE VARCHAR(512) NOT NULL,
    ARTIST VARCHAR(512) NOT NULL,
    ALBUM VARCHAR(512),
    LOCAL_FILE_PATH VARCHAR(2048) NOT NULL,
    DURATION_SECONDS INTEGER,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE PLAYLIST_SONGS (
    PLAYLIST_ID BIGINT NOT NULL,
    SONG_ID BIGINT NOT NULL,
    POSITION INTEGER NOT NULL,
    PRIMARY KEY (PLAYLIST_ID, SONG_ID),
    CONSTRAINT PLAYLIST_SONG_POSITION_UQ UNIQUE (PLAYLIST_ID, POSITION),
    CONSTRAINT PLAYLIST_SONG_PLAYLIST_FK FOREIGN KEY (PLAYLIST_ID)
        REFERENCES PLAYLISTS (PLAYLIST_ID),
    CONSTRAINT PLAYLIST_SONG_SONG_FK FOREIGN KEY (SONG_ID)
        REFERENCES SONGS (SONG_ID)
);

CREATE TABLE PLAYBACK_SESSIONS (
    SESSION_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    MOOD_ID BIGINT NOT NULL,
    PLAYLIST_ID BIGINT NOT NULL,
    STARTED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    ENDED_AT TIMESTAMP,
    FEEDBACK VARCHAR(32),
    CONSTRAINT SESSION_MOOD_FK FOREIGN KEY (MOOD_ID) REFERENCES MOODS (MOOD_ID),
    CONSTRAINT SESSION_PLAYLIST_FK FOREIGN KEY (PLAYLIST_ID)
        REFERENCES PLAYLISTS (PLAYLIST_ID)
);

CREATE TABLE MEMORIES (
    MEMORY_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    MEMORY_TEXT VARCHAR(4000) NOT NULL,
    SONG_TITLE VARCHAR(512) NOT NULL,
    ARTIST VARCHAR(512) NOT NULL,
    MOOD_TAG VARCHAR(128),
    SAVED_AT TIMESTAMP NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
);

CREATE INDEX MEMORIES_MOOD_IDX ON MEMORIES (MOOD_TAG);
CREATE INDEX MEMORIES_SAVED_AT_IDX ON MEMORIES (SAVED_AT);
CREATE INDEX MOOD_PLAYLISTS_PRIORITY_IDX ON MOOD_PLAYLISTS (MOOD_ID, PRIORITY);
CREATE INDEX PLAYLIST_SONGS_ORDER_IDX ON PLAYLIST_SONGS (PLAYLIST_ID, POSITION);
