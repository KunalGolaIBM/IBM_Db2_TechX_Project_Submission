import type { GeneratorType } from './domain'

/**
 * Who/what actually produced a recommendation. This is the single place that decides how the UI words it,
 * so rule-based output can never be described as an AI model's result.
 */
export type GeneratorKind = 'llm' | 'rules' | 'manual' | 'test-double' | 'unknown'

export interface GeneratorInfo {
  kind: GeneratorKind
  /** Short badge text. */
  label: string
  /** One sentence for tooltips, panels and screen readers. */
  description: string
  /** True only for output of a real hosted/local language model. */
  isRealModel: boolean
  /** provider:model, rule-set id, etc. */
  detail: string | null
}

const TEST_DOUBLE_PREFIX = 'test-double:'

export function describeGenerator(type: GeneratorType, modelName: string | null): GeneratorInfo {
  if (type === 'LLM') {
    if (modelName?.startsWith(TEST_DOUBLE_PREFIX)) {
      return {
        kind: 'test-double',
        label: 'Test double · not a real model',
        description:
          'Produced by a scripted test double used to exercise the agent loop. It is not a language model and its output is not evidence of AI reasoning.',
        isRealModel: false,
        detail: modelName,
      }
    }
    return {
      kind: 'llm',
      label: 'AI model (LLM)',
      description: `Generated by a language model${modelName ? ` (${modelName})` : ''} using audited read-only tools, then checked against evidence retrieved in the same run. A human must review it.`,
      isRealModel: true,
      detail: modelName,
    }
  }
  if (type === 'DETERMINISTIC_FALLBACK') {
    return {
      kind: 'rules',
      label: 'Rule-based · no LLM',
      description: `Produced by fixed, deterministic rules${modelName ? ` (${modelName})` : ''} over database aggregates. No AI model was involved; confidence is a data-volume heuristic, not a model probability.`,
      isRealModel: false,
      detail: modelName,
    }
  }
  if (type === 'MANUAL') {
    return {
      kind: 'manual',
      label: 'Manual · analyst-written',
      description: 'Written by an analyst. No AI model and no automated rules were involved.',
      isRealModel: false,
      detail: null,
    }
  }
  return {
    kind: 'unknown',
    label: 'Origin not recorded',
    description: 'This recommendation predates generator tracking, so how it was produced is unknown.',
    isRealModel: false,
    detail: modelName,
  }
}

const CITED_BY = /^cited by (LLM|DETERMINISTIC_FALLBACK|MANUAL)$/

const CITED_BY_WORDING: Record<GeneratorType, string> = {
  LLM: 'Cited during the LLM agent run',
  DETERMINISTIC_FALLBACK: 'Cited by the rule-based run (no LLM)',
  MANUAL: 'Cited in a manual proposal',
  UNKNOWN: 'Cited (origin not recorded)',
}

/**
 * The backend stores an evidence note such as "cited by DETERMINISTIC_FALLBACK". Show that in plain words
 * (same wording rules as describeGenerator) instead of a raw enum value. Any other note is shown unchanged.
 */
export function describeEvidenceNote(note: string): string {
  const match = CITED_BY.exec(note.trim())
  return match ? CITED_BY_WORDING[match[1] as GeneratorType] : note
}
