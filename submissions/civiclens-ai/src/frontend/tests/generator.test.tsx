import { render, screen } from '@testing-library/react'
import { describe, expect, it } from 'vitest'
import { GeneratorBadge, GeneratorExplanation } from '../src/components/Badges'
import { GENERATOR_TYPES } from '../src/lib/domain'
import { describeEvidenceNote, describeGenerator } from '../src/lib/generator'

const FALSELY_AI = /AI-generated|LLM-generated|generated by (an? |the )?(AI|LLM|language model)|written by (an? |the )?(AI|LLM|language model)/i

describe('describeGenerator: rule-based output is never described as an AI result', () => {
  it('real LLM output is the only thing labelled as a model', () => {
    const llm = describeGenerator('LLM', 'anthropic:some-model')
    expect(llm).toMatchObject({ kind: 'llm', isRealModel: true, label: 'AI model (LLM)', detail: 'anthropic:some-model' })
    expect(llm.description).toContain('anthropic:some-model')
  })

  it('deterministic fallback says "no LLM" and never claims to be a model', () => {
    const rules = describeGenerator('DETERMINISTIC_FALLBACK', 'hotspot-rules-v1')
    expect(rules.isRealModel).toBe(false)
    expect(rules.label).toMatch(/no LLM/i)
    expect(`${rules.label} ${rules.description}`).not.toMatch(FALSELY_AI)
    expect(rules.description).toMatch(/No AI model was involved/i)
    expect(rules.description).toMatch(/not a model probability/i)
  })

  it('manual recommendations are analyst-written and say neither AI nor rules were involved', () => {
    const manual = describeGenerator('MANUAL', null)
    expect(manual.kind).toBe('manual')
    expect(manual.isRealModel).toBe(false)
    expect(manual.description).toMatch(/No AI model and no automated rules/i)
  })

  it('a scripted test double stored as LLM is exposed as NOT a real model', () => {
    const double = describeGenerator('LLM', 'test-double:scripted')
    expect(double.kind).toBe('test-double')
    expect(double.isRealModel).toBe(false)
    expect(double.label).toMatch(/not a real model/i)
  })

  it('unknown origin is called unknown, not guessed', () => {
    const unknown = describeGenerator('UNKNOWN', null)
    expect(unknown.kind).toBe('unknown')
    expect(unknown.isRealModel).toBe(false)
  })

  it('only the LLM generator can ever be a real model', () => {
    for (const type of GENERATOR_TYPES) {
      expect(describeGenerator(type, 'some:model').isRealModel).toBe(type === 'LLM')
    }
  })
})

describe('GeneratorBadge', () => {
  it.each([
    ['LLM', 'provider:model', 'llm', 'AI model (LLM)'],
    ['DETERMINISTIC_FALLBACK', 'hotspot-rules-v1', 'rules', 'Rule-based · no LLM'],
    ['MANUAL', null, 'manual', 'Manual · analyst-written'],
    ['UNKNOWN', null, 'unknown', 'Origin not recorded'],
  ] as const)('%s renders its own label and kind', (type, model, kind, label) => {
    render(<GeneratorBadge type={type} modelName={model} />)
    const badge = screen.getByTestId('generator-badge')
    expect(badge).toHaveTextContent(label)
    expect(badge).toHaveAttribute('data-generator-kind', kind)
  })

  it('the rule-based badge never contains wording that claims AI authorship', () => {
    render(<GeneratorBadge type="DETERMINISTIC_FALLBACK" modelName="hotspot-rules-v1" />)
    const text = screen.getByTestId('generator-badge').textContent ?? ''
    expect(text).not.toMatch(FALSELY_AI)
    expect(text).not.toMatch(/^AI/i)
    expect(screen.getByTestId('generator-badge').getAttribute('title') ?? '').toMatch(/No AI model was involved/)
  })

  it('every generator badge differs in its words, not just in colour', () => {
    const labels = GENERATOR_TYPES.map((t) => describeGenerator(t, null).label)
    expect(new Set(labels).size).toBe(GENERATOR_TYPES.length)
  })
})

describe('GeneratorExplanation', () => {
  it('spells out provenance in a full sentence for reviewers', () => {
    render(<GeneratorExplanation type="DETERMINISTIC_FALLBACK" modelName="hotspot-rules-v1" />)
    expect(screen.getByTestId('generator-explanation')).toHaveTextContent(/fixed, deterministic rules/i)
    expect(screen.getByTestId('generator-explanation')).toHaveTextContent('hotspot-rules-v1')
  })
})

describe('describeEvidenceNote: the backend note is shown in plain words, never as a raw enum', () => {
  it('rule-based citations say rule-based and "no LLM"', () => {
    const text = describeEvidenceNote('cited by DETERMINISTIC_FALLBACK')
    expect(text).toBe('Cited by the rule-based run (no LLM)')
    expect(text).not.toMatch(FALSELY_AI)
    expect(text).not.toContain('DETERMINISTIC_FALLBACK')
  })

  it('every generator type has wording, and none of the wordings is a raw enum value', () => {
    for (const type of GENERATOR_TYPES.filter((t) => t !== 'UNKNOWN')) {
      const text = describeEvidenceNote(`cited by ${type}`)
      expect(text).not.toBe(`cited by ${type}`) // reworded
      expect(text).not.toMatch(/[A-Z]+_[A-Z]+/) // no SNAKE_CASE enum leaks through
      expect(text).toMatch(/^Cited /)
    }
    expect(describeEvidenceNote('cited by MANUAL')).not.toContain('MANUAL')
    expect(describeEvidenceNote('cited by LLM')).toMatch(/LLM agent run/)
    expect(describeEvidenceNote('cited by MANUAL')).toMatch(/manual/i)
  })

  it('anything else is shown exactly as written (an analyst note is never rewritten)', () => {
    expect(describeEvidenceNote('Photo attached by the resident')).toBe('Photo attached by the resident')
    expect(describeEvidenceNote('cited by DETERMINISTIC_FALLBACK and more')).toBe('cited by DETERMINISTIC_FALLBACK and more')
  })
})
