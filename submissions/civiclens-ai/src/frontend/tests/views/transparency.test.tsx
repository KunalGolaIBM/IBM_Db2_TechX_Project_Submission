import { screen, within } from '@testing-library/react'
import { http, HttpResponse } from 'msw'
import { describe, expect, it } from 'vitest'
import { API, overview, queueItem } from '../fixtures'
import { apiError, authed, server } from '../msw'
import { renderApp } from '../render'

const served = (o = overview()) => server.use(http.get(`${API}/api/overview`, authed(() => HttpResponse.json(o))))

describe('Agent transparency', () => {
  it('states that no recommendation came from a language model when none did', async () => {
    served()
    await renderApp('/transparency', { as: 'analyst' })
    expect(await screen.findByTestId('llm-count-statement')).toHaveTextContent('None of the 3 recommendations in the database were written by a language model')
    const llm = screen.getByTestId('llm-status')
    expect(llm).toHaveTextContent('No language model is configured')
    expect(screen.getByTestId('generator-count-LLM')).toHaveTextContent('0')
    expect(screen.getByTestId('generator-count-DETERMINISTIC_FALLBACK')).toHaveTextContent('3')
  })

  it('counts real LLM recommendations separately from rule-based and manual ones', async () => {
    const o = overview()
    served({ ...o, recommendations: { ...o.recommendations, total: 12, by_generator: { LLM: 5, DETERMINISTIC_FALLBACK: 4, MANUAL: 3, UNKNOWN: 0 } } })
    await renderApp('/transparency', { as: 'analyst' })
    expect(await screen.findByTestId('llm-count-statement')).toHaveTextContent('5 of 12 recommendations were written by a language model')
    expect(screen.getByTestId('generator-count-LLM')).toHaveTextContent('5')
    expect(screen.getByTestId('generator-count-DETERMINISTIC_FALLBACK')).toHaveTextContent('4')
    expect(screen.getByTestId('generator-count-MANUAL')).toHaveTextContent('3')
  })

  it('words the single-recommendation case correctly', async () => {
    const o = overview()
    served({ ...o, recommendations: { ...o.recommendations, total: 1, by_generator: { LLM: 0, DETERMINISTIC_FALLBACK: 1, MANUAL: 0, UNKNOWN: 0 } } })
    await renderApp('/transparency', { as: 'analyst' })
    expect(await screen.findByTestId('llm-count-statement')).toHaveTextContent('The one recommendation in the database was not written by a language model.')
  })

  it('uses "was" when exactly one recommendation came from a language model', async () => {
    const o = overview()
    served({ ...o, recommendations: { ...o.recommendations, total: 4, by_generator: { LLM: 1, DETERMINISTIC_FALLBACK: 3, MANUAL: 0, UNKNOWN: 0 } } })
    await renderApp('/transparency', { as: 'analyst' })
    expect(await screen.findByTestId('llm-count-statement')).toHaveTextContent('1 of 4 recommendations was written by a language model')
  })

  it('describes each author type in its own words', async () => {
    served()
    await renderApp('/transparency', { as: 'analyst' })
    expect(await screen.findByTestId('generator-card-LLM')).toHaveTextContent('Generated by a language model')
    expect(screen.getByTestId('generator-card-DETERMINISTIC_FALLBACK')).toHaveTextContent('No AI model was involved')
    expect(screen.getByTestId('generator-card-MANUAL')).toHaveTextContent('Written by an analyst')
  })

  it('shows the stored generator for every latest recommendation', async () => {
    served()
    server.use(
      http.get(`${API}/api/recommendations`, authed(() =>
        HttpResponse.json([
          queueItem({ recommendation_id: 1, generator_type: 'LLM', model_name: 'anthropic:some-model' }),
          queueItem({ recommendation_id: 2, generator_type: 'DETERMINISTIC_FALLBACK', model_name: 'hotspot-rules-v1' }),
          queueItem({ recommendation_id: 3, generator_type: 'MANUAL', model_name: null }),
          queueItem({ recommendation_id: 4, generator_type: 'LLM', model_name: 'test-double:scripted' }),
        ]),
      )),
    )
    await renderApp('/transparency', { as: 'analyst' })
    const rows = await screen.findAllByTestId('author-row')
    const labels = rows.map((r) => within(r).getByTestId('generator-badge').textContent)
    expect(labels).toEqual(['AI model (LLM)', 'Rule-based · no LLM', 'Manual · analyst-written', 'Test double · not a real model'])
    expect(rows.map((r) => r.getAttribute('data-generator'))).toEqual(['LLM', 'DETERMINISTIC_FALLBACK', 'MANUAL', 'LLM'])
  })

  it('lists the guard rails and the allow-listed tools reported by the server', async () => {
    const o = overview()
    served({ ...o, system: { ...o.system, agent: { max_steps: 4, timeout_s: 45, tools: ['search_complaints', 'hotspot_summary'] } } })
    await renderApp('/transparency', { as: 'analyst' })
    const rails = await screen.findByTestId('guard-rails')
    expect(rails).toHaveTextContent('4')
    expect(rails).toHaveTextContent('45 s')
    expect(within(screen.getByTestId('tool-list')).getAllByRole('listitem').map((li) => li.textContent)).toEqual(['search_complaints', 'hotspot_summary'])
    expect(screen.getByText('No model-written SQL')).toBeInTheDocument()
    expect(screen.getByText('Proposals only')).toBeInTheDocument()
  })

  it('reports a configured model without claiming it was tested', async () => {
    const o = overview()
    served({ ...o, system: { ...o.system, llm: { configured: true, provider: 'anthropic', model: 'a-model', problem: null } } })
    await renderApp('/transparency', { as: 'analyst' })
    const card = await screen.findByTestId('llm-status')
    expect(card).toHaveTextContent('Language model configured: anthropic · a-model')
    expect(card).toHaveTextContent('does not test connectivity')
  })

  it('says how tool calls are logged, so rule-based calls are not mistaken for LLM activity', async () => {
    served()
    await renderApp('/transparency', { as: 'analyst' })
    expect(await screen.findByText(/logged identically whether a language model or the rule-based fallback issued them/)).toBeInTheDocument()
  })

  it('shows the error when the overview cannot be loaded', async () => {
    server.use(http.get(`${API}/api/overview`, authed(() => apiError(503, 'DB_UNAVAILABLE', 'down'))))
    await renderApp('/transparency', { as: 'analyst' })
    expect(await screen.findByTestId('error-notice')).toHaveAttribute('data-status', '503')
  })
})
