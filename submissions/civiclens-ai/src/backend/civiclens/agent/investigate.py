"""Investigation orchestrator: runs the LLM agent or the labelled rule-based fallback and
persists grounded, PROPOSED recommendations in IBM Db2.

Truthful labelling: ``RunResult.generator`` / ``RECOMMENDATIONS.GENERATOR_TYPE`` is ``LLM`` only
when a real model produced the recommendations, otherwise ``DETERMINISTIC_FALLBACK``. In ``auto``
mode a failed LLM run degrades to the fallback *and says so* in ``fallback_reason``.
"""

from __future__ import annotations

import logging
from typing import Any

from civiclens.agent import fallback as fallback_mod
from civiclens.agent import runner
from civiclens.agent.llm import LlmConfigError, LlmHandle, build_llm
from civiclens.agent.tools import CivicLensToolkit
from civiclens.config import Settings
from civiclens.db import investigation_repo as inv_repo
from civiclens.db import repository as repo
from civiclens.db.connection import Db2Session
from civiclens.domain.errors import (
    AgentError,
    ConflictError,
    DomainError,
    LlmNotConfiguredError,
)
from civiclens.domain.investigation_models import (
    GeneratorType,
    InvestigationStatus,
    RunRequest,
    RunResult,
)

logger = logging.getLogger(__name__)
AGENT_ID = "civiclens-agent"
NOTICE_LLM = (
    "Recommendations were generated by the LLM '{label}' using audited Db2 tools, then grounded "
    "against evidence retrieved in this run. All are PROPOSED and need human review."
)
NOTICE_FALLBACK = (
    "Recommendations were produced by deterministic rule-based logic. NO LLM WAS USED. "
    "All are PROPOSED and need human review."
)


def _audit(db: Db2Session, inv_id: int):
    def write(action: str, payload: dict[str, Any], summary: str, success: bool) -> None:
        repo.write_audit(
            db,
            actor_type="AGENT",
            actor_id=AGENT_ID,
            action=action,
            investigation_id=inv_id,
            input_payload=payload,
            output_summary=summary,
            success=success,
        )

    return write


def run_investigation(
    db: Db2Session,
    investigation_id: int,
    *,
    requested_by: str,
    request: RunRequest,
    settings: Settings,
    llm: LlmHandle | None = None,
) -> RunResult:
    inv_repo.require_investigation(db, investigation_id)

    # ---- decide which engine is available (before claiming the investigation) -------------
    config_problem: str | None = None
    handle = llm
    if handle is None:
        try:
            handle = build_llm(settings)
        except LlmConfigError as exc:
            config_problem = str(exc)
    if request.mode == "llm" and handle is None:
        raise LlmNotConfiguredError(
            config_problem or "No LLM provider is configured (LLM_PROVIDER=none).",
            llm_configured=False,
        )

    claimed = inv_repo.transition_status(
        db,
        investigation_id,
        from_statuses=[InvestigationStatus.OPEN, InvestigationStatus.FAILED],
        to_status=InvestigationStatus.RUNNING,
    )
    if not claimed:
        raise ConflictError(
            "Investigation is not runnable (it is already running, awaiting review or closed).",
            code="INVESTIGATION_NOT_RUNNABLE",
        )

    audit = _audit(db, investigation_id)
    audit(
        "AGENT_RUN_STARTED",
        {"requested_by": requested_by, "mode": request.mode, "days": request.days},
        f"llm_available={handle is not None}",
        True,
    )
    inv = inv_repo.require_investigation(db, investigation_id)
    toolkit = CivicLensToolkit(db, investigation_id=investigation_id, actor_id=AGENT_ID)
    tools = {t.name: t for t in toolkit.tools()}
    limits = runner.Limits(settings.agent_max_steps, settings.agent_timeout_s)

    generator = GeneratorType.DETERMINISTIC_FALLBACK
    model_name: str | None = None
    fallback_reason: str | None = None
    try:
        loop: runner.LoopResult | None = None
        if request.mode in ("auto", "llm") and handle is not None:
            try:
                loop = runner.run_llm_loop(handle.model, tools, inv.question, limits, audit)
                accepted, rejected = runner.ground_drafts(loop.drafts, loop.seen_ids)
                for draft, ungrounded in rejected:
                    audit(
                        "EVIDENCE_REJECTED",
                        {"summary": draft.summary[:120], "ungrounded_ids": ungrounded[:20]},
                        "cited ids were not returned by any tool in this run",
                        False,
                    )
                if loop.drafts and not accepted:
                    raise AgentError(
                        "Every recommendation cited ungrounded evidence.", code="EVIDENCE_REJECTED"
                    )
                loop.drafts = accepted
                generator, model_name = GeneratorType.LLM, handle.label
            except AgentError as exc:
                reason = exc.details.get("reason")
                audit("LLM_RUN_FAILED", {"code": exc.code, "reason": reason}, exc.message[:300], False)
                if request.mode == "llm":
                    raise
                detail = f"{exc.code}: {reason}" if reason else exc.code
                fallback_reason = f"LLM run failed ({detail}); rule-based fallback used instead."
                loop = None
        elif request.mode == "auto":
            fallback_reason = config_problem or "No LLM provider configured (LLM_PROVIDER=none)."
        else:
            fallback_reason = "Rule-based fallback requested explicitly."
        if loop is None:
            loop = fallback_mod.run_fallback(tools, request)
            generator, model_name = GeneratorType.DETERMINISTIC_FALLBACK, fallback_mod.RULE_VERSION

        # ---- persist atomically: evidence links, recommendations, status ------------------
        rec_ids: list[int] = []
        with db.transaction():
            cited = sorted({i for d in loop.drafts for i in d.evidence_ids})
            if cited:
                inv_repo.add_evidence(
                    db, investigation_id, cited, relevance=1.0, note=f"cited by {generator.value}"
                )
            for draft in loop.drafts:
                rec_ids.append(
                    inv_repo.create_recommendation(
                        db,
                        investigation_id,
                        draft,
                        generator=generator,
                        model_name=model_name,
                        actor_id=AGENT_ID,
                    )
                )
            final = InvestigationStatus.PENDING_REVIEW if rec_ids else InvestigationStatus.CLOSED
            inv_repo.transition_status(
                db, investigation_id, from_statuses=[InvestigationStatus.RUNNING], to_status=final
            )
    except DomainError as exc:
        _fail(db, investigation_id, audit, exc.code, exc.message)
        raise
    except Exception as exc:
        logger.exception("Unexpected failure in investigation %s", investigation_id)
        _fail(db, investigation_id, audit, "UNEXPECTED", type(exc).__name__)
        raise AgentError("Investigation failed unexpectedly.", code="UNEXPECTED") from None

    audit(
        "AGENT_RUN_COMPLETED",
        {"generator": generator.value, "recommendations": len(rec_ids)},
        f"status={final.value} steps={loop.steps} tool_calls={loop.tool_calls}",
        True,
    )
    return RunResult(
        investigation_id=investigation_id,
        status=final,
        generator=generator,
        model_name=model_name,
        llm_configured=handle is not None,
        fallback_reason=fallback_reason,
        steps=loop.steps,
        tool_calls=loop.tool_calls,
        recommendation_ids=rec_ids,
        notice=NOTICE_LLM.format(label=model_name) if generator is GeneratorType.LLM else NOTICE_FALLBACK,
    )


def _fail(db: Db2Session, investigation_id: int, audit, code: str, message: str) -> None:
    try:
        inv_repo.transition_status(
            db,
            investigation_id,
            from_statuses=[InvestigationStatus.RUNNING],
            to_status=InvestigationStatus.FAILED,
        )
        audit("AGENT_RUN_FAILED", {"code": code}, message[:300], False)
    except Exception:  # pragma: no cover - best effort; never mask the original error
        logger.exception("Could not record failure for investigation %s", investigation_id)
