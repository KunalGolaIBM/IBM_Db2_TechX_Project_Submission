-- CivicLens AI: IBM Db2 schema (Phase 00)
--
-- `{schema}` is replaced at migration time with the validated value of
-- DB2_SCHEMA (default CIVICLENS). Statements are separated by semicolons;
-- the migrator checks the Db2 catalog (SYSCAT.*) before each CREATE so the
-- script is safe to run repeatedly.
--
-- Conventions:
--   * IS_SYNTHETIC = 1 marks demonstration data that is not a real complaint.
--   * Status/category columns use CHECK constraints instead of free text.
--   * AUDIT_LOG is append-only by convention (the application never updates it).

CREATE TABLE {schema}.COMPLAINTS (
    COMPLAINT_ID      BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    EXTERNAL_REF      VARCHAR(64),
    CATEGORY          VARCHAR(32)   NOT NULL,
    TITLE             VARCHAR(200)  NOT NULL,
    DESCRIPTION       VARCHAR(4000) NOT NULL,
    LATITUDE          DECIMAL(9,6)  NOT NULL,
    LONGITUDE         DECIMAL(9,6)  NOT NULL,
    GEO_CELL          VARCHAR(24)   NOT NULL,
    WARD              VARCHAR(64),
    SEVERITY          SMALLINT      NOT NULL DEFAULT 3,
    STATUS            VARCHAR(16)   NOT NULL DEFAULT 'NEW',
    SOURCE            VARCHAR(32)   NOT NULL DEFAULT 'API',
    TEXT_FINGERPRINT  CHAR(64)      NOT NULL,
    DUPLICATE_OF      BIGINT,
    IS_SYNTHETIC      SMALLINT      NOT NULL DEFAULT 0,
    REPORTED_AT       TIMESTAMP     NOT NULL,
    CREATED_AT        TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_COMPLAINTS PRIMARY KEY (COMPLAINT_ID),
    CONSTRAINT FK_COMPLAINTS_DUP FOREIGN KEY (DUPLICATE_OF)
        REFERENCES {schema}.COMPLAINTS (COMPLAINT_ID) ON DELETE SET NULL,
    CONSTRAINT CK_COMPLAINTS_CATEGORY CHECK (CATEGORY IN
        ('POTHOLE','STREETLIGHT','WATER_LEAK','SEWAGE','GARBAGE',
         'DRAINAGE','ROAD_DAMAGE','TRAFFIC_SIGNAL','OTHER')),
    CONSTRAINT CK_COMPLAINTS_SEVERITY CHECK (SEVERITY BETWEEN 1 AND 5),
    CONSTRAINT CK_COMPLAINTS_STATUS CHECK (STATUS IN
        ('NEW','TRIAGED','DUPLICATE','UNDER_INVESTIGATION','RESOLVED','REJECTED')),
    CONSTRAINT CK_COMPLAINTS_SYNTH CHECK (IS_SYNTHETIC IN (0,1)),
    CONSTRAINT CK_COMPLAINTS_LAT CHECK (LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_COMPLAINTS_LON CHECK (LONGITUDE BETWEEN -180 AND 180)
);

CREATE INDEX {schema}.IX_COMPLAINTS_CAT_TIME ON {schema}.COMPLAINTS (CATEGORY, REPORTED_AT);

CREATE INDEX {schema}.IX_COMPLAINTS_CELL_TIME ON {schema}.COMPLAINTS (GEO_CELL, REPORTED_AT);

CREATE INDEX {schema}.IX_COMPLAINTS_FINGERPRINT ON {schema}.COMPLAINTS (TEXT_FINGERPRINT);

CREATE INDEX {schema}.IX_COMPLAINTS_STATUS ON {schema}.COMPLAINTS (STATUS, REPORTED_AT);

CREATE TABLE {schema}.INVESTIGATIONS (
    INVESTIGATION_ID  BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    TITLE             VARCHAR(200)  NOT NULL,
    QUESTION          VARCHAR(2000) NOT NULL,
    STATUS            VARCHAR(20)   NOT NULL DEFAULT 'OPEN',
    CREATED_BY        VARCHAR(64)   NOT NULL,
    CREATED_AT        TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CLOSED_AT         TIMESTAMP,
    CONSTRAINT PK_INVESTIGATIONS PRIMARY KEY (INVESTIGATION_ID),
    CONSTRAINT CK_INVESTIGATIONS_STATUS CHECK (STATUS IN
        ('OPEN','RUNNING','PENDING_REVIEW','CLOSED','FAILED'))
);

CREATE TABLE {schema}.INVESTIGATION_EVIDENCE (
    INVESTIGATION_ID  BIGINT       NOT NULL,
    COMPLAINT_ID      BIGINT       NOT NULL,
    RELEVANCE         DECIMAL(4,3) NOT NULL DEFAULT 1.000,
    NOTE              VARCHAR(1000),
    ADDED_AT          TIMESTAMP    NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_EVIDENCE PRIMARY KEY (INVESTIGATION_ID, COMPLAINT_ID),
    CONSTRAINT FK_EVIDENCE_INV FOREIGN KEY (INVESTIGATION_ID)
        REFERENCES {schema}.INVESTIGATIONS (INVESTIGATION_ID) ON DELETE CASCADE,
    CONSTRAINT FK_EVIDENCE_CMP FOREIGN KEY (COMPLAINT_ID)
        REFERENCES {schema}.COMPLAINTS (COMPLAINT_ID) ON DELETE CASCADE,
    CONSTRAINT CK_EVIDENCE_REL CHECK (RELEVANCE BETWEEN 0 AND 1)
);

CREATE TABLE {schema}.RECOMMENDATIONS (
    RECOMMENDATION_ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    INVESTIGATION_ID  BIGINT        NOT NULL,
    SUMMARY           VARCHAR(500)  NOT NULL,
    RATIONALE         VARCHAR(8000) NOT NULL,
    PRIORITY          SMALLINT      NOT NULL DEFAULT 3,
    CONFIDENCE        DECIMAL(4,3)  NOT NULL,
    EVIDENCE_IDS      VARCHAR(2000) NOT NULL,
    MODEL_NAME        VARCHAR(128),
    GENERATOR_TYPE    VARCHAR(24)   NOT NULL DEFAULT 'UNKNOWN',
    STATUS            VARCHAR(16)   NOT NULL DEFAULT 'PROPOSED',
    CREATED_AT        TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_RECOMMENDATIONS PRIMARY KEY (RECOMMENDATION_ID),
    CONSTRAINT FK_REC_INV FOREIGN KEY (INVESTIGATION_ID)
        REFERENCES {schema}.INVESTIGATIONS (INVESTIGATION_ID) ON DELETE CASCADE,
    CONSTRAINT CK_REC_PRIORITY CHECK (PRIORITY BETWEEN 1 AND 5),
    CONSTRAINT CK_REC_CONF CHECK (CONFIDENCE BETWEEN 0 AND 1),
    CONSTRAINT CK_REC_STATUS CHECK (STATUS IN
        ('PROPOSED','APPROVED','REJECTED','NEEDS_INFO')),
    CONSTRAINT CK_REC_GENERATOR CHECK (GENERATOR_TYPE IN
        ('LLM','DETERMINISTIC_FALLBACK','MANUAL','UNKNOWN'))
);

CREATE INDEX {schema}.IX_REC_INV_STATUS ON {schema}.RECOMMENDATIONS (INVESTIGATION_ID, STATUS);

-- Evidence cited by a recommendation. The composite foreign key means Db2 itself rejects
-- any complaint that has not been attached to the *same* investigation, so a fabricated or
-- foreign evidence id cannot be stored even if application validation were bypassed.
CREATE TABLE {schema}.RECOMMENDATION_EVIDENCE (
    RECOMMENDATION_ID BIGINT NOT NULL,
    INVESTIGATION_ID  BIGINT NOT NULL,
    COMPLAINT_ID      BIGINT NOT NULL,
    CONSTRAINT PK_REC_EVIDENCE PRIMARY KEY (RECOMMENDATION_ID, COMPLAINT_ID),
    CONSTRAINT FK_RECEV_REC FOREIGN KEY (RECOMMENDATION_ID)
        REFERENCES {schema}.RECOMMENDATIONS (RECOMMENDATION_ID) ON DELETE CASCADE,
    CONSTRAINT FK_RECEV_EVIDENCE FOREIGN KEY (INVESTIGATION_ID, COMPLAINT_ID)
        REFERENCES {schema}.INVESTIGATION_EVIDENCE (INVESTIGATION_ID, COMPLAINT_ID) ON DELETE CASCADE
);

CREATE TABLE {schema}.REVIEW_DECISIONS (
    DECISION_ID       BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    RECOMMENDATION_ID BIGINT        NOT NULL,
    REVIEWER          VARCHAR(64)   NOT NULL,
    DECISION          VARCHAR(16)   NOT NULL,
    COMMENT           VARCHAR(2000),
    DECIDED_AT        TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_REVIEW_DECISIONS PRIMARY KEY (DECISION_ID),
    CONSTRAINT FK_DECISION_REC FOREIGN KEY (RECOMMENDATION_ID)
        REFERENCES {schema}.RECOMMENDATIONS (RECOMMENDATION_ID) ON DELETE CASCADE,
    CONSTRAINT CK_DECISION CHECK (DECISION IN ('APPROVED','REJECTED','NEEDS_INFO'))
);

-- At most one decision per recommendation: the database backstop against double review.
CREATE UNIQUE INDEX {schema}.UX_DECISIONS_REC ON {schema}.REVIEW_DECISIONS (RECOMMENDATION_ID);

CREATE TABLE {schema}.AUDIT_LOG (
    AUDIT_ID          BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    INVESTIGATION_ID  BIGINT,
    ACTOR_TYPE        VARCHAR(16)   NOT NULL,
    ACTOR_ID          VARCHAR(64)   NOT NULL,
    ACTION            VARCHAR(64)   NOT NULL,
    TOOL_NAME         VARCHAR(64),
    INPUT_JSON        VARCHAR(4000),
    OUTPUT_SUMMARY    VARCHAR(4000),
    SUCCESS           SMALLINT      NOT NULL DEFAULT 1,
    CREATED_AT        TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_AUDIT_LOG PRIMARY KEY (AUDIT_ID),
    CONSTRAINT CK_AUDIT_ACTOR CHECK (ACTOR_TYPE IN ('USER','AGENT','SYSTEM')),
    CONSTRAINT CK_AUDIT_SUCCESS CHECK (SUCCESS IN (0,1))
);

CREATE INDEX {schema}.IX_AUDIT_INV_TIME ON {schema}.AUDIT_LOG (INVESTIGATION_ID, CREATED_AT);
