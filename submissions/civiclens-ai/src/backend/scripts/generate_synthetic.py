"""Generate the deterministic SYNTHETIC demonstration dataset.

All records are fictional and are written with ``is_synthetic: true``. The coordinates
are scattered around a fictional demo area so hotspot clusters are visible.

Usage:  python scripts/generate_synthetic.py
"""

import json
import random

import _bootstrap

OUT = _bootstrap.SUBMISSION_DIR / "data" / "synthetic" / "complaints_demo.json"
CENTER = (27.4924, 77.6737)  # demo area centre (data is fictional)
WARDS = ["Ward 1", "Ward 2", "Ward 3", "Ward 4", "Ward 5"]
TEMPLATES = {
    "POTHOLE": [
        "Deep pothole on main road",
        "Pothole causing two-wheeler accidents",
        "Large pothole near bus stop",
    ],
    "STREETLIGHT": [
        "Streetlight not working",
        "Street lamp flickering all night",
        "Dark stretch, lights off",
    ],
    "WATER_LEAK": [
        "Water pipeline leaking",
        "Burst water main flooding lane",
        "Continuous leak from supply pipe",
    ],
    "GARBAGE": [
        "Garbage not collected for days",
        "Overflowing waste bin",
        "Dumped garbage blocking footpath",
    ],
    "DRAINAGE": ["Blocked drain causing waterlogging", "Open drain overflowing", "Stagnant water after rain"],
    "SEWAGE": ["Sewage overflow on street", "Manhole overflowing with sewage"],
    "TRAFFIC_SIGNAL": ["Traffic signal not working", "Signal timer stuck on red"],
}
# Planted clusters (category, lat offset, lon offset, count) to create hotspots.
CLUSTERS = [("POTHOLE", 0.004, 0.003, 9), ("WATER_LEAK", -0.006, 0.008, 7), ("GARBAGE", 0.010, -0.007, 6)]


def main(seed: int = 2026) -> None:
    rng = random.Random(seed)  # noqa: S311 - deterministic demo data, not security-related
    rows = []

    def add(category: str, lat: float, lon: float) -> None:
        title = rng.choice(TEMPLATES[category])
        rows.append(
            {
                "external_ref": f"SYN-{len(rows) + 1:04d}",
                "category": category,
                "title": title,
                "description": f"[SYNTHETIC] {title}. Reported by a fictional resident for demo purposes.",
                "latitude": round(lat, 6),
                "longitude": round(lon, 6),
                "ward": rng.choice(WARDS),
                "severity": rng.randint(1, 5),
                "days_ago": rng.randint(0, 28),
                "hour": rng.randint(6, 22),
                "source": "SYNTHETIC",
                "is_synthetic": True,
            }
        )

    for category, dlat, dlon, count in CLUSTERS:
        for _ in range(count):
            add(
                category,
                CENTER[0] + dlat + rng.uniform(-0.0012, 0.0012),
                CENTER[1] + dlon + rng.uniform(-0.0012, 0.0012),
            )
    for _ in range(30):
        add(
            rng.choice(list(TEMPLATES)),
            CENTER[0] + rng.uniform(-0.03, 0.03),
            CENTER[1] + rng.uniform(-0.03, 0.03),
        )

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        json.dumps(
            {
                "_notice": "SYNTHETIC DEMONSTRATION DATA. All complaints are fictional and generated by "
                "scripts/generate_synthetic.py (seed 2026). Not real citizen reports.",
                "records": rows,
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(rows)} synthetic records to {OUT}")


if __name__ == "__main__":
    main()
