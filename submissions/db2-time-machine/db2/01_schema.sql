-- Db2 Time Machine schema. Statements are separated by lines containing only "--#".
-- Run inside schema TIMEMACHINE (the CLI creates it and sets CURRENT SCHEMA).

CREATE TABLE PRODUCTS (
    PRODUCT_ID  INTEGER       NOT NULL PRIMARY KEY,
    NAME        VARCHAR(100)  NOT NULL,
    CATEGORY    VARCHAR(50)   NOT NULL,
    LIST_PRICE  DECIMAL(10,2) NOT NULL
)
--#
CREATE TABLE ORDERS (
    ORDER_ID    INTEGER       NOT NULL PRIMARY KEY,
    CUSTOMER    VARCHAR(100)  NOT NULL,
    ORDER_DATE  DATE          NOT NULL
)
--#
-- The business table. SYS_START / SYS_END / TRANS_ID are maintained by Db2 itself
-- (system-period temporal table). CHANGED_BY is filled by triggers below.
CREATE TABLE ORDER_ITEMS (
    ITEM_ID     INTEGER       NOT NULL PRIMARY KEY,
    ORDER_ID    INTEGER       NOT NULL,
    PRODUCT_ID  INTEGER       NOT NULL,
    QUANTITY    INTEGER       NOT NULL,
    UNIT_PRICE  DECIMAL(10,2) NOT NULL,
    CHANGED_BY  VARCHAR(128)  NOT NULL DEFAULT 'unknown',
    SYS_START   TIMESTAMP(12) NOT NULL GENERATED ALWAYS AS ROW BEGIN,
    SYS_END     TIMESTAMP(12) NOT NULL GENERATED ALWAYS AS ROW END,
    TRANS_ID    TIMESTAMP(12) NOT NULL GENERATED ALWAYS AS TRANSACTION START ID,
    PERIOD SYSTEM_TIME (SYS_START, SYS_END)
)
--#
CREATE TABLE ORDER_ITEMS_HISTORY LIKE ORDER_ITEMS
--#
ALTER TABLE ORDER_ITEMS ADD VERSIONING USE HISTORY TABLE ORDER_ITEMS_HISTORY
--#
CREATE INDEX IX_OI_PRODUCT ON ORDER_ITEMS (PRODUCT_ID)
--#
-- "Who changed it": record the application user (set with WLM_SET_CLIENT_INFO) or the session user.
CREATE TRIGGER TRG_OI_INS NO CASCADE BEFORE INSERT ON ORDER_ITEMS
    REFERENCING NEW AS N FOR EACH ROW MODE DB2SQL
BEGIN ATOMIC
    SET N.CHANGED_BY = COALESCE(NULLIF(TRIM(CURRENT CLIENT_USERID), ''), SESSION_USER);
END
--#
CREATE TRIGGER TRG_OI_UPD NO CASCADE BEFORE UPDATE ON ORDER_ITEMS
    REFERENCING NEW AS N FOR EACH ROW MODE DB2SQL
BEGIN ATOMIC
    SET N.CHANGED_BY = COALESCE(NULLIF(TRIM(CURRENT CLIENT_USERID), ''), SESSION_USER);
END
--#
-- Deleted rows only survive in the history table, which does not record the deleting user.
CREATE TABLE ROW_DELETE_LOG (
    LOG_ID      INTEGER       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ITEM_ID     INTEGER       NOT NULL,
    DELETED_BY  VARCHAR(128)  NOT NULL,
    DELETED_AT  TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP
)
--#
CREATE TRIGGER TRG_OI_DEL AFTER DELETE ON ORDER_ITEMS
    REFERENCING OLD AS O FOR EACH ROW MODE DB2SQL
BEGIN ATOMIC
    INSERT INTO ROW_DELETE_LOG (ITEM_ID, DELETED_BY)
    VALUES (O.ITEM_ID, COALESCE(NULLIF(TRIM(CURRENT CLIENT_USERID), ''), SESSION_USER));
END
--#
-- Last known-good KPI values, like a dashboard's nightly snapshot.
CREATE TABLE KPI_SNAPSHOTS (
    PRODUCT_ID   INTEGER        NOT NULL,
    REVENUE      DECIMAL(14,2)  NOT NULL,
    SNAPSHOT_TS  TIMESTAMP      NOT NULL
)
--#
CREATE TABLE AUDIT_LOG (
    LOG_ID      INTEGER       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    RUN_ID      VARCHAR(32)   NOT NULL,
    SEQ         INTEGER       NOT NULL,
    AGENT       VARCHAR(20)   NOT NULL,
    ACTION      VARCHAR(120)  NOT NULL,
    SQL_TEXT    VARCHAR(1800),
    ROW_COUNT   INTEGER,
    LATENCY_MS  DECIMAL(10,1),
    OUTCOME     VARCHAR(120)  NOT NULL DEFAULT 'ok',
    DETAIL      VARCHAR(800),
    CREATED_AT  TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP
)
--#
CREATE INDEX IX_AUDIT_RUN ON AUDIT_LOG (RUN_ID, SEQ)
--#
CREATE TABLE INCIDENT_REPORTS (
    RUN_ID        VARCHAR(32)   NOT NULL PRIMARY KEY,
    QUESTION      VARCHAR(500)  NOT NULL,
    PRODUCT_NAME  VARCHAR(100),
    STATUS        VARCHAR(20)   NOT NULL,
    ROOT_CAUSE    VARCHAR(40),
    ACTOR         VARCHAR(200),
    IMPACT        VARCHAR(40),
    CREATED_AT    TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    REPORT_JSON   CLOB(1M)      NOT NULL
)
