"""Run the evaluation and write the report.

    python -m asof.eval --split dev
    python -m asof.eval --split test                       # frozen 40-case airline split
    python -m asof.eval --split bank-test                  # frozen 26-case bank split
    python -m asof.eval --split escalation-test            # frozen 33-case split, both domains
    LLM_TIMEOUT_S=180 python -m asof.eval --split test --provider ollama

Runs against its own schema (ASOF_EVAL), with a fresh ledger each run, so evaluation never
touches the demo ledger. Writes docs/eval/<split>__<provider>__<model>.json and rebuilds
docs/eval_results.md from every result file there.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from datetime import UTC, date, datetime
from typing import Any

from langchain_core.embeddings import Embeddings

from .. import db, schema, seed
from ..config import PROJECT_ROOT, Settings, get_settings
from ..domains import domain_for
from ..embeddings import get_embeddings
from ..gate import Gate, GateRequest
from ..llm import build_llm
from . import EVAL_SCHEMA, FROZEN, SPLIT_DOC, SPLITS, Case, CountingLLM, load_cases, score, split_sha256, summarize

OUT_DIR = PROJECT_ROOT / "docs" / "eval"
REPORT = PROJECT_ROOT / "docs" / "eval_results.md"
CATEGORY_ORDER = ["supported", "contradicted_numbers", "contradicted_eligibility", "date_boundary", "not_covered",
                  "counts", "multi_claim", "prompt_injection", "extractor_injection", "control"]


def prepare(settings: Settings, embeddings: Embeddings) -> None:
    """A fresh ASOF_EVAL schema for every run: same DDL, seed data and grants as setup, empty ledger."""
    with db.connection(settings, "admin") as conn:
        schema.drop(conn, EVAL_SCHEMA)
        schema.install(conn, EVAL_SCHEMA)
        seed.seed_policy(conn, embeddings, EVAL_SCHEMA)
        seed.seed_chain_head(conn, EVAL_SCHEMA)
        seed.seed_published_answers(conn, EVAL_SCHEMA)
        seed.seed_faq(conn, embeddings, EVAL_SCHEMA)
        schema.apply_grants(conn, settings.asof_app_user, settings.asof_editor_user, EVAL_SCHEMA)


def _git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=PROJECT_ROOT, capture_output=True,
                              text=True, timeout=10).stdout.strip() or "unknown"
    except Exception:  # noqa: BLE001
        return "unknown"


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def _of(num: int, den: int) -> str:
    return "n/a" if den == 0 else f"{100 * num / den:.1f}% ({num} of {den})"


def render_report(results: list[dict[str, Any]]) -> str:
    lines = ["# Evaluation results", "",
             "Generated by `python -m asof.eval`. Every number below comes from a recorded run in "
             "[docs/eval/](eval/); nothing is hand-edited.", "",
             "- **False-allow rate**: drafts that are wrong for their date but were released as PASS, over all wrong "
             "drafts. The safety number.",
             "- **False-block rate**: correct drafts that were rewritten or escalated, over all correct drafts.",
             "- **Safe**: the decision was one of the case's acceptable outcomes (for a wrong draft, CORRECTED or "
             "ESCALATED; for a correct draft, PASS). **Ideal**: exactly the expected decision.",
             "- **Citation accuracy**: the key claim was checked against the right clause version for the date.",
             "- **Rule check flagged**: wrong drafts in which the deterministic rule check found a mismatch with "
             "`RULE_JSON` in the draft itself, whatever the judge said.",
             "- **Rule overrides**: claims the deterministic rule check turned from the judge's SUPPORTED to "
             "CONTRADICTED.",
             "", "The airline test split (40 cases) was committed in `81b5b69` before any run and is frozen: the runner "
             "refuses to run it if its SHA-256 changes. The dev split (20 cases) holds the scenarios used while building. "
             "The bank splits (Fernhollow Bank, the second fictional domain) work the same way: `bank-test` (26 cases) "
             "was committed and pinned before its first run, and `bank-dev` (12 cases) is for iterating. That first bank run "
             "found a gap in clause MTF-003's rule data, which was then fixed, so bank runs after `6d928b7` are not blind. "
             "`extractor-test` (10 cases, both documents) holds drafts that try to talk the claim extractor out of a wrong "
             "claim; it was pinned before its first run at `a7bece1`. `bank-test2` (22 new bank cases) restores a blind bank "
             "measurement: it was pinned before its first run and nothing was changed because of it. "
             "`escalation-test` (33 new cases, both documents) targets the known causes of holding a draft that could "
             "have been corrected or passed; it was pinned before its first run and before any change meant to reduce "
             "those escalations, which were tuned on `escalation-dev` (14 cases) only. `situation-test` (12 new cases, both "
             "documents) holds drafts whose premise about the customer contradicts or restates what the customer said; it "
             "was written after the change that shows the judge the question, and pinned before its first run. That run released "
             "3 of 7 drafts whose premise contradicted the customer, which led to the situation_conflict check; "
             "`situation-test2` (12 new cases) was then pinned before its first run as the blind measure. When a later run of "
             "it released a draft whose premise the extractor had turned into a general rule, `situation-test3` (20 new "
             "cases) was pinned before any change meant to fix that. `list-test` (16 new cases) holds drafts that claim a "
             "relation or document qualifies when the clause's list leaves it out; it was pinned after the watsonx.ai run "
             "released T20 and before any change meant to catch that. Runs marked "
             "\"(ablation: current-policy)\" check every case against the policy in force on 7 Nov 2026 instead of the case's "
             "own date: AsOf's own check standing in for one that only knows the current policy, scored "
             "against the same labels.", ""]
    order = {"test": 0, "escalation-test": 1, "situation-test3": 2, "list-test": 3, "situation-test2": 4,
             "situation-test": 5, "bank-test2": 6, "bank-test": 7, "extractor-test": 8, "dev": 9, "bank-dev": 10,
             "escalation-dev": 11, "situation-dev": 12, "list-dev": 13}
    providers = {"openrouter": 0, "openai_compatible": 1, "ollama": 2, "watsonx": 3}  # the default provider first
    newest_first = sorted(results, key=lambda r: r["started_at"], reverse=True)
    for r in sorted(newest_first, key=lambda r: (order.get(r["split"], 9), providers.get(r["provider"], 9), r["model"])):
        summary = summarize(r["records"])  # recomputed from the per-case records, not the stored rounding
        o = summary["overall"]
        lines += [f"## {r['split']} split: {r['provider']} `{r['model']}`, run {r['started_at'][:10]} at `{r['git_commit']}`", "",
                  f"Run {r['started_at']} at commit `{r['git_commit']}`, prompt version `{r['prompt_version']}`, "
                  f"{o['n']} cases, cases file sha256 `{r['cases_sha256'][:16]}...`, wall time {r['wall_time_s']} s.", "",
                  "| Metric | Value |", "|---|---|",
                  f"| False-allow rate | **{_of(o['false_allows'], o['wrong_drafts'])}** |",
                  f"| False-block rate | {_of(o['false_blocks'], o['correct_drafts'])} |",
                  f"| Safe decisions | {_pct(o['safe_rate'])} |",
                  f"| Ideal decisions | {_pct(o['ideal_rate'])} |",
                  f"| Escalated / corrected | {_pct(o['escalation_rate'])} / {_pct(o['correction_rate'])} |",
                  f"| Citation accuracy | {_pct(o['citation_accuracy'])} |",
                  f"| Rule check flagged | {o['rule_flagged']} of {o['wrong_drafts']} wrong drafts |",
                  f"| Rule overrides | {o['rule_overrides']} |",
                  f"| Errors (failed closed) | {o['errors']} |",
                  f"| Latency p50 / p90 | {o['latency_p50_ms'] / 1000:.1f} s / {o['latency_p90_ms'] / 1000:.1f} s |",
                  f"| LLM calls per case | {o['llm_calls_mean']} |", "",
                  "| Category | n | False allow | False block | Safe | Ideal | Citation |", "|---|---|---|---|---|---|---|"]
        cats = summary["by_category"]
        for c in [c for c in CATEGORY_ORDER if c in cats] + [c for c in cats if c not in CATEGORY_ORDER]:
            b = cats[c]
            lines.append(f"| {c} | {b['n']} | {_pct(b['false_allow_rate'])} | {_pct(b['false_block_rate'])} | "
                         f"{_pct(b['safe_rate'])} | {_pct(b['ideal_rate'])} | {_pct(b['citation_accuracy'])} |")
        misses = [x for x in r["records"] if not x["ideal"]]
        if misses:
            lines += ["", "Cases that did not get the ideal decision:", ""]
            for x in misses:
                lines.append(f"- `{x['id']}` ({x['category']}, {x['as_of']}): expected {x['expected']}, got "
                             f"**{x['decision']}** ({x['reason']})" + (" **FALSE ALLOW**" if x["false_allow"] else "")
                             + (" (false block)" if x["false_block"] else ""))
                for cl in x["claims"][:6]:
                    lines.append(f"  - {cl}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# The ablation's "today": every case is checked against the policy in force on this date, the day it was run.
ABLATION_DATE = date(2026, 11, 7)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="python -m asof.eval")
    p.add_argument("--split", choices=list(SPLITS), required=True)
    p.add_argument("--provider", choices=["openrouter", "ollama", "openai_compatible", "watsonx"])
    p.add_argument("--model")
    p.add_argument("--workers", type=int, help="parallel cases (default 4 hosted, 1 for ollama)")
    p.add_argument("--limit", type=int, help="run only the first N cases (smoke test; not written)")
    p.add_argument("--ablation", choices=["current-policy"],
                   help="current-policy: check every case against the policy in force on 7 Nov 2026 instead of the "
                        "case's own date: AsOf's own check standing in for one that only knows the current policy "
                        "(scored against the same labels)")
    args = p.parse_args(argv)

    if args.split in FROZEN and split_sha256(args.split) != FROZEN[args.split]:
        print(f"Refusing to run: the frozen {args.split} split has changed since it was pinned.")
        return 2
    domain = domain_for(SPLIT_DOC[args.split])
    settings = get_settings()
    provider = args.provider or settings.llm_provider
    if provider == "replay":  # the frozen cases are not recorded, and a replay would not measure a model anyway
        print("Refusing to run: eval measures a live model; set --provider or LLM_PROVIDER to one (not replay).")
        return 2
    llm = build_llm(settings, provider=provider, model=args.model, fallback=False)  # measure one provider only
    workers = args.workers or (1 if provider == "ollama" else 4)
    cases = load_cases(args.split)[: args.limit] if args.limit else load_cases(args.split)
    embeddings = get_embeddings(settings.embedding_model)
    prepare(settings, embeddings)
    print(f"Running {len(cases)} {args.split} cases with {llm.info}, {workers} worker(s), schema {EVAL_SCHEMA}", flush=True)

    connections = db.ConnectionPool(settings, "app")  # as the API runs; the workers share it

    def one(case: Case) -> dict[str, Any]:
        counting = CountingLLM(llm)
        gate = Gate(counting, embeddings, connections.connect, EVAL_SCHEMA)
        as_of = ABLATION_DATE if args.ablation == "current-policy" else case.as_of
        result = gate.check(GateRequest(case.question, case.draft, as_of, case.doc_id or domain.doc_id, "eval"))
        rec = score(case, result) | {"llm_calls": counting.calls, "input_tokens": counting.input_tokens,
                                     "output_tokens": counting.output_tokens}
        flag = "ok  " if rec["safe"] else "MISS"
        print(f"  {flag} {case.id} {case.category:<24} expected {case.expected:<9} got {rec['decision']:<9} "
              f"{rec['latency_ms'] / 1000:5.1f}s" + ("  FALSE ALLOW" if rec["false_allow"] else ""), flush=True)
        return rec

    started = datetime.now(UTC)
    t0 = time.monotonic()
    with ThreadPoolExecutor(max_workers=workers) as pool:
        records = list(pool.map(one, cases))
    wall = round(time.monotonic() - t0, 1)
    summary = summarize(records)
    o = summary["overall"]
    print(f"\nfalse-allow {_pct(o['false_allow_rate'])}  false-block {_pct(o['false_block_rate'])}  "
          f"safe {_pct(o['safe_rate'])}  ideal {_pct(o['ideal_rate'])}  citation {_pct(o['citation_accuracy'])}  "
          f"p50 {o['latency_p50_ms'] / 1000:.1f}s  wall {wall}s  "
          f"tokens {sum(r['input_tokens'] for r in records)} in / {sum(r['output_tokens'] for r in records)} out")
    with db.connection(settings, "app") as conn:
        from ..ledger import verify_chain
        chain = verify_chain(conn, EVAL_SCHEMA)
    print(f"eval ledger chain: {chain.status} ({chain.checked} rows)")
    if args.limit:
        print("(--limit run: results not written)")
        return 0

    prompt_versions = " + ".join(sorted({domain_for(c.doc_id or domain.doc_id).prompt_version for c in cases}))
    split_label = f"{args.split} (ablation: {args.ablation})" if args.ablation else args.split
    result = {"split": split_label, "provider": provider, "model": llm.model_name,
              "started_at": started.isoformat(timespec="seconds"),
              "git_commit": _git_commit(), "prompt_version": prompt_versions, "cases_sha256": split_sha256(args.split),
              "workers": workers, "wall_time_s": wall, "ledger_chain": chain.status, "summary": summary, "records": records}
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    slug = re.sub(r"[^A-Za-z0-9.]+", "-", llm.model_name).strip("-")
    # One file per run (commit in the name), so a new run sits next to the earlier ones.
    stem = f"{args.split}-ablation-{args.ablation}" if args.ablation else args.split
    out = OUT_DIR / f"{stem}__{provider}__{slug}__{result['git_commit']}.json"
    out.write_text(json.dumps(result, indent=1, default=str) + "\n", encoding="utf-8")
    all_results = [json.loads(f.read_text(encoding="utf-8")) for f in sorted(OUT_DIR.glob("*.json"))]
    REPORT.write_text(render_report(all_results), encoding="utf-8")
    print(f"wrote {out.relative_to(PROJECT_ROOT)} and {REPORT.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
