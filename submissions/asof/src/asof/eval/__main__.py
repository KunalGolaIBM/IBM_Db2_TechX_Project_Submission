"""Run the evaluation and write the report.

    python -m asof.eval --split dev
    python -m asof.eval --split test                       # frozen 40-case split
    LLM_TIMEOUT_S=180 python -m asof.eval --split test --provider ollama

Runs against its own schema (ASOF_EVAL), with a fresh ledger each run, so evaluation never
touches the demo ledger. Writes docs/eval/<split>__<provider>__<model>.json and rebuilds
docs/eval_results.md from every result file there.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
from pathlib import Path

from .. import db, schema, seed
from ..config import PROJECT_ROOT, get_settings
from ..embeddings import get_embeddings
from ..gate import Gate, GateRequest
from ..llm import build_llm
from ..prompts import PROMPT_VERSION
from . import EVAL_SCHEMA, FROZEN_TEST_SHA256, CountingLLM, load_cases, score, split_sha256, summarize

OUT_DIR = PROJECT_ROOT / "docs" / "eval"
REPORT = PROJECT_ROOT / "docs" / "eval_results.md"
CATEGORY_ORDER = ["supported", "contradicted_numbers", "contradicted_eligibility", "date_boundary", "not_covered",
                  "counts", "multi_claim", "prompt_injection"]


def prepare(settings, embeddings) -> None:
    """Fresh ledger in ASOF_EVAL; policy, help-centre answers and FAQ seeded once."""
    with db.connection(settings, "admin") as conn:
        if schema.table_exists(conn, EVAL_SCHEMA, "ANSWER_LEDGER"):
            schema.reset_ledger(conn, EVAL_SCHEMA)
        schema.install(conn, EVAL_SCHEMA)
        seed.seed_policy(conn, embeddings, EVAL_SCHEMA)
        seed.seed_chain_head(conn, EVAL_SCHEMA)
        seed.seed_published_answers(conn, EVAL_SCHEMA)
        seed.seed_faq(conn, embeddings, EVAL_SCHEMA)
        schema.apply_grants(conn, settings.asof_app_user, settings.asof_editor_user, EVAL_SCHEMA)


def _git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=PROJECT_ROOT, capture_output=True,
                              text=True, timeout=10).stdout.strip() or "unknown"
    except Exception:  # noqa: BLE001
        return "unknown"


def _pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def _of(num: int, den: int) -> str:
    return "n/a" if den == 0 else f"{100 * num / den:.1f}% ({num} of {den})"


def render_report(results: list[dict]) -> str:
    lines = ["# Evaluation results", "",
             "Generated by `python -m asof.eval`. Every number below comes from a recorded run in "
             "[docs/eval/](eval/); nothing is hand-edited.", "",
             "- **False-allow rate**: drafts that are wrong for their date but were released as PASS, over all wrong "
             "drafts. The safety number.",
             "- **False-block rate**: correct drafts that were rewritten or escalated, over all correct drafts.",
             "- **Safe**: the decision was one of the case's acceptable outcomes (for a wrong draft, CORRECTED or "
             "ESCALATED; for a correct draft, PASS). **Ideal**: exactly the expected decision.",
             "- **Citation accuracy**: the key claim was checked against the right clause version for the date.",
             "- **Rule overrides**: claims the deterministic rule check turned from the judge's SUPPORTED to "
             "CONTRADICTED.",
             "", "The test split (40 cases) was committed in `81b5b69` before any run and is frozen: the runner refuses "
             "to run it if its SHA-256 changes. The dev split (20 cases) holds the scenarios used while building.", ""]
    order = {"test": 0, "dev": 1}
    providers = {"openrouter": 0, "openai_compatible": 1, "ollama": 2}  # the default provider first
    for r in sorted(results, key=lambda r: (order.get(r["split"], 9), providers.get(r["provider"], 9), r["model"])):
        summary = summarize(r["records"])  # recomputed from the per-case records, not the stored rounding
        o = summary["overall"]
        lines += [f"## {r['split']} split: {r['provider']} `{r['model']}`", "",
                  f"Run {r['started_at']} at commit `{r['git_commit']}`, prompt version `{r['prompt_version']}`, "
                  f"{o['n']} cases, cases file sha256 `{r['cases_sha256'][:16]}...`, wall time {r['wall_time_s']} s.", "",
                  "| Metric | Value |", "|---|---|",
                  f"| False-allow rate | **{_of(o['false_allows'], o['wrong_drafts'])}** |",
                  f"| False-block rate | {_of(o['false_blocks'], o['correct_drafts'])} |",
                  f"| Safe decisions | {_pct(o['safe_rate'])} |",
                  f"| Ideal decisions | {_pct(o['ideal_rate'])} |",
                  f"| Escalated / corrected | {_pct(o['escalation_rate'])} / {_pct(o['correction_rate'])} |",
                  f"| Citation accuracy | {_pct(o['citation_accuracy'])} |",
                  f"| Rule overrides | {o['rule_overrides']} |",
                  f"| Errors (failed closed) | {o['errors']} |",
                  f"| Latency p50 / p90 | {o['latency_p50_ms'] / 1000:.1f} s / {o['latency_p90_ms'] / 1000:.1f} s |",
                  f"| LLM calls per case | {o['llm_calls_mean']} |", "",
                  "| Category | n | False allow | False block | Safe | Ideal | Citation |", "|---|---|---|---|---|---|---|"]
        cats = summary["by_category"]
        for c in [c for c in CATEGORY_ORDER if c in cats] + [c for c in cats if c not in CATEGORY_ORDER]:
            b = cats[c]
            lines.append(f"| {c} | {b['n']} | {_pct(b['false_allow_rate'])} | {_pct(b['false_block_rate'])} | "
                         f"{_pct(b['safe_rate'])} | {_pct(b['ideal_rate'])} | {_pct(b['citation_accuracy'])} |")
        misses = [x for x in r["records"] if not x["ideal"]]
        if misses:
            lines += ["", "Cases that did not get the ideal decision:", ""]
            for x in misses:
                lines.append(f"- `{x['id']}` ({x['category']}, {x['as_of']}): expected {x['expected']}, got "
                             f"**{x['decision']}** ({x['reason']})" + (" **FALSE ALLOW**" if x["false_allow"] else "")
                             + (" (false block)" if x["false_block"] else ""))
                for cl in x["claims"][:6]:
                    lines.append(f"  - {cl}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="python -m asof.eval")
    p.add_argument("--split", choices=["dev", "test"], required=True)
    p.add_argument("--provider", choices=["openrouter", "ollama", "openai_compatible"])
    p.add_argument("--model")
    p.add_argument("--workers", type=int, help="parallel cases (default 4 hosted, 1 for ollama)")
    p.add_argument("--limit", type=int, help="run only the first N cases (smoke test; not written)")
    args = p.parse_args(argv)

    if args.split == "test" and split_sha256("test") != FROZEN_TEST_SHA256:
        print("Refusing to run: the frozen test split has changed since commit 81b5b69.")
        return 2
    settings = get_settings()
    provider = args.provider or settings.llm_provider
    llm = build_llm(settings, provider=provider, model=args.model)
    workers = args.workers or (1 if provider == "ollama" else 4)
    cases = load_cases(args.split)[: args.limit] if args.limit else load_cases(args.split)
    embeddings = get_embeddings(settings.embedding_model)
    prepare(settings, embeddings)
    print(f"Running {len(cases)} {args.split} cases with {llm.info}, {workers} worker(s), schema {EVAL_SCHEMA}", flush=True)

    def one(case):
        counting = CountingLLM(llm)
        gate = Gate(counting, embeddings, lambda: db.connect(settings, "app"), EVAL_SCHEMA)
        result = gate.check(GateRequest(case.question, case.draft, case.as_of, "AURELIA-CSP", "eval"))
        rec = score(case, result) | {"llm_calls": counting.calls}
        flag = "ok  " if rec["safe"] else "MISS"
        print(f"  {flag} {case.id} {case.category:<24} expected {case.expected:<9} got {rec['decision']:<9} "
              f"{rec['latency_ms'] / 1000:5.1f}s" + ("  FALSE ALLOW" if rec["false_allow"] else ""), flush=True)
        return rec

    started = datetime.now(timezone.utc)
    t0 = time.monotonic()
    with ThreadPoolExecutor(max_workers=workers) as pool:
        records = list(pool.map(one, cases))
    wall = round(time.monotonic() - t0, 1)
    summary = summarize(records)
    o = summary["overall"]
    print(f"\nfalse-allow {_pct(o['false_allow_rate'])}  false-block {_pct(o['false_block_rate'])}  "
          f"safe {_pct(o['safe_rate'])}  ideal {_pct(o['ideal_rate'])}  citation {_pct(o['citation_accuracy'])}  "
          f"p50 {o['latency_p50_ms'] / 1000:.1f}s  wall {wall}s")
    with db.connection(settings, "app") as conn:
        from ..ledger import verify_chain
        chain = verify_chain(conn, EVAL_SCHEMA)
    print(f"eval ledger chain: {chain.status} ({chain.checked} rows)")
    if args.limit:
        print("(--limit run: results not written)")
        return 0

    result = {"split": args.split, "provider": provider, "model": llm.model_name, "started_at": started.isoformat(timespec="seconds"),
              "git_commit": _git_commit(), "prompt_version": PROMPT_VERSION, "cases_sha256": split_sha256(args.split),
              "workers": workers, "wall_time_s": wall, "ledger_chain": chain.status, "summary": summary, "records": records}
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    slug = re.sub(r"[^A-Za-z0-9.]+", "-", llm.model_name).strip("-")
    out = OUT_DIR / f"{args.split}__{provider}__{slug}.json"
    out.write_text(json.dumps(result, indent=1, default=str) + "\n", encoding="utf-8")
    all_results = [json.loads(f.read_text(encoding="utf-8")) for f in sorted(OUT_DIR.glob("*.json"))]
    REPORT.write_text(render_report(all_results), encoding="utf-8")
    print(f"wrote {out.relative_to(PROJECT_ROOT)} and {REPORT.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
