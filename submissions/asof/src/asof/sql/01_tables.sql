  TITLE       VARCHAR(200) NOT NULL,
  OWNER_TEAM  VARCHAR(100),
  SOURCE_NOTE VARCHAR(400),
  CONSTRAINT PK_POLICY_DOC PRIMARY KEY (DOC_ID)
) IN ASOF_TS32K
