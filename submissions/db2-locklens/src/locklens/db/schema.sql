-- LockLens incident store. ${SCHEMA} is substituted by the application (default LOCKLENS).
-- Statements are separated by semicolons. Re-running is safe: "already exists" is ignored.

CREATE SCHEMA ${SCHEMA};

CREATE TABLE ${SCHEMA}.LOCK_INCIDENTS (
    INCIDENT_ID      BIGINT        NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1),
    INCIDENT_KEY     VARCHAR(160)  NOT NULL,
    OPEN_KEY         VARCHAR(160),
    STATUS           VARCHAR(12)   NOT NULL DEFAULT 'OPEN',
    SEVERITY         VARCHAR(10)   NOT NULL,
    CATEGORY         VARCHAR(40)   NOT NULL,
    FINDING_TYPE     VARCHAR(40)   NOT NULL,
    TITLE            VARCHAR(300)  NOT NULL,
    DETECTED_AT      TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    LAST_SEEN_AT     TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    RESOLVED_AT      TIMESTAMP,
    OBSERVATIONS     INTEGER       NOT NULL DEFAULT 1,
    BLOCKER_HANDLE   BIGINT,
    BLOCKER_INFO     VARCHAR(300),
    WAITER_HANDLES   VARCHAR(300),
    WAITER_INFO      VARCHAR(300),
    LOCK_DETAILS     VARCHAR(500),
    MAX_WAIT_SECONDS INTEGER,
    RESOLUTION_NOTE  VARCHAR(200),
    EXPLANATION      CLOB(64K),
    RECOMMENDATION   CLOB(64K),
    EVIDENCE         CLOB(64K),
    CONSTRAINT PK_LOCK_INCIDENTS PRIMARY KEY (INCIDENT_ID)
);

-- At most ONE open incident per key: OPEN_KEY is NULL once an incident is resolved, and
-- EXCLUDE NULL KEYS lets any number of resolved rows coexist.
CREATE UNIQUE INDEX ${SCHEMA}.UX_LOCK_INCIDENTS_OPEN ON ${SCHEMA}.LOCK_INCIDENTS (OPEN_KEY) EXCLUDE NULL KEYS;

CREATE INDEX ${SCHEMA}.IX_LOCK_INCIDENTS_DETECTED ON ${SCHEMA}.LOCK_INCIDENTS (DETECTED_AT);
