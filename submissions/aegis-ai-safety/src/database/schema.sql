-- AEGIS relational schema for IBM Db2 Community Edition 12.1.5
-- The AEGIS schema itself is created by database/init_db.py, which then sets
-- CURRENT SCHEMA and executes these statements. All types are Db2-native.
-- Indexes live in indexes.sql. Existing databases are upgraded by init_db.py.

CREATE TABLE DOCUMENTS (
    DOCUMENT_ID       INTEGER       NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    TITLE             VARCHAR(500)  NOT NULL,
    FILENAME          VARCHAR(255)  NOT NULL,
    CONTENT_HASH      CHAR(64)      NOT NULL,
    SOURCE_TYPE       VARCHAR(32)   NOT NULL,
    EXTERNAL_ID       VARCHAR(100),
    PROCESSING_STATUS VARCHAR(32)   NOT NULL DEFAULT 'READY',
    CREATED_AT        TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_DOCUMENTS PRIMARY KEY (DOCUMENT_ID),
    CONSTRAINT UQ_DOCUMENTS_HASH UNIQUE (CONTENT_HASH)
);

CREATE TABLE PASSAGES (
    PASSAGE_ID      INTEGER       NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    DOCUMENT_ID     INTEGER       NOT NULL,
    PASSAGE_TEXT    VARCHAR(4000) NOT NULL,
    PAGE_NUMBER     INTEGER,
    PASSAGE_INDEX   INTEGER       NOT NULL,
    CHAR_START      INTEGER,
    CHAR_END        INTEGER,
    CONSTRAINT PK_PASSAGES PRIMARY KEY (PASSAGE_ID),
    CONSTRAINT FK_PASSAGES_DOCUMENT FOREIGN KEY (DOCUMENT_ID)
        REFERENCES DOCUMENTS (DOCUMENT_ID) ON DELETE CASCADE
);

CREATE TABLE VERIFICATION_SESSIONS (
    SESSION_ID      INTEGER       NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    SUBMITTED_TEXT  VARCHAR(32672) NOT NULL,
    MODEL_PROVIDER  VARCHAR(120)  NOT NULL,
    STATUS          VARCHAR(32)   NOT NULL,
    ERROR_MESSAGE   VARCHAR(2000),
    CREATED_AT      TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    COMPLETED_AT    TIMESTAMP,
    DURATION_MS     INTEGER,
    CONSTRAINT PK_VERIFICATION_SESSIONS PRIMARY KEY (SESSION_ID)
);

CREATE TABLE CLAIMS (
    CLAIM_ID         INTEGER       NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    SESSION_ID       INTEGER       NOT NULL,
    ORIGINAL_CLAIM   VARCHAR(2000) NOT NULL,
    NORMALIZED_CLAIM VARCHAR(2000) NOT NULL,
    CLAIM_TYPE       VARCHAR(32)   NOT NULL,
    POSITION_START   INTEGER,
    POSITION_END     INTEGER,
    CONSTRAINT PK_CLAIMS PRIMARY KEY (CLAIM_ID),
    CONSTRAINT FK_CLAIMS_SESSION FOREIGN KEY (SESSION_ID)
        REFERENCES VERIFICATION_SESSIONS (SESSION_ID) ON DELETE CASCADE
);

CREATE TABLE VERIFICATION_RESULTS (
    RESULT_ID             INTEGER      NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    CLAIM_ID              INTEGER      NOT NULL,
    CLASSIFICATION        VARCHAR(32)  NOT NULL,
    EXPLANATION           VARCHAR(4000) NOT NULL,
    LIMITATIONS           VARCHAR(4000),
    NUMERICAL_ANALYSIS    VARCHAR(4000),
    VERIFICATION_METHOD   VARCHAR(100) NOT NULL,
    HUMAN_REVIEW_STATUS   VARCHAR(32)  NOT NULL DEFAULT 'PENDING',
    CREATED_AT            TIMESTAMP    NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_VERIFICATION_RESULTS PRIMARY KEY (RESULT_ID),
    CONSTRAINT UQ_RESULTS_CLAIM UNIQUE (CLAIM_ID),
    CONSTRAINT FK_RESULTS_CLAIM FOREIGN KEY (CLAIM_ID)
        REFERENCES CLAIMS (CLAIM_ID) ON DELETE CASCADE,
    CONSTRAINT CK_RESULTS_CLASSIFICATION CHECK (
        CLASSIFICATION IN ('SUPPORTED', 'CONTRADICTED', 'INSUFFICIENT_EVIDENCE', 'VERIFICATION_ERROR')
    )
);

CREATE TABLE EVIDENCE_LINKS (
    EVIDENCE_LINK_ID      INTEGER NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    RESULT_ID             INTEGER NOT NULL,
    PASSAGE_ID            INTEGER NOT NULL,
    EVIDENCE_RELATIONSHIP VARCHAR(32),
    RELEVANCE_SCORE       DOUBLE,
    CONSTRAINT PK_EVIDENCE_LINKS PRIMARY KEY (EVIDENCE_LINK_ID),
    CONSTRAINT UQ_EVIDENCE_LINK UNIQUE (RESULT_ID, PASSAGE_ID),
    CONSTRAINT FK_EVIDENCE_RESULT FOREIGN KEY (RESULT_ID)
        REFERENCES VERIFICATION_RESULTS (RESULT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_EVIDENCE_PASSAGE FOREIGN KEY (PASSAGE_ID)
        REFERENCES PASSAGES (PASSAGE_ID) ON DELETE CASCADE
);
