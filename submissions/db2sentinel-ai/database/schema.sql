-- ==============================================================================
-- IBM Db2 Schema Definition for Db2Sentinel AI
-- Target Database: SENTINELDB
-- Compatible with IBM Db2 Community Edition v11.5 / v12.1 and Db2 on Cloud
-- ==============================================================================

-- 1. SECURITY EVENTS TABLE: Normalized telemetry from Db2 audit & event monitors
CREATE TABLE SENTINEL_EVENTS (
    EVENT_ID            BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    EVENT_TYPE          VARCHAR(64) NOT NULL,
    USERNAME            VARCHAR(128) NOT NULL,
    SOURCE_IP           VARCHAR(45),
    DATABASE_NAME       VARCHAR(64) DEFAULT 'SENTINELDB',
    SQL_OPERATION       VARCHAR(32),
    OBJECT_NAME         VARCHAR(256),
    STATUS              VARCHAR(32) NOT NULL,
    EVENT_TIMESTAMP     TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    SEVERITY            VARCHAR(32) DEFAULT 'LOW',
    EVENT_SOURCE        VARCHAR(64) DEFAULT 'DB2_AUDIT_FACILITY',
    RAW_DETAILS         VARCHAR(4000)
);

-- 2. SECURITY ALERTS TABLE: Verified rule violations and anomalies
CREATE TABLE SENTINEL_ALERTS (
    ALERT_ID            BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    EVENT_ID            BIGINT,
    ALERT_NAME          VARCHAR(128) NOT NULL,
    DESCRIPTION         VARCHAR(1000) NOT NULL,
    SEVERITY            VARCHAR(32) NOT NULL,
    RISK_SCORE          DECIMAL(5,2) NOT NULL,
    STATUS              VARCHAR(32) DEFAULT 'OPEN',
    CREATED_AT          TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_ALERT_EVENT FOREIGN KEY (EVENT_ID) REFERENCES SENTINEL_EVENTS(EVENT_ID) ON DELETE SET NULL
);

-- 3. SECURITY INCIDENTS TABLE: Coordinated multi-event investigations
CREATE TABLE SENTINEL_INCIDENTS (
    INCIDENT_ID         VARCHAR(64) NOT NULL PRIMARY KEY,
    TITLE               VARCHAR(256) NOT NULL,
    DESCRIPTION         VARCHAR(2000),
    SEVERITY            VARCHAR(32) NOT NULL,
    RISK_SCORE          DECIMAL(5,2) NOT NULL,
    STATUS              VARCHAR(32) DEFAULT 'INVESTIGATING',
    ASSIGNED_TO         VARCHAR(128) DEFAULT 'LangGraph Supervisor',
    CREATED_AT          TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    UPDATED_AT          TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    AI_SUMMARY          VARCHAR(4000)
);

-- 4. AI INVESTIGATIONS TABLE: Agent-specific findings and evidence correlation
CREATE TABLE SENTINEL_INVESTIGATIONS (
    INVESTIGATION_ID    VARCHAR(64) NOT NULL PRIMARY KEY,
    INCIDENT_ID         VARCHAR(64) NOT NULL,
    AGENT_NAME          VARCHAR(64) NOT NULL,
    FINDINGS            VARCHAR(4000) NOT NULL,
    RECOMMENDATION      VARCHAR(2000),
    CONFIDENCE          DECIMAL(5,2) DEFAULT 0.90,
    CREATED_AT          TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_INV_INCIDENT FOREIGN KEY (INCIDENT_ID) REFERENCES SENTINEL_INCIDENTS(INCIDENT_ID) ON DELETE CASCADE
);

-- 5. RESPONSE APPROVALS TABLE: Human-in-the-loop governance sign-offs
CREATE TABLE SENTINEL_APPROVALS (
    APPROVAL_ID         VARCHAR(64) NOT NULL PRIMARY KEY,
    INCIDENT_ID         VARCHAR(64) NOT NULL,
    PROPOSED_ACTION     VARCHAR(512) NOT NULL,
    REQUESTED_BY        VARCHAR(128) DEFAULT 'Response Agent',
    APPROVAL_STATUS     VARCHAR(32) DEFAULT 'PENDING',
    REVIEWER            VARCHAR(128),
    REVIEWED_AT         TIMESTAMP,
    AUDIT_NOTES         VARCHAR(1000),
    CONSTRAINT FK_APP_INCIDENT FOREIGN KEY (INCIDENT_ID) REFERENCES SENTINEL_INCIDENTS(INCIDENT_ID) ON DELETE CASCADE
);

-- 6. AUDIT LOG TABLE: Tamper-evident execution trail of all system decisions
CREATE TABLE SENTINEL_AUDIT_LOG (
    LOG_ID              BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    ACTION_TAKEN        VARCHAR(256) NOT NULL,
    EXECUTED_BY         VARCHAR(128) NOT NULL,
    DB2_QUERY           VARCHAR(2000),
    EXECUTION_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    VERIFICATION_HASH   VARCHAR(128)
);
