--@
-- Idempotent on the content hash: saving a dataset that is already cached is a
-- no-op that returns the existing id.
CREATE PROCEDURE PORTPROOF.RECORD_DATASET (
  IN  P_SCHEMA_FP  VARCHAR(16),
  IN  P_NAME       VARCHAR(120),
  IN  P_ORIGIN     VARCHAR(12),
  IN  P_STRATEGY   VARCHAR(40),
  IN  P_TARGETS    VARCHAR(400),
  IN  P_PAYLOAD    CLOB(2M),
  IN  P_SHA        VARCHAR(64),
  OUT P_DATASET_ID INTEGER
)
LANGUAGE SQL
MODIFIES SQL DATA
BEGIN
  DECLARE V_ID INTEGER;
  -- The payload is parsed by the engine rather than trusted to be JSON. Db2
  -- 12.1.5 has no IS JSON predicate for a CHECK constraint (SQL0104N), so the
  -- one door into the table does the check: a payload without a "rows" object
  -- is refused here, whoever sent it.
  IF NOT JSON_EXISTS(P_PAYLOAD, '$.rows') THEN
    SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'dataset payload is not JSON with a rows object';
  END IF;
  SET V_ID = (SELECT DATASET_ID FROM PORTPROOF.DATASET WHERE CONTENT_SHA = P_SHA);
  IF V_ID IS NULL THEN
    INSERT INTO PORTPROOF.DATASET (SCHEMA_FP, NAME, ORIGIN, STRATEGY, TARGETS, PAYLOAD, CONTENT_SHA)
    VALUES (P_SCHEMA_FP, P_NAME, P_ORIGIN, P_STRATEGY, P_TARGETS, P_PAYLOAD, P_SHA);
    SET V_ID = (SELECT DATASET_ID FROM PORTPROOF.DATASET WHERE CONTENT_SHA = P_SHA);
  END IF;
  SET P_DATASET_ID = V_ID;
END
--@
-- Log what one dataset achieved on one statement. Unknown datasets are ignored
-- rather than raised: the log is evidence about datasets that exist.
CREATE PROCEDURE PORTPROOF.RECORD_DATASET_RUN (
  IN P_SHA      VARCHAR(64),
  IN P_CASE     VARCHAR(80),
  IN P_DIALECT  VARCHAR(16),
  IN P_FEATURES VARCHAR(400),
  IN P_ROWS     INTEGER,
  IN P_VACUOUS  SMALLINT,
  IN P_AGREED   SMALLINT,
  IN P_KILLED   SMALLINT
)
LANGUAGE SQL
MODIFIES SQL DATA
BEGIN
  INSERT INTO PORTPROOF.DATASET_RUN
         (DATASET_ID, CASE_NAME, SRC_DIALECT, FEATURES, ROWS_COMPARED, VACUOUS, AGREED, KILLED)
  SELECT DATASET_ID, P_CASE, P_DIALECT, P_FEATURES, COALESCE(P_ROWS, 0),
         COALESCE(P_VACUOUS, 0), COALESCE(P_AGREED, 0), COALESCE(P_KILLED, 0)
    FROM PORTPROOF.DATASET WHERE CONTENT_SHA = P_SHA;
END
--@
CREATE PROCEDURE PORTPROOF.RECORD_LLM_CALL (
  IN P_STAGE      VARCHAR(20),
  IN P_MODEL      VARCHAR(80),
  IN P_CASE       VARCHAR(80),
  IN P_PROMPT     INTEGER,
  IN P_COMPLETION INTEGER,
  IN P_LATENCY    INTEGER,
  IN P_OK         SMALLINT
)
LANGUAGE SQL
MODIFIES SQL DATA
BEGIN
  INSERT INTO PORTPROOF.LLM_CALL
         (STAGE, MODEL, CASE_NAME, PROMPT_TOKENS, COMPLETION_TOKENS, LATENCY_MS, OK)
  VALUES (P_STAGE, P_MODEL, P_CASE, COALESCE(P_PROMPT, 0), COALESCE(P_COMPLETION, 0),
          COALESCE(P_LATENCY, 0), COALESCE(P_OK, 1));
END
