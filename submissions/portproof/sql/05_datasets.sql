--@
-- Every adversarial dataset PortProof has accepted, keyed by the fingerprint of
-- the schema it was built for. CONTENT_SHA is the dataset's own content hash,
-- so the same rows under the same DDL are stored once however often they are
-- produced. A dataset proposed by a model lands here only after both engines
-- loaded it, which is what makes it reusable without asking the model again.
CREATE TABLE PORTPROOF.DATASET (
  DATASET_ID   INTEGER      NOT NULL GENERATED ALWAYS AS IDENTITY,
  SCHEMA_FP    VARCHAR(16)  NOT NULL,
  NAME         VARCHAR(120) NOT NULL,
  ORIGIN       VARCHAR(12)  NOT NULL,
  STRATEGY     VARCHAR(40)  NOT NULL,
  TARGETS      VARCHAR(400),
  PAYLOAD      CLOB(2M)     NOT NULL,
  CONTENT_SHA  VARCHAR(64)  NOT NULL,
  CREATED_AT   TIMESTAMP    NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT PK_DATASET PRIMARY KEY (DATASET_ID),
  CONSTRAINT UQ_DATASET_SHA UNIQUE (CONTENT_SHA),
  CONSTRAINT CK_DS_ORIGIN CHECK (ORIGIN IN ('BUILTIN', 'GENERATED', 'LLM'))
)
--@
CREATE INDEX PORTPROOF.IX_DATASET_SCHEMA ON PORTPROOF.DATASET (SCHEMA_FP, ORIGIN)
--@
-- One row per (dataset, statement) the prover ran. This is the log the dataset
-- agent ranks by: a dataset that keeps returning nothing sinks, one that keeps
-- exposing divergences rises.
CREATE TABLE PORTPROOF.DATASET_RUN (
  RUN_ID        INTEGER      NOT NULL GENERATED ALWAYS AS IDENTITY,
  DATASET_ID    INTEGER      NOT NULL,
  CASE_NAME     VARCHAR(80)  NOT NULL,
  SRC_DIALECT   VARCHAR(16)  NOT NULL,
  FEATURES      VARCHAR(400),
  ROWS_COMPARED INTEGER      NOT NULL DEFAULT 0,
  VACUOUS       SMALLINT     NOT NULL DEFAULT 0,
  AGREED        SMALLINT     NOT NULL DEFAULT 0,
  KILLED        SMALLINT     NOT NULL DEFAULT 0,
  CREATED_AT    TIMESTAMP    NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT PK_DATASET_RUN PRIMARY KEY (RUN_ID),
  CONSTRAINT FK_RUN_DATASET FOREIGN KEY (DATASET_ID)
    REFERENCES PORTPROOF.DATASET (DATASET_ID) ON DELETE CASCADE,
  CONSTRAINT CK_RUN_FLAGS CHECK (VACUOUS IN (0, 1) AND AGREED IN (0, 1) AND KILLED IN (0, 1)),
  -- A dataset cannot both agree and expose a divergence on the same statement.
  CONSTRAINT CK_RUN_EXCLUSIVE CHECK (AGREED + KILLED <= 1)
)
--@
CREATE INDEX PORTPROOF.IX_RUN_DATASET ON PORTPROOF.DATASET_RUN (DATASET_ID, SRC_DIALECT)
--@
-- What the agent reads: how each strategy has performed per source dialect.
CREATE VIEW PORTPROOF.DATASET_YIELD AS
  SELECT d.STRATEGY, r.SRC_DIALECT,
         COUNT(*)                                             AS RUNS,
         SUM(CASE WHEN r.VACUOUS = 0 THEN 1 ELSE 0 END)       AS SUBSTANTIVE,
         SUM(r.KILLED)                                        AS KILLS,
         SUM(r.ROWS_COMPARED)                                 AS ROWS_COMPARED
    FROM PORTPROOF.DATASET_RUN r
    JOIN PORTPROOF.DATASET d ON d.DATASET_ID = r.DATASET_ID
   GROUP BY d.STRATEGY, r.SRC_DIALECT
--@
-- Every call to a language model, with the token counts the provider reported.
-- The cost claim in docs/ai-cost-analysis.md is a query over this table.
CREATE TABLE PORTPROOF.LLM_CALL (
  CALL_ID           INTEGER      NOT NULL GENERATED ALWAYS AS IDENTITY,
  STAGE             VARCHAR(20)  NOT NULL,
  MODEL             VARCHAR(80)  NOT NULL,
  CASE_NAME         VARCHAR(80),
  PROMPT_TOKENS     INTEGER      NOT NULL DEFAULT 0,
  COMPLETION_TOKENS INTEGER      NOT NULL DEFAULT 0,
  LATENCY_MS        INTEGER      NOT NULL DEFAULT 0,
  OK                SMALLINT     NOT NULL DEFAULT 1,
  CREATED_AT        TIMESTAMP    NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT PK_LLM_CALL PRIMARY KEY (CALL_ID),
  CONSTRAINT CK_LLM_STAGE CHECK (STAGE IN ('COMPILE_REPAIR', 'SEMANTIC_REPAIR', 'DATASET')),
  CONSTRAINT CK_LLM_TOKENS CHECK (PROMPT_TOKENS >= 0 AND COMPLETION_TOKENS >= 0)
)
--@
CREATE VIEW PORTPROOF.LLM_COST AS
  SELECT STAGE, MODEL, COUNT(*) AS CALLS,
         SUM(PROMPT_TOKENS) AS PROMPT_TOKENS,
         SUM(COMPLETION_TOKENS) AS COMPLETION_TOKENS,
         AVG(LATENCY_MS) AS AVG_LATENCY_MS
    FROM PORTPROOF.LLM_CALL
   GROUP BY STAGE, MODEL
