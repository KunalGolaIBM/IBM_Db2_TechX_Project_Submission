-- =============================================================================
-- LOTLINE: IBM Db2 12.1 Schema Definition (LOTLINE_APP)
-- Single Source of Truth for Recall Intelligence & Closed-Loop Execution
-- =============================================================================

CREATE TABLE LOTLINE_APP.INCIDENTS (
    INCIDENT_ID VARCHAR(32) NOT NULL PRIMARY KEY,
    TITLE VARCHAR(255) NOT NULL,
    DESCRIPTION CLOB NOT NULL,
    SEVERITY VARCHAR(32) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    CONTAMINANT VARCHAR(128) NOT NULL,
    DISCOVERY_DATE DATE NOT NULL,
    REPORTED_BY VARCHAR(128),
    SOURCE_LOT_ID VARCHAR(32) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE LOTLINE_APP.SUPPLIERS (
    SUPPLIER_ID VARCHAR(32) NOT NULL PRIMARY KEY,
    NAME VARCHAR(128) NOT NULL,
    COUNTRY VARCHAR(64) NOT NULL,
    CONTACT_EMAIL VARCHAR(128),
    STATUS VARCHAR(32) DEFAULT 'ACTIVE',
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE LOTLINE_APP.FACILITIES (
    FACILITY_ID VARCHAR(32) NOT NULL PRIMARY KEY,
    NAME VARCHAR(128) NOT NULL,
    LOCATION VARCHAR(128) NOT NULL,
    FACILITY_TYPE VARCHAR(64) NOT NULL,
    STATUS VARCHAR(32) DEFAULT 'OPERATIONAL'
);

CREATE TABLE LOTLINE_APP.LOTS (
    LOT_ID VARCHAR(32) NOT NULL PRIMARY KEY,
    ITEM_NAME VARCHAR(128) NOT NULL,
    LOT_TYPE VARCHAR(32) NOT NULL,
    SUPPLIER_ID VARCHAR(32),
    QUANTITY DECIMAL(12, 2) NOT NULL,
    UNIT_OF_MEASURE VARCHAR(16) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    MANUFACTURE_DATE DATE,
    EXPIRY_DATE DATE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE LOTLINE_APP.LOT_LINEAGE (
    LINEAGE_ID VARCHAR(32) NOT NULL PRIMARY KEY,
    PARENT_LOT_ID VARCHAR(32) NOT NULL,
    CHILD_LOT_ID VARCHAR(32) NOT NULL,
    QUANTITY_USED DECIMAL(12, 2) NOT NULL,
    UNIT_OF_MEASURE VARCHAR(16) NOT NULL,
    PROCESS_STEP VARCHAR(64) NOT NULL,
    RECORDED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE LOTLINE_APP.INVENTORY (
    INVENTORY_ID VARCHAR(32) NOT NULL PRIMARY KEY,
    LOT_ID VARCHAR(32) NOT NULL,
    FACILITY_ID VARCHAR(32) NOT NULL,
    QUANTITY_ON_HAND DECIMAL(12, 2) NOT NULL,
    QUANTITY_QUARANTINED DECIMAL(12, 2) DEFAULT 0,
    STORAGE_BIN VARCHAR(64),
    LAST_AUDITED TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE LOTLINE_APP.SHIPMENTS (
    SHIPMENT_ID VARCHAR(32) NOT NULL PRIMARY KEY,
    LOT_ID VARCHAR(32) NOT NULL,
    DESTINATION_NAME VARCHAR(128) NOT NULL,
    DESTINATION_LOCATION VARCHAR(128) NOT NULL,
    QUANTITY DECIMAL(12, 2) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    CARRIER_NAME VARCHAR(128),
    DISPATCHED_AT TIMESTAMP,
    DELIVERED_AT TIMESTAMP
);

CREATE TABLE LOTLINE_APP.RECALL_ACTIONS (
    ACTION_ID VARCHAR(32) NOT NULL PRIMARY KEY,
    INCIDENT_ID VARCHAR(32) NOT NULL,
    ACTION_TYPE VARCHAR(64) NOT NULL,
    TARGET_ENTITY VARCHAR(128) NOT NULL,
    DESCRIPTION CLOB NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    PROPOSED_BY VARCHAR(128) DEFAULT 'Response Planning Agent',
    DECIDED_BY VARCHAR(128),
    DECIDED_AT TIMESTAMP,
    DECISION_NOTES CLOB,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE LOTLINE_APP.RECALL_COMMUNICATIONS (
    COMM_ID VARCHAR(32) NOT NULL PRIMARY KEY,
    INCIDENT_ID VARCHAR(32) NOT NULL,
    ACTION_ID VARCHAR(32),
    RECIPIENT_ORG VARCHAR(128) NOT NULL,
    CONTACT_NAME VARCHAR(128),
    CHANNEL VARCHAR(32) NOT NULL,
    STATUTORY_TEMPLATE_REF VARCHAR(64) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    DRAFT_TEXT CLOB,
    SENT_AT TIMESTAMP,
    DELIVERED_AT TIMESTAMP,
    ACKNOWLEDGED_AT TIMESTAMP,
    ACKNOWLEDGEMENT_REF VARCHAR(128),
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE LOTLINE_APP.LOGISTICS_INTERVENTIONS (
    INTERVENTION_ID VARCHAR(32) NOT NULL PRIMARY KEY,
    INCIDENT_ID VARCHAR(32) NOT NULL,
    SHIPMENT_ID VARCHAR(32) NOT NULL,
    CARRIER_NAME VARCHAR(128) NOT NULL,
    VEHICLE_REF VARCHAR(64),
    CARGO_LOCATION VARCHAR(128),
    TARGET_DESTINATION VARCHAR(128),
    CURRENT_STATUS VARCHAR(32) NOT NULL,
    RECOVERED_QUANTITY DECIMAL(12, 2) DEFAULT 0,
    CARRIER_CONTACT VARCHAR(128),
    INTERVENTION_NOTES CLOB,
    DISPATCH_CONFIRMED_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE LOTLINE_APP.PRODUCT_RECOVERIES (
    RECOVERY_ID VARCHAR(32) NOT NULL PRIMARY KEY,
    INCIDENT_ID VARCHAR(32) NOT NULL,
    LOT_ID VARCHAR(32) NOT NULL,
    SOURCE_LOCATION_TYPE VARCHAR(32) NOT NULL,
    SOURCE_ENTITY_NAME VARCHAR(128) NOT NULL,
    QUANTITY_RECOVERED DECIMAL(12, 2) NOT NULL,
    UNIT_OF_MEASURE VARCHAR(16) NOT NULL,
    STORAGE_FACILITY_ID VARCHAR(32) NOT NULL,
    VERIFICATION_METHOD VARCHAR(32) NOT NULL,
    VERIFIED_BY_OPERATOR VARCHAR(128) NOT NULL,
    VERIFIED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    NOTES CLOB
);

CREATE TABLE LOTLINE_APP.PRODUCT_DISPOSITIONS (
    DISPOSITION_ID VARCHAR(32) NOT NULL PRIMARY KEY,
    INCIDENT_ID VARCHAR(32) NOT NULL,
    LOT_ID VARCHAR(32) NOT NULL,
    LOT_TYPE VARCHAR(32) NOT NULL,
    QUANTITY DECIMAL(12, 2) NOT NULL,
    UNIT_OF_MEASURE VARCHAR(16) NOT NULL,
    DISPOSITION_TYPE VARCHAR(64) NOT NULL,
    STATUS VARCHAR(32) NOT NULL,
    REASON CLOB NOT NULL,
    PROPOSED_METHOD CLOB,
    AUTHORITY_PERMISSION_REF VARCHAR(128),
    OPERATOR_NAME VARCHAR(128),
    APPROVED_BY VARCHAR(128),
    APPROVED_AT TIMESTAMP,
    EXECUTED_AT TIMESTAMP,
    EVIDENCE_ATTACHMENT VARCHAR(255),
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE LOTLINE_APP.REGULATORY_SUBMISSIONS (
    SUBMISSION_ID VARCHAR(32) NOT NULL PRIMARY KEY,
    INCIDENT_ID VARCHAR(32) NOT NULL,
    REGULATORY_BODY VARCHAR(128) NOT NULL,
    FOSCOS_RECALL_REF VARCHAR(128),
    SUBMISSION_STAGE VARCHAR(32) NOT NULL,
    SUBMITTED_BY VARCHAR(128),
    SUBMISSION_TIMESTAMP TIMESTAMP,
    AUTHORITY_FEEDBACK CLOB,
    SUPPORTING_EVIDENCE_REF VARCHAR(255),
    PENDING_CORRECTIONS CLOB,
    AWARENESS_TIMESTAMP TIMESTAMP NOT NULL,
    STATUTORY_DEADLINE TIMESTAMP NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE LOTLINE_APP.AUDIT_LOG (
    AUDIT_ID VARCHAR(32) NOT NULL PRIMARY KEY,
    INCIDENT_ID VARCHAR(32),
    ACTION_ID VARCHAR(32),
    ENTITY_TYPE VARCHAR(64) NOT NULL,
    ENTITY_ID VARCHAR(64) NOT NULL,
    EVENT_TYPE VARCHAR(64) NOT NULL,
    ACTOR VARCHAR(128) NOT NULL,
    DETAILS CLOB NOT NULL,
    PREVIOUS_STATE CLOB,
    NEW_STATE CLOB,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);
