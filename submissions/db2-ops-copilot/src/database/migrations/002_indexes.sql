-- ============================================================================
-- 002_indexes.sql — indexes for the application schema.
-- Run after 001_app_schema.sql. NEVER executed during M1/M2 development.
-- Idempotent: each index is created only when absent (SYSCAT.INDEXES guard).
-- ============================================================================

--#SET TERMINATOR @
BEGIN
  DECLARE cnt INT DEFAULT 0;
  SELECT COUNT(*) INTO cnt FROM SYSCAT.INDEXES
    WHERE INDSCHEMA = 'APP' AND INDNAME = 'IDX_INCIDENTS_SERVER';
  IF cnt = 0 THEN
    EXECUTE IMMEDIATE
      'CREATE INDEX APP.IDX_INCIDENTS_SERVER ON APP.DEMO_INCIDENTS (SERVER_ID)';
  END IF;
END@
--#SET TERMINATOR ;

