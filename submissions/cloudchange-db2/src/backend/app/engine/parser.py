"""Terraform Plan Parser.

Ingests and validates raw Terraform JSON plans generated by `terraform show -json`.
Enforces schema validity, identifies unchanged (no-op) and data-source (read) entries,
and isolates supported actionable changes while generating structured warnings for
unsupported resource types.
"""

from typing import Any
from pydantic import BaseModel, Field

from backend.app.engine.exceptions import (
    InvalidActionError,
    PlanValidationError,
    UnsupportedResourceError,
)
from backend.app.models.change import UnsupportedResourceWarning

# Phase 1 strictly supported resource types
SUPPORTED_RESOURCE_TYPES: set[str] = {
    "aws_instance",
    "aws_security_group",
    "aws_db_instance",
}

# Recognized actionable action sets
ACTIONABLE_ACTION_COMBINATIONS = {
    ("create",),
    ("update",),
    ("delete",),
    ("delete", "create"),
    ("create", "delete"),
}


class ParsedPlan(BaseModel):
    """Output of PlanParser containing actionable changes, unsupported resources, and ignored entries."""
    actionable_changes: list[dict[str, Any]] = Field(default_factory=list)
    unsupported_resources: list[UnsupportedResourceWarning] = Field(default_factory=list)
    ignored_noops: list[str] = Field(default_factory=list, description="Addresses of unchanged (no-op) resources")
    ignored_reads: list[str] = Field(default_factory=list, description="Addresses of data source read entries")

    def __iter__(self):
        """Allow iterating directly over actionable changes."""
        return iter(self.actionable_changes)

    def __len__(self):
        """Allow checking len() of actionable changes."""
        return len(self.actionable_changes)

    def __getitem__(self, idx):
        """Allow indexing directly into actionable changes."""
        return self.actionable_changes[idx]


class PlanParser:
    """Validates and parses raw change sets from Terraform plan JSON artifacts."""

    def __init__(self, supported_types: set[str] = None) -> None:
        self.supported_types = supported_types if supported_types is not None else SUPPORTED_RESOURCE_TYPES

    def validate_schema(self, plan_json: Any) -> None:
        """Validate that the plan artifact conforms to Terraform JSON specifications.
        
        Raises:
            PlanValidationError: If the structure is not a dict or lacks required fields.
        """
        if not isinstance(plan_json, dict):
            raise PlanValidationError("Plan artifact must be a JSON object (dictionary).")

        format_version = plan_json.get("format_version")
        if not format_version or not isinstance(format_version, str):
            raise PlanValidationError("Missing or invalid 'format_version' string in Terraform plan JSON.")

        resource_changes = plan_json.get("resource_changes")
        if resource_changes is None or not isinstance(resource_changes, list):
            raise PlanValidationError("Missing or invalid 'resource_changes' array in Terraform plan JSON.")

    def parse(self, plan_json: Any, strict_supported_only: bool = False) -> ParsedPlan:
        """Validate plan schema and categorize resource change entries.
        
        Args:
            plan_json: Parsed JSON content from terraform plan.
            strict_supported_only: When True, raises UnsupportedResourceError if
                any unsupported resource type is encountered. When False (default),
                unsupported resources are preserved as structured warnings.

        Returns:
            ParsedPlan object containing actionable changes and metadata.

        Raises:
            PlanValidationError: If the plan or any resource change entry is malformed.
            UnsupportedResourceError: If strict_supported_only is True and an unsupported
                resource is encountered.
            InvalidActionError: If an unrecognized action array is encountered on an actionable change.
        """
        self.validate_schema(plan_json)

        raw_changes = plan_json["resource_changes"]
        actionable_changes: list[dict[str, Any]] = []
        unsupported_resources: list[UnsupportedResourceWarning] = []
        ignored_noops: list[str] = []
        ignored_reads: list[str] = []

        for idx, item in enumerate(raw_changes):
            if not isinstance(item, dict):
                raise PlanValidationError(f"resource_changes[{idx}] is not an object.")

            address = item.get("address")
            if not address or not isinstance(address, str):
                raise PlanValidationError(f"resource_changes[{idx}] missing valid 'address'.")

            resource_type = item.get("type")
            if not resource_type or not isinstance(resource_type, str):
                raise PlanValidationError(f"Resource '{address}' missing valid 'type'.")

            change_info = item.get("change")
            if not isinstance(change_info, dict):
                raise PlanValidationError(f"Resource '{address}' missing 'change' object.")

            actions = change_info.get("actions")
            if not isinstance(actions, list) or not actions:
                raise PlanValidationError(f"Resource '{address}' missing non-empty 'change.actions' array.")

            mode = item.get("mode", "managed")

            # 1. Check for data source or read-only action
            if mode == "data" or actions == ["read"]:
                ignored_reads.append(address)
                continue

            # 2. Check for unchanged (no-op) resource
            if actions == ["no-op"]:
                ignored_noops.append(address)
                continue

            # 3. Validate that actionable actions are recognized
            actions_tuple = tuple(actions)
            if actions_tuple not in ACTIONABLE_ACTION_COMBINATIONS:
                raise InvalidActionError(actions=actions, resource_address=address)

            # 4. Check supported resource type boundary
            if resource_type not in self.supported_types:
                if strict_supported_only:
                    raise UnsupportedResourceError(
                        resource_type=resource_type,
                        resource_address=address,
                        supported_types=list(self.supported_types)
                    )
                unsupported_resources.append(
                    UnsupportedResourceWarning(
                        resource_address=address,
                        resource_type=resource_type,
                        reason=(
                            f"Resource '{address}' has type '{resource_type}' which is outside Phase 1 "
                            f"supported scope: {', '.join(sorted(self.supported_types))}."
                        )
                    )
                )
                continue

            # 5. Supported actionable change
            actionable_changes.append(item)

        return ParsedPlan(
            actionable_changes=actionable_changes,
            unsupported_resources=unsupported_resources,
            ignored_noops=ignored_noops,
            ignored_reads=ignored_reads,
        )
