-- IssueSmith schema for IBM Db2 12.1.2+ (VECTOR support required).
-- Statements are separated by a line containing only "@".
-- {schema} and {dim} are filled in by db.py. Statements marked "-- optional"
-- only log a warning if they fail (e.g. on older Db2 builds).

CREATE TABLE {schema}.INCIDENTS (
  INCIDENT_ID      INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1001) NOT NULL PRIMARY KEY,
  SOURCE_NAME      VARCHAR(255),
  CATEGORY         VARCHAR(30)  NOT NULL DEFAULT 'UNCLASSIFIED',
  CONFIDENCE       DECIMAL(4,3),
  SIGNATURE        VARCHAR(3000),
  ENV_JSON         CLOB(64K),
  SANITIZED_LOG    CLOB(10M),
  REDACTION_COUNT  INTEGER      NOT NULL DEFAULT 0,
  EMBEDDING        VECTOR({dim}, FLOAT32),
  STATUS           VARCHAR(20)  NOT NULL DEFAULT 'NEW',
  DUPLICATE_OF     INTEGER,
  CREATED_AT       TIMESTAMP    NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT CK_INCIDENT_STATUS CHECK (STATUS IN ('NEW','DRAFTED','DUPLICATE','POSTED'))
)
@
CREATE TABLE {schema}.EVIDENCE (
  EVIDENCE_ID  INTEGER GENERATED ALWAYS AS IDENTITY NOT NULL PRIMARY KEY,
  INCIDENT_ID  INTEGER      NOT NULL,
  LINE_NO      INTEGER,
  KIND         VARCHAR(12)  NOT NULL,
  LABEL        VARCHAR(120),
  CATEGORY     VARCHAR(30),
  LOG_LINE     VARCHAR(2000),
  SIGNATURE    VARCHAR(1000),
  CONSTRAINT CK_EVIDENCE_KIND CHECK (KIND IN ('ERROR','WARNING','OBSERVATION')),
  CONSTRAINT FK_EVIDENCE_INCIDENT FOREIGN KEY (INCIDENT_ID)
    REFERENCES {schema}.INCIDENTS (INCIDENT_ID) ON DELETE CASCADE
)
@
CREATE TABLE {schema}.ISSUE_DRAFTS (
  DRAFT_ID      INTEGER GENERATED ALWAYS AS IDENTITY NOT NULL PRIMARY KEY,
  INCIDENT_ID   INTEGER      NOT NULL,
  ROUND_NO      SMALLINT     NOT NULL DEFAULT 1,
  TITLE         VARCHAR(300) NOT NULL,
  BODY_MD       CLOB(1M)     NOT NULL,
  CRITIC_SCORE  DECIMAL(5,2),
  CRITIC_NOTES  CLOB(64K),
  GENERATED_BY  VARCHAR(80),
  IS_FINAL      CHAR(1)      NOT NULL DEFAULT 'N',
  GITHUB_URL    VARCHAR(500),
  CREATED_AT    TIMESTAMP    NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT FK_DRAFT_INCIDENT FOREIGN KEY (INCIDENT_ID)
    REFERENCES {schema}.INCIDENTS (INCIDENT_ID) ON DELETE CASCADE
)
@
CREATE TABLE {schema}.AGENT_RUNS (
  RUN_ID       BIGINT GENERATED ALWAYS AS IDENTITY NOT NULL PRIMARY KEY,
  INCIDENT_ID  INTEGER,
  AGENT        VARCHAR(40)  NOT NULL,
  STATUS       VARCHAR(12)  NOT NULL,
  DETAIL       VARCHAR(2000),
  LATENCY_MS   INTEGER,
  CREATED_AT   TIMESTAMP    NOT NULL DEFAULT CURRENT TIMESTAMP
)
@
CREATE INDEX {schema}.IX_INCIDENTS_CAT_TIME ON {schema}.INCIDENTS (CATEGORY, CREATED_AT)
@
CREATE INDEX {schema}.IX_EVIDENCE_INCIDENT ON {schema}.EVIDENCE (INCIDENT_ID)
@
CREATE INDEX {schema}.IX_EVIDENCE_SIGNATURE ON {schema}.EVIDENCE (SIGNATURE)
@
CREATE INDEX {schema}.IX_DRAFTS_INCIDENT ON {schema}.ISSUE_DRAFTS (INCIDENT_ID, IS_FINAL)
@
CREATE INDEX {schema}.IX_RUNS_AGENT ON {schema}.AGENT_RUNS (AGENT, CREATED_AT)
@
CREATE OR REPLACE VIEW {schema}.V_CATEGORY_STATS AS
  SELECT CATEGORY,
         COUNT(*)                                             AS INCIDENTS,
         SUM(CASE WHEN STATUS = 'DUPLICATE' THEN 1 ELSE 0 END) AS DUPLICATES,
         DECIMAL(AVG(CONFIDENCE), 4, 3)                       AS AVG_CONFIDENCE,
         SUM(REDACTION_COUNT)                                 AS SECRETS_REDACTED,
         MAX(CREATED_AT)                                      AS LAST_SEEN
  FROM {schema}.INCIDENTS
  GROUP BY CATEGORY
@
CREATE OR REPLACE VIEW {schema}.V_TOP_SIGNATURES AS
  SELECT E.SIGNATURE,
         MAX(E.LABEL)                    AS LABEL,
         MAX(E.CATEGORY)                 AS CATEGORY,
         COUNT(DISTINCT E.INCIDENT_ID)   AS INCIDENTS,
         MIN(I.CREATED_AT)               AS FIRST_SEEN,
         MAX(I.CREATED_AT)               AS LAST_SEEN
  FROM {schema}.EVIDENCE E
  JOIN {schema}.INCIDENTS I ON I.INCIDENT_ID = E.INCIDENT_ID
  WHERE E.KIND IN ('ERROR', 'WARNING')
  GROUP BY E.SIGNATURE
@
CREATE OR REPLACE VIEW {schema}.V_AGENT_PERFORMANCE AS
  SELECT AGENT,
         COUNT(*)                                          AS RUNS,
         INTEGER(AVG(LATENCY_MS))                          AS AVG_LATENCY_MS,
         MAX(LATENCY_MS)                                   AS MAX_LATENCY_MS,
         SUM(CASE WHEN STATUS <> 'OK' THEN 1 ELSE 0 END)   AS FAILURES
  FROM {schema}.AGENT_RUNS
  GROUP BY AGENT
@
CREATE OR REPLACE VIEW {schema}.V_DRAFT_QUALITY AS
  SELECT D.INCIDENT_ID, I.CATEGORY, D.ROUND_NO AS ROUNDS_NEEDED,
         D.CRITIC_SCORE, D.GENERATED_BY, D.GITHUB_URL, D.CREATED_AT
  FROM {schema}.ISSUE_DRAFTS D
  JOIN {schema}.INCIDENTS I ON I.INCIDENT_ID = D.INCIDENT_ID
  WHERE D.IS_FINAL = 'Y'
@
-- optional
CREATE OR REPLACE VIEW {schema}.V_INCIDENT_ENV AS
  SELECT INCIDENT_ID, CATEGORY, CREATED_AT,
         JSON_VALUE(ENV_JSON, '$.operating_system'  RETURNING VARCHAR(80))  AS OPERATING_SYSTEM,
         JSON_VALUE(ENV_JSON, '$.container_runtime' RETURNING VARCHAR(80))  AS CONTAINER_RUNTIME,
         JSON_VALUE(ENV_JSON, '$.extension_version' RETURNING VARCHAR(20))  AS EXTENSION_VERSION,
         JSON_VALUE(ENV_JSON, '$.db2_version'       RETURNING VARCHAR(20))  AS DB2_VERSION
  FROM {schema}.INCIDENTS
@
CREATE OR REPLACE PROCEDURE {schema}.FIND_SIMILAR_INCIDENTS (IN P_INCIDENT_ID INTEGER)
  LANGUAGE SQL
  READS SQL DATA
  DYNAMIC RESULT SETS 1
BEGIN
  DECLARE C1 CURSOR WITH RETURN TO CALLER FOR
    SELECT O.INCIDENT_ID, O.CATEGORY, O.STATUS, O.CREATED_AT,
           VECTOR_DISTANCE(T.EMBEDDING, O.EMBEDDING, COSINE) AS DISTANCE
    FROM {schema}.INCIDENTS T
    JOIN {schema}.INCIDENTS O ON O.INCIDENT_ID <> T.INCIDENT_ID
    WHERE T.INCIDENT_ID = P_INCIDENT_ID
      AND T.EMBEDDING IS NOT NULL
      AND O.EMBEDDING IS NOT NULL
    ORDER BY DISTANCE
    FETCH FIRST 5 ROWS ONLY;
  OPEN C1;
END
