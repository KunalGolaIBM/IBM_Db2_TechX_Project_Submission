-- 1. USERS
CREATE TABLE FINSIGHT.USERS (
    user_id VARCHAR(36) NOT NULL PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    full_name VARCHAR(120) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
);

-- 2. ACCOUNTS
CREATE TABLE FINSIGHT.ACCOUNTS (
    account_id VARCHAR(36) NOT NULL PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    account_name VARCHAR(100) NOT NULL,
    account_type VARCHAR(30) NOT NULL,
    institution_name VARCHAR(100) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'INR',
    opening_balance DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_ACCOUNTS_USER FOREIGN KEY (user_id) REFERENCES FINSIGHT.USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT CHK_ACCOUNT_TYPE CHECK (account_type IN ('CHECKING', 'SAVINGS', 'CREDIT_CARD', 'INVESTMENT')),
    CONSTRAINT CHK_ACC_CURRENCY CHECK (currency IN ('INR', 'USD', 'EUR', 'GBP'))
);

-- 3. CATEGORIES (user_id is nullable to support platform default categories)
CREATE TABLE FINSIGHT.CATEGORIES (
    category_id VARCHAR(36) NOT NULL PRIMARY KEY,
    user_id VARCHAR(36),
    category_name VARCHAR(100) NOT NULL,
    category_type VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_CATEGORIES_USER FOREIGN KEY (user_id) REFERENCES FINSIGHT.USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT CHK_CAT_TYPE CHECK (category_type IN ('INCOME', 'EXPENSE', 'TRANSFER'))
);

-- 4. TRANSACTIONS
CREATE TABLE FINSIGHT.TRANSACTIONS (
    transaction_id VARCHAR(36) NOT NULL PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    account_id VARCHAR(36) NOT NULL,
    category_id VARCHAR(36),
    external_transaction_id VARCHAR(100),
    merchant VARCHAR(150) NOT NULL,
    description VARCHAR(500),
    amount DECIMAL(14,2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'INR',
    transaction_type VARCHAR(20) NOT NULL,
    transaction_date DATE NOT NULL,
    transaction_status VARCHAR(20) NOT NULL DEFAULT 'POSTED',
    source VARCHAR(50) NOT NULL DEFAULT 'MANUAL',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_TX_USER FOREIGN KEY (user_id) REFERENCES FINSIGHT.USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT FK_TX_ACCOUNT FOREIGN KEY (account_id) REFERENCES FINSIGHT.ACCOUNTS(account_id) ON DELETE CASCADE,
    CONSTRAINT FK_TX_CATEGORY FOREIGN KEY (category_id) REFERENCES FINSIGHT.CATEGORIES(category_id) ON DELETE SET NULL,
    CONSTRAINT CHK_TX_AMOUNT CHECK (amount >= 0.00),
    CONSTRAINT CHK_TX_TYPE CHECK (transaction_type IN ('DEBIT', 'CREDIT')),
    CONSTRAINT CHK_TX_STATUS CHECK (transaction_status IN ('POSTED', 'PENDING')),
    CONSTRAINT CHK_TX_CURRENCY CHECK (currency IN ('INR', 'USD', 'EUR', 'GBP'))
);

-- 5. IMPORT_JOBS
CREATE TABLE FINSIGHT.IMPORT_JOBS (
    import_job_id VARCHAR(36) NOT NULL PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    filename VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    total_rows INTEGER NOT NULL DEFAULT 0,
    successful_rows INTEGER NOT NULL DEFAULT 0,
    rejected_rows INTEGER NOT NULL DEFAULT 0,
    duplicate_rows INTEGER NOT NULL DEFAULT 0,
    error_summary CLOB(10000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    completed_at TIMESTAMP,
    CONSTRAINT FK_IMPORT_USER FOREIGN KEY (user_id) REFERENCES FINSIGHT.USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT CHK_IMPORT_STATUS CHECK (status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED'))
);

-- 6. ANOMALY_ALERTS
CREATE TABLE FINSIGHT.ANOMALY_ALERTS (
    alert_id VARCHAR(36) NOT NULL PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    transaction_id VARCHAR(36),
    alert_type VARCHAR(50) NOT NULL,
    severity VARCHAR(20) NOT NULL,
    explanation VARCHAR(1000) NOT NULL,
    score DECIMAL(5,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_ALERT_USER FOREIGN KEY (user_id) REFERENCES FINSIGHT.USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT FK_ALERT_TX FOREIGN KEY (transaction_id) REFERENCES FINSIGHT.TRANSACTIONS(transaction_id) ON DELETE SET NULL,
    CONSTRAINT CHK_ALERT_SEVERITY CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT CHK_ALERT_STATUS CHECK (status IN ('ACTIVE', 'DISMISSED', 'RESOLVED'))
);

-- 7. AI_INSIGHTS
CREATE TABLE FINSIGHT.AI_INSIGHTS (
    insight_id VARCHAR(36) NOT NULL PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    insight_type VARCHAR(50) NOT NULL,
    title VARCHAR(200) NOT NULL,
    explanation CLOB(50000) NOT NULL,
    supporting_data CLOB(50000),
    generated_at TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_INSIGHT_USER FOREIGN KEY (user_id) REFERENCES FINSIGHT.USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT CHK_INSIGHT_TYPE CHECK (insight_type IN ('MONTHLY_SUMMARY', 'SPENDING_ANOMALY', 'BUDGET_PACING', 'SAVINGS_OPPORTUNITY'))
);

-- Indexes for performance and multi-tenant query isolation
CREATE INDEX FINSIGHT.IDX_ACCOUNTS_USER ON FINSIGHT.ACCOUNTS(user_id);
CREATE INDEX FINSIGHT.IDX_TX_USER_DATE ON FINSIGHT.TRANSACTIONS(user_id, transaction_date DESC);
CREATE INDEX FINSIGHT.IDX_TX_ACCOUNT_DATE ON FINSIGHT.TRANSACTIONS(account_id, transaction_date DESC);
CREATE INDEX FINSIGHT.IDX_TX_CATEGORY ON FINSIGHT.TRANSACTIONS(user_id, category_id);
CREATE INDEX FINSIGHT.IDX_TX_MERCHANT ON FINSIGHT.TRANSACTIONS(user_id, merchant);
CREATE INDEX FINSIGHT.IDX_ALERTS_USER ON FINSIGHT.ANOMALY_ALERTS(user_id, status);
CREATE INDEX FINSIGHT.IDX_INSIGHTS_USER ON FINSIGHT.AI_INSIGHTS(user_id, generated_at DESC);
