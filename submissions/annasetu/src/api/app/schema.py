def initialize_schema() -> None:
    conn = connect()
    try:
        cursor = conn.cursor()
        try:
            for statement in DDL:
                try:
                    cursor.execute(statement)
                except Exception as exc:
                    message = str(exc)
                    if "42710" not in message and "-601" not in message and "already exists" not in message.lower():
                        raise
            conn.commit()
        finally:
            cursor.close()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()
