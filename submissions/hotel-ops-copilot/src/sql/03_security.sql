-- Row and column access control: mask PII for the agent role
CREATE MASK GUEST_EMAIL_MASK ON GUESTS
    FOR COLUMN EMAIL RETURN
        CASE WHEN VERIFY_ROLE_FOR_USER(SESSION_USER, 'HOTELOPS_AGENT') = 1
             THEN '***@' || SUBSTR(EMAIL, LOCATE('@', EMAIL) + 1)
             ELSE EMAIL END
    ENABLE
@
