-- Hotel Ops Copilot - least-privilege access for the AI agent
-- {AGENT_USER} is substituted by setup_db.py (default: OPSAGENT).
--
-- Defence in depth:
--   1. The agent connects as its own Db2 user that holds role HOTELOPS_AGENT.
--   2. The role can SELECT business data and CALL SP_PROPOSE_ACTION - nothing else.
--      Even a malicious generated query cannot UPDATE, DELETE or DROP anything.
--   3. Column masks (RCAC) hide guest e-mail and phone from the agent, so PII
--      never reaches the LLM prompt.

CREATE ROLE HOTELOPS_AGENT
@
GRANT ROLE HOTELOPS_AGENT TO USER {AGENT_USER}
@
GRANT CONNECT ON DATABASE TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON ROOM_TYPES TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON ROOMS TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON GUESTS TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON RESERVATIONS TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON RATE_PLAN TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON RATE_PLAN_HISTORY TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON RESERVATIONS_HISTORY TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON ROOMS_HISTORY TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON GUEST_REVIEWS TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON REVIEW_CHUNKS TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON POLICY_KB TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON MAINTENANCE_TICKETS TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON CALENDAR TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON AGENT_ACTIONS TO ROLE HOTELOPS_AGENT
@
-- the agent may read its autonomy grants but never change them
GRANT SELECT ON AUTONOMY_POLICY TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON V_ROOM_TYPE_DAY TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON V_DAILY_KPIS TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON V_REVIEW_SUMMARY TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON PROMOTIONS TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON PROMOTIONS_HISTORY TO ROLE HOTELOPS_AGENT
@
GRANT SELECT ON MQT_DAILY_KPIS TO ROLE HOTELOPS_AGENT
@
GRANT EXECUTE ON PROCEDURE SP_PROPOSE_ACTION TO ROLE HOTELOPS_AGENT
@
-- the agent must not create objects of its own
REVOKE CREATETAB ON DATABASE FROM PUBLIC
@
REVOKE IMPLICIT_SCHEMA ON DATABASE FROM PUBLIC
@
-- Row and column access control: mask PII for the agent role
CREATE MASK GUEST_EMAIL_MASK ON GUESTS
    FOR COLUMN EMAIL RETURN
        CASE WHEN VERIFY_ROLE_FOR_USER(SESSION_USER, 'HOTELOPS_AGENT') = 1
             THEN '***@' || SUBSTR(EMAIL, LOCATE('@', EMAIL) + 1)
             ELSE EMAIL END
    ENABLE
@
CREATE MASK GUEST_PHONE_MASK ON GUESTS
    FOR COLUMN PHONE RETURN
        CASE WHEN VERIFY_ROLE_FOR_USER(SESSION_USER, 'HOTELOPS_AGENT') = 1
             THEN 'XXXXXX' || RIGHT(PHONE, 4)
             ELSE PHONE END
    ENABLE
@
ALTER TABLE GUESTS ACTIVATE COLUMN ACCESS CONTROL
@
-- Row access control: guests who withdrew consent (DPDP Act 2023) do not exist
-- for the AI. Everyone else (managers, stored procedures run by managers) sees all rows.
CREATE PERMISSION GUEST_CONSENT_ROWS ON GUESTS
    FOR ROWS WHERE VERIFY_ROLE_FOR_USER(SESSION_USER, 'HOTELOPS_AGENT') = 0
                OR AI_CONSENT = 'Y'
    ENFORCED FOR ALL ACCESS
    ENABLE
@
ALTER TABLE GUESTS ACTIVATE ROW ACCESS CONTROL
@
