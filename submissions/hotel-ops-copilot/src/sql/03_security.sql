-- Row access control: guests who withdrew consent (DPDP Act 2023) do not exist
-- for the AI. Everyone else (managers, stored procedures run by managers) sees all rows.
CREATE PERMISSION GUEST_CONSENT_ROWS ON GUESTS
    FOR ROWS WHERE VERIFY_ROLE_FOR_USER(SESSION_USER, 'HOTELOPS_AGENT') = 0
                OR AI_CONSENT = 'Y'
    ENFORCED FOR ALL ACCESS
    ENABLE
