-- Db2 workload management: every connection of the AI login runs in its own workload, and Db2 itself
-- stops an activity that is estimated to be too expensive, returns too many rows (bulk extraction) or
-- runs too long. This holds even if the application's SQL guard and EXPLAIN check are bypassed.
-- Each stop is recorded by a threshold-violations event monitor in HOTELOPS.AGENT_THRESHOLD_VIOLATIONS.
CREATE WORKLOAD HOTELOPS_AGENT_WL SESSION_USER ('{AGENT_USER}') ENABLE
@
GRANT USAGE ON WORKLOAD HOTELOPS_AGENT_WL TO USER {AGENT_USER}
@
CREATE THRESHOLD HOTELOPS_AGENT_MAX_COST FOR WORKLOAD HOTELOPS_AGENT_WL ACTIVITIES ENFORCEMENT DATABASE
    WHEN ESTIMATEDSQLCOST > 25000 STOP EXECUTION
@
CREATE THRESHOLD HOTELOPS_AGENT_MAX_ROWS FOR WORKLOAD HOTELOPS_AGENT_WL ACTIVITIES ENFORCEMENT DATABASE
    WHEN SQLROWSRETURNED > 1000 STOP EXECUTION
@
CREATE THRESHOLD HOTELOPS_AGENT_MAX_TIME FOR WORKLOAD HOTELOPS_AGENT_WL ACTIVITIES ENFORCEMENT DATABASE
    WHEN ACTIVITYTOTALTIME > 30 SECONDS STOP EXECUTION
@
CREATE EVENT MONITOR HOTELOPS_AGENT_VIOLATIONS FOR THRESHOLD VIOLATIONS
    WRITE TO TABLE THRESHOLDVIOLATIONS (TABLE HOTELOPS.AGENT_THRESHOLD_VIOLATIONS) AUTOSTART
@
SET EVENT MONITOR HOTELOPS_AGENT_VIOLATIONS STATE 1
