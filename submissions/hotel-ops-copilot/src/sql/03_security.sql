-- Hotel Ops Copilot - least-privilege access for the AI agent
-- {AGENT_USER} is substituted by setup_db.py (default: OPSAGENT).
--
-- Defence in depth:
--   1. The agent connects as its own Db2 user that holds role HOTELOPS_AGENT.
--   2. The role can SELECT business data and CALL SP_PROPOSE_ACTION - nothing else.
--      Even a malicious generated query cannot UPDATE, DELETE or DROP anything.
--   3. Column masks (RCAC) hide guest e-mail and phone from the agent, so PII
--      never reaches the LLM prompt.
--   4. Property isolation (hotel chain): each agent identity is scoped to its own
--      hotel in AGENT_SCOPE, a table the agent cannot read or change. Row permissions
--      on every operational table hide the other hotels' rows from it, including inside
--      views, the MQT and the stored procedures it calls.

CREATE ROLE HOTELOPS_AGENT
@
GRANT ROLE HOTELOPS_AGENT TO USER {AGENT_USER}
@
GRANT CONNECT ON DATABASE TO ROLE HOTELOPS_AGENT
@
CREATE TABLE AGENT_SCOPE (
    AUTH_ID      VARCHAR(128) NOT NULL,
    PROPERTY_ID  SMALLINT     NOT NULL REFERENCES PROPERTIES ON DELETE CASCADE,
    GRANTED_BY   VARCHAR(40)  NOT NULL DEFAULT 'SYSTEM',
    GRANTED_AT   TIMESTAMP    NOT NULL DEFAULT CURRENT TIMESTAMP,
    PRIMARY KEY (AUTH_ID, PROPERTY_ID)
)
@
COMMENT ON TABLE AGENT_SCOPE IS 'Which hotel(s) each AI agent identity (Db2 auth ID) may see. Only managers can change it; the agent role has no privilege on it.'
