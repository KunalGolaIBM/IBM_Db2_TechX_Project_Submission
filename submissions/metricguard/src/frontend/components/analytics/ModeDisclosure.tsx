import { Cpu, Sparkles } from "lucide-react";
import type { PlannerInfo, ValidationStatus } from "@/lib/api/types";

const PROVIDER_LABEL: Record<string, string> = { meta: "Meta Model API", anthropic: "Anthropic" };

/** Truthful label for a real model plan: provider (when the API says it) plus model id. */
export function llmLabel(p: Pick<PlannerInfo, "name" | "model" | "provider">, short = false): string {
  const provider = p.provider ? (short && p.provider === "meta" ? "Meta" : PROVIDER_LABEL[p.provider] ?? p.provider) : p.name;
  return p.model ? `${provider} · ${p.model}` : provider;
}

/** What happened after planning, stated per status so the banner never claims SQL ran when it did not. */
function llmSentence(status?: ValidationStatus): string {
  const lead = "A language model interpreted the question into a typed plan.";
  if (status === "AMBIGUOUS" || status === "BLOCKED") return `${lead} No SQL was generated or run on IBM Db2 for this request.`;
  if (status === "EXECUTION_FAILED") return `${lead} The SQL was generated by deterministic code; IBM Db2 did not complete it.`;
  return `${lead} The SQL was generated by deterministic code and executed on IBM Db2.`;
}

/** Persistent, visible planner disclosure. Uses `planner.disclosure` verbatim when provided. */
export function ModeDisclosure({ planner, status }: { planner: PlannerInfo; status?: ValidationStatus }) {
  if (planner.execution_mode === "DEMO_RULE_BASED") {
    return (
      <div data-testid="mode-disclosure" data-mode="DEMO_RULE_BASED" role="note" className="flex items-start gap-3 rounded-xl border border-warn/30 bg-warn-soft px-4 py-3 text-warn">
        <Cpu aria-hidden className="mt-0.5 size-5 shrink-0" />
        <div className="min-w-0 text-[15px] leading-relaxed text-ink-2">
          <p className="font-semibold text-warn">Demo Planner · rule-based, not an LLM</p>
          <p>
            {planner.disclosure ??
              "This request was interpreted using deterministic rules. The SQL and results were executed against IBM Db2."}
          </p>
        </div>
      </div>
    );
  }
  return (
    <div data-testid="mode-disclosure" data-mode="LLM" role="note" className="flex items-start gap-3 rounded-xl border border-accent/25 bg-accent-soft px-4 py-3">
      <Sparkles aria-hidden className="mt-0.5 size-5 shrink-0 text-accent-ink" />
      <div className="min-w-0 text-[15px] leading-relaxed text-ink-2">
        <p className="font-semibold text-accent-ink" data-testid="llm-label">AI planner · {llmLabel(planner)}</p>
        <p data-testid="llm-sentence">{planner.disclosure ?? llmSentence(status)}</p>
      </div>
    </div>
  );
}
