import { fireEvent, render, screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { describe, expect, it, vi } from "vitest";
import { FIX } from "./fixtures";
import type { AnalyzeResponse } from "@/lib/api/types";

vi.mock("next/link", () => ({ default: ({ href, children, ...rest }: { href: string; children: React.ReactNode }) => <a href={href} {...rest}>{children}</a> }));
vi.mock("@/components/layout/BackendProvider", () => ({
  useBackend: () => ({
    health: { data: null, error: null, loading: false, reload: () => {} },
    catalog: { data: null, error: null, loading: false, reload: () => {} },
    examples: { data: null, error: null, loading: false, reload: () => {} },
  }),
}));
// Recharts needs real layout; chart geometry is covered by the Playwright tests.
vi.mock("@/components/analytics/ResultChart", () => ({ ResultChart: () => <div data-testid="chart-stub" />, toRows: () => [] }));

import { AnalysisView } from "@/components/analytics/AnalysisView";
import { ModeDisclosure } from "@/components/analytics/ModeDisclosure";
import { EvidencePanel } from "@/components/evidence/EvidencePanel";
import { fromAnalyze, fromAudit } from "@/lib/evidence-model";
import { ResultTable } from "@/components/analytics/ResultTable";
import { TransportError } from "@/components/analytics/TransportError";
import { ApiError } from "@/lib/api/client";

const view = (r: AnalyzeResponse, onAsk = vi.fn(), onEdit = vi.fn()) => { render(<AnalysisView r={r} onAsk={onAsk} onEdit={onEdit} />); return { onAsk, onEdit }; };

describe("ModeDisclosure", () => {
  it("shows the backend disclosure verbatim for DEMO_RULE_BASED", () => {
    render(<ModeDisclosure planner={FIX.verified.planner} />);
    const el = screen.getByTestId("mode-disclosure");
    expect(el).toHaveAttribute("data-mode", "DEMO_RULE_BASED");
    expect(el).toHaveTextContent(FIX.verified.planner.disclosure!);
    expect(el).toHaveTextContent(/not an LLM/i);
  });
  it("shows provider and model, not the demo label, for LLM mode", () => {
    render(<ModeDisclosure planner={{ name: "langchain-meta", provider: "meta", model: "muse-spark-1.3", execution_mode: "LLM", disclosure: null }} />);
    const el = screen.getByTestId("mode-disclosure");
    expect(el).toHaveAttribute("data-mode", "LLM");
    expect(screen.getByTestId("llm-label")).toHaveTextContent("Meta Model API · muse-spark-1.3");
    expect(el).not.toHaveTextContent(/Demo Planner/);
  });
  it.each([
    ["VERIFIED", /generated by deterministic code and executed on IBM Db2/],
    ["AMBIGUOUS", /No SQL was generated or run on IBM Db2/],
    ["BLOCKED", /No SQL was generated or run on IBM Db2/],
    ["EXECUTION_FAILED", /IBM Db2 did not complete it/],
  ] as const)("LLM disclosure for %s never claims SQL ran when it did not", (status, text) => {
    render(<ModeDisclosure status={status} planner={{ name: "langchain-meta", provider: "meta", model: "muse-spark-1.3", execution_mode: "LLM", disclosure: null }} />);
    expect(screen.getByTestId("llm-sentence")).toHaveTextContent(text);
    if (status !== "VERIFIED") expect(screen.getByTestId("llm-sentence")).not.toHaveTextContent(/executed on IBM Db2/);
  });
});

describe("AnalysisView by status (recorded real responses)", () => {
  it("VERIFIED: headline, summary, evidence verdict, 11 checks, SQL and demo disclosure", () => {
    view(FIX.verified);
    expect(screen.getByTestId("analysis-view")).toHaveAttribute("data-status", "VERIFIED");
    expect(screen.getByTestId("headline-value")).toHaveTextContent(FIX.verified.answer!.headline!.formatted);
    expect(screen.getByTestId("verdict-status")).toHaveTextContent("Verified");
    expect(screen.getByTestId("checks-list").querySelectorAll("li")).toHaveLength(11);
    expect(screen.getByTestId("sql-text")).toHaveTextContent("WITH eligible_orders");
    expect(screen.getByTestId("mode-disclosure")).toBeInTheDocument();
    expect(screen.getByText(/does not certify that the underlying data is correct/i)).toBeInTheDocument();
  });

  it("VERIFIED with several KPI metrics renders tiles from result rows", () => {
    view(FIX.verified);
    const tiles = screen.getByTestId("kpi-tiles");
    expect(within(tiles).getByText("Order Count")).toBeInTheDocument();
    expect(within(tiles).getByText("$274.83")).toBeInTheDocument();
  });

  it("EXECUTED_WITH_WARNINGS: warning banner lists the backend warning", () => {
    view(FIX.warnings);
    expect(screen.getByTestId("warning-banner")).toHaveTextContent(/RANGE|have no data|coverage/i);
    expect(screen.getByTestId("verdict-status")).toHaveTextContent("Executed with warnings");
  });

  it("AMBIGUOUS: one button per option; click re-submits suggested_question verbatim; no numbers", async () => {
    const { onAsk, onEdit } = view(FIX.ambiguous);
    expect(screen.queryByTestId("headline-value")).not.toBeInTheDocument();
    for (const o of FIX.ambiguous.clarification!.options) {
      expect(screen.getByTestId(`clarify-${o.id}`)).toBeInTheDocument();
    }
    await userEvent.click(screen.getByTestId("clarify-net_revenue"));
    expect(onAsk).toHaveBeenCalledWith(FIX.ambiguous.clarification!.options.find((o) => o.id === "net_revenue")!.suggested_question);
    await userEvent.click(screen.getByRole("button", { name: /revise the question/i }));
    expect(onEdit).toHaveBeenCalled();
  });

  it("BLOCKED (write intent): says nothing executed, shows reason, no numbers, no SQL", () => {
    view(FIX.blocked);
    expect(screen.getByTestId("blocked-no-sql")).toHaveTextContent(/No SQL was executed/);
    expect(screen.getByTestId("blocked-reasons")).toHaveTextContent("WRITE_INTENT");
    expect(screen.queryByTestId("headline-value")).not.toBeInTheDocument();
    expect(screen.getByTestId("no-sql")).toBeInTheDocument();
    expect(screen.queryByTestId("sql-block")).not.toBeInTheDocument();
  });

  it("BLOCKED (policy): shows the dimension reason", () => {
    view(FIX.blockedPolicy);
    expect(screen.getByTestId("blocked-reasons")).toHaveTextContent("DIMENSION_NOT_ALLOWED");
  });

  it("EXECUTION_FAILED: shows SQLSTATE and retry, never numbers or a verified badge", async () => {
    const { onAsk } = view(FIX.failed);
    expect(screen.getByTestId("failed-error")).toHaveTextContent(FIX.failed.error!.sqlstate!);
    expect(screen.queryByTestId("headline-value")).not.toBeInTheDocument();
    expect(screen.queryByText("Verified", { selector: "[data-testid=status-badge]" })).not.toBeInTheDocument();
    await userEvent.click(screen.getByTestId("retry"));
    expect(onAsk).toHaveBeenCalledWith(FIX.failed.question);
    // the attempted SQL is still available for transparency
    expect(screen.getByTestId("sql-text")).toBeInTheDocument();
  });
});

describe("EvidencePanel", () => {
  it("expands and collapses sections", async () => {
    render(<EvidencePanel model={fromAnalyze(FIX.verified)} />);
    const toggle = screen.getByRole("button", { name: /Query parameters/ });
    expect(toggle).toHaveAttribute("aria-expanded", "false");
    await userEvent.click(toggle);
    expect(toggle).toHaveAttribute("aria-expanded", "true");
    expect(screen.getByTestId("params-table")).toHaveTextContent("eligible_status_1");
    await userEvent.click(toggle);
    expect(toggle).toHaveAttribute("aria-expanded", "false");
  });

  it("copies the exact SQL text", async () => {
    const writeText = vi.fn().mockResolvedValue(undefined);
    Object.defineProperty(navigator, "clipboard", { value: { writeText }, configurable: true });
    render(<EvidencePanel model={fromAnalyze(FIX.verified)} />);
    fireEvent.click(screen.getByTestId("copy-sql"));
    await vi.waitFor(() => expect(writeText).toHaveBeenCalledWith(FIX.verified.sql!.text));
    expect(await screen.findByText("Copied")).toBeInTheDocument();
  });

  it("flags unlogged requests when audit.persisted is false", () => {
    render(<EvidencePanel model={fromAnalyze({ ...FIX.verified, audit: { persisted: false, url: null } } as AnalyzeResponse)} />);
    expect(screen.getByTestId("audit-not-persisted")).toBeInTheDocument();
    expect(screen.queryByTestId("audit-link")).not.toBeInTheDocument();
  });

  it("renders a stored audit record, including the EXECUTION_FAILED SQL and mode", () => {
    render(<EvidencePanel model={fromAudit(FIX.auditDetail)} />);
    expect(screen.getByTestId("verdict-status")).toHaveTextContent("Execution failed");
    expect(screen.getByTestId("sql-text")).toBeInTheDocument();
    expect(screen.getByTestId("request-id")).toHaveTextContent(FIX.auditDetail.request_id);
  });
});

describe("ResultTable", () => {
  it("shows null metrics as undefined, never zero", () => {
    render(<ResultTable result={{ columns: [{ name: "region", label: "Region", role: "dimension", data_type: "string" }, { name: "aov", label: "AOV", role: "metric", data_type: "decimal", unit: "USD", scale: 2 }], rows: [{ region: "NA", aov: null }], row_count: 1, truncated: false }} />);
    expect(screen.getByText("—")).toBeInTheDocument();
    expect(screen.queryByText("$0.00")).not.toBeInTheDocument();
  });
});

describe("TransportError", () => {
  it("planner_unavailable never claims a demo fallback happened", () => {
    render(<TransportError error={new ApiError("planner_unavailable", "No key", 503, "PLANNER_UNAVAILABLE")} onRetry={() => {}} />);
    expect(screen.getByTestId("transport-error")).toHaveAttribute("data-kind", "planner_unavailable");
    expect(screen.getByText("AI planner unavailable")).toBeInTheDocument();
    expect(screen.getByText(/does not silently switch to the demo planner/)).toBeInTheDocument();
  });
});
