-- Secondary indexes. Primary/unique keys above already create their own indexes.

-- Metric queries always filter eligible orders by status + order date range.
CREATE INDEX METRICGUARD.IX_ORDERS_STATUS_TS ON METRICGUARD.ORDERS (STATUS, ORDER_TS);
CREATE INDEX METRICGUARD.IX_ORDERS_TS ON METRICGUARD.ORDERS (ORDER_TS);
CREATE INDEX METRICGUARD.IX_ORDERS_REGION_CHANNEL ON METRICGUARD.ORDERS (REGION_CODE, CHANNEL_CODE);

-- FK / join support.
CREATE INDEX METRICGUARD.IX_ORDER_ITEMS_ORDER ON METRICGUARD.ORDER_ITEMS (ORDER_ID);
CREATE INDEX METRICGUARD.IX_ORDER_ITEMS_PRODUCT ON METRICGUARD.ORDER_ITEMS (PRODUCT_ID);
CREATE INDEX METRICGUARD.IX_PRODUCTS_CATEGORY ON METRICGUARD.PRODUCTS (CATEGORY);

-- Refund pre-aggregation (status filter + per-line grouping) and order lookups.
CREATE INDEX METRICGUARD.IX_REFUNDS_STATUS_ITEM ON METRICGUARD.REFUNDS (STATUS, ORDER_ITEM_ID, REFUND_AMOUNT);
CREATE INDEX METRICGUARD.IX_REFUNDS_ORDER ON METRICGUARD.REFUNDS (ORDER_ID);
CREATE INDEX METRICGUARD.IX_REFUNDS_TS ON METRICGUARD.REFUNDS (REFUND_TS);

-- Audit browsing (newest first, optionally by status).
CREATE INDEX METRICGUARD.IX_AUDIT_CREATED ON METRICGUARD.QUERY_AUDIT_LOG (CREATED_AT DESC);
CREATE INDEX METRICGUARD.IX_AUDIT_STATUS_CREATED ON METRICGUARD.QUERY_AUDIT_LOG (STATUS, CREATED_AT DESC);
