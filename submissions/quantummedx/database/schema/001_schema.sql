-- QuantumMedX schema for IBM Db2 (LUW). Statements are separated by a line containing only ';;'
CREATE TABLE USERS (
  USER_ID INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
  USERNAME VARCHAR(64) NOT NULL UNIQUE,
  EMAIL VARCHAR(255) NOT NULL UNIQUE,
  PASSWORD_HASH VARCHAR(255) NOT NULL,
  ROLE VARCHAR(16) NOT NULL DEFAULT 'RESEARCHER' CHECK (ROLE IN ('ADMIN','RESEARCHER')),
  IS_ACTIVE SMALLINT NOT NULL DEFAULT 1,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
)
;;
CREATE TABLE DATASETS (
  DATASET_ID INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
  OWNER_ID INTEGER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
  NAME VARCHAR(255) NOT NULL,
  SOURCE VARCHAR(255),
  STORAGE_REF VARCHAR(512) NOT NULL,
  TARGET_COLUMN VARCHAR(128),
  STATUS VARCHAR(16) NOT NULL DEFAULT 'UPLOADED',
  UPLOADED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
)
;;
CREATE INDEX IDX_DATASETS_OWNER ON DATASETS (OWNER_ID, UPLOADED_AT)
;;
CREATE TABLE DATASET_METADATA (
  DATASET_ID INTEGER NOT NULL PRIMARY KEY REFERENCES DATASETS(DATASET_ID) ON DELETE CASCADE,
  ROW_COUNT INTEGER NOT NULL,
  COLUMN_COUNT INTEGER NOT NULL,
  DUPLICATE_ROWS INTEGER NOT NULL DEFAULT 0,
  SCHEMA_JSON CLOB(1M) NOT NULL,
  MISSING_JSON CLOB(1M) NOT NULL,
  STATS_JSON CLOB(1M)
)
;;
CREATE TABLE PREPROCESSING_CONFIGS (
  CONFIG_ID INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
  DATASET_ID INTEGER NOT NULL REFERENCES DATASETS(DATASET_ID) ON DELETE CASCADE,
  CONFIG_JSON CLOB(1M) NOT NULL,
  RANDOM_SEED INTEGER NOT NULL,
  TEST_SIZE DECIMAL(4,3) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
)
;;
CREATE TABLE EXPERIMENTS (
  EXPERIMENT_ID INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
  DATASET_ID INTEGER NOT NULL REFERENCES DATASETS(DATASET_ID) ON DELETE CASCADE,
  CONFIG_ID INTEGER REFERENCES PREPROCESSING_CONFIGS(CONFIG_ID),
  MODEL_FAMILY VARCHAR(16) NOT NULL CHECK (MODEL_FAMILY IN ('CLASSICAL','QUANTUM')),
  ALGORITHM VARCHAR(64) NOT NULL,
  PARAMS_JSON CLOB(1M),
  STATUS VARCHAR(16) NOT NULL DEFAULT 'QUEUED',
  ERROR_MESSAGE VARCHAR(1024),
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  FINISHED_AT TIMESTAMP
)
;;
CREATE INDEX IDX_EXPERIMENTS_DATASET ON EXPERIMENTS (DATASET_ID, MODEL_FAMILY, STATUS)
;;
CREATE TABLE MODEL_RESULTS (
  RESULT_ID INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
  EXPERIMENT_ID INTEGER NOT NULL UNIQUE REFERENCES EXPERIMENTS(EXPERIMENT_ID) ON DELETE CASCADE,
  ACCURACY DECIMAL(7,6), PRECISION_SCORE DECIMAL(7,6), RECALL DECIMAL(7,6),
  F1_SCORE DECIMAL(7,6), ROC_AUC DECIMAL(7,6),
  CONFUSION_JSON VARCHAR(512),
  TRAIN_SECONDS DECIMAL(10,4), INFER_SECONDS DECIMAL(10,4),
  BACKEND_INFO VARCHAR(255),
  EXTRA_JSON CLOB(1M)
)
;;
CREATE TABLE AGENT_RUNS (
  RUN_ID INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
  DATASET_ID INTEGER NOT NULL REFERENCES DATASETS(DATASET_ID) ON DELETE CASCADE,
  STARTED_BY INTEGER NOT NULL REFERENCES USERS(USER_ID),
  RUN_MODE VARCHAR(16) NOT NULL DEFAULT 'CREWAI' CHECK (RUN_MODE IN ('CREWAI','DETERMINISTIC')),
  STATUS VARCHAR(16) NOT NULL DEFAULT 'RUNNING',
  ERROR_MESSAGE VARCHAR(1024),
  STARTED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  FINISHED_AT TIMESTAMP
)
;;
CREATE TABLE AGENT_ACTIVITIES (
  ACTIVITY_ID INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
  RUN_ID INTEGER NOT NULL REFERENCES AGENT_RUNS(RUN_ID) ON DELETE CASCADE,
  AGENT_NAME VARCHAR(64) NOT NULL,
  TOOL_NAME VARCHAR(64),
  STATUS VARCHAR(16) NOT NULL,
  INPUT_REF VARCHAR(512),
  OUTPUT_SUMMARY CLOB(1M),
  ERROR_MESSAGE VARCHAR(1024),
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
)
;;
CREATE INDEX IDX_ACTIVITIES_RUN ON AGENT_ACTIVITIES (RUN_ID, CREATED_AT)
;;
CREATE TABLE RESEARCH_REPORTS (
  REPORT_ID INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
  RUN_ID INTEGER REFERENCES AGENT_RUNS(RUN_ID) ON DELETE SET NULL,
  DATASET_ID INTEGER NOT NULL REFERENCES DATASETS(DATASET_ID) ON DELETE CASCADE,
  TITLE VARCHAR(255) NOT NULL,
  BODY_MD CLOB(4M) NOT NULL,
  STATUS VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
)
;;
CREATE TABLE AUDIT_LOGS (
  LOG_ID BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
  USER_ID INTEGER REFERENCES USERS(USER_ID) ON DELETE SET NULL,
  EVENT_TYPE VARCHAR(64) NOT NULL,
  DETAILS VARCHAR(1024),
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
)
