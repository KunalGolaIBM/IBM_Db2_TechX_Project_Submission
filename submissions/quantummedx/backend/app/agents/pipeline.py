"""Runs a full analysis for one dataset, logs every step in Db2 and stores a verified report."""
import os

from app.agents.report import build_report, template_narrative
from app.agents.tools import Toolbox


def run_pipeline(repo, dataset: dict, target: str, user_id: int, mode: str, run_id: int) -> int:
    box = Toolbox(repo, dataset, target, run_id)
    try:
        if mode == "CREWAI":
            from app.agents.crew import build_crew, make_llm
            result = build_crew(box, make_llm()).kickoff()
            narrative = str(getattr(result, "raw", result))
            source = f"written by CrewAI agents using model {os.getenv('LLM_PROVIDER')}/{os.getenv('LLM_MODEL')}"
        else:
            narrative, source = None, "template text generated by the backend; no LLM was used"
        # Guarantee every step exists even if an LLM agent skipped a tool; these calls are logged too.
        if "data_quality" not in box.out: box.data_quality()
        if "feature_patterns" not in box.out: box.feature_patterns()
        if mode == "DETERMINISTIC" or "run_classical" not in box.out:
            for algo in ("logistic_regression", "random_forest"):
                box.run_classical(algo)
        if mode == "DETERMINISTIC" or "run_quantum" not in box.out:
            box.run_quantum()
        results = box.stored_results()["results"]
        if narrative is None:
            narrative = template_narrative(box.out["data_quality"], box.out["feature_patterns"], results)
        body, bad = build_report(dataset, box.out["data_quality"], box.out["feature_patterns"], results, narrative, source)
        report_id = repo.save_report(run_id, dataset["dataset_id"], f"QuantumMedX report: {dataset['name']}", body,
                                     "FINAL" if not bad else "NEEDS_REVIEW")
        repo.finish_agent_run(run_id, "COMPLETED")
        return report_id
    except Exception as exc:
        repo.finish_agent_run(run_id, "FAILED", str(exc))
        raise
