from __future__ import annotations

import json
import os
from typing import Any, Dict

try:
    from langchain_core.prompts import PromptTemplate
    from langchain_core.output_parsers import JsonOutputParser
except ImportError:  # pragma: no cover
    PromptTemplate = None
    JsonOutputParser = None


def build_fallback_recommendation(studio: Dict[str, Any]) -> Dict[str, Any]:
    revenue = float(studio.get("revenue", 0))
    expenses = float(studio.get("expenses", 0))
    profit = revenue - expenses
    trend = str(studio.get("market_trend", "stable")).lower()
    reputation = float(studio.get("reputation", 0))
    marketing_budget = float(studio.get("marketing_budget", 0))

    if profit > 0 and reputation >= 75:
        recommendation = "Expand your strongest-performing franchise and increase release frequency in adjacent genres."
    elif trend in {"rising", "growth", "upward"}:
        recommendation = "Increase marketing spend and accelerate the release calendar to capture market momentum."
    elif marketing_budget < 50000:
        recommendation = "Reallocate capital into audience acquisition and test screenings to improve early feedback quality."
    else:
        recommendation = "Reduce cost pressure, prioritize the best-performing titles, and keep production pacing disciplined."

    return {
        "recommendation": recommendation,
        "reason": "This strategy uses studio analytics and market trend signals to recommend a safe next move with a clear business rationale.",
        "source": "local_fallback",
    }


def build_langchain_recommendation(studio: Dict[str, Any]) -> Dict[str, Any]:
    if PromptTemplate is None or JsonOutputParser is None:
        return build_fallback_recommendation(studio)

    openai_key = os.getenv("OPENAI_API_KEY")
    if not openai_key:
        return build_fallback_recommendation(studio)

    try:
        from langchain_openai import ChatOpenAI
    except ImportError:  # pragma: no cover
        return build_fallback_recommendation(studio)

    try:
        model = ChatOpenAI(model="gpt-4o-mini", api_key=openai_key)
        prompt = PromptTemplate(
            template=(
                "You are a movie studio strategy advisor. Based on the studio metrics below, provide a single concise recommendation and a short rationale. "
                "Return valid JSON with keys: recommendation, reason.\n\nStudio: {studio_summary}"
            )
        )
        chain = prompt | model | JsonOutputParser()
        result = chain.invoke({"studio_summary": json.dumps(studio, default=str)})
        return {
            "recommendation": str(result.get("recommendation", "Focus on the strongest-performing release window.")),
            "reason": str(result.get("reason", "Generated by the configured model using studio analytics.")),
            "source": "langchain",
        }
    except Exception:
        return build_fallback_recommendation(studio)


def build_strategy(studio: Dict[str, Any]) -> Dict[str, Any]:
    try:
        return build_langchain_recommendation(studio)
    except Exception:
        return build_fallback_recommendation(studio)
