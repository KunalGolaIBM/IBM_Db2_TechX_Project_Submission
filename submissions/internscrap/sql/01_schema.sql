-- 1. COMPANIES TABLE
CREATE TABLE COMPANIES (
    ID          INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    NAME        VARCHAR(150) NOT NULL,
    WEBSITE     VARCHAR(255),
    LOCATION    VARCHAR(120),
    INDUSTRY    VARCHAR(100) DEFAULT 'Technology',
    TIER        VARCHAR(20)  DEFAULT 'Mid' CHECK (TIER IN ('Startup', 'Mid', 'Enterprise', 'FAANG')),
    CREATED_AT  TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_COMPANIES PRIMARY KEY (ID),
    CONSTRAINT UQ_COMPANY_NAME UNIQUE (NAME)
);

-- 2. INTERNSHIPS TABLE
CREATE TABLE INTERNSHIPS (
    ID              INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    TITLE           VARCHAR(200) NOT NULL,
    COMPANY_ID      INTEGER NOT NULL,
    LOCATION        VARCHAR(150) DEFAULT 'Remote',
    IS_REMOTE       SMALLINT DEFAULT 1 CHECK (IS_REMOTE IN (0, 1)),
    STIPEND_MIN     DECIMAL(10, 2),
    STIPEND_MAX     DECIMAL(10, 2),
    CURRENCY        VARCHAR(10) DEFAULT 'USD',
    APPLY_URL       VARCHAR(1000) NOT NULL,
    SOURCE          VARCHAR(50) DEFAULT 'Direct',
    EXTERNAL_ID     VARCHAR(100),
    POSTED_DATE     DATE DEFAULT CURRENT DATE,
    DEADLINE        DATE,
    STATUS          VARCHAR(20) DEFAULT 'ACTIVE' CHECK (STATUS IN ('ACTIVE', 'EXPIRED', 'ARCHIVED')),
    CREATED_AT      TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    UPDATED_AT      TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_INTERNSHIPS PRIMARY KEY (ID),
    CONSTRAINT FK_INTERNSHIP_COMPANY FOREIGN KEY (COMPANY_ID) 
        REFERENCES COMPANIES (ID) ON DELETE CASCADE,
    CONSTRAINT UQ_EXTERNAL_SOURCE UNIQUE (SOURCE, EXTERNAL_ID)
);

-- 3. SKILLS MASTER TABLE
CREATE TABLE SKILLS (
    ID          INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    NAME        VARCHAR(80) NOT NULL,
    CATEGORY    VARCHAR(50) DEFAULT 'General',
    CONSTRAINT PK_SKILLS PRIMARY KEY (ID),
    CONSTRAINT UQ_SKILL_NAME UNIQUE (NAME)
);

-- 4. INTERNSHIP_SKILLS (Many-to-Many Bridge Table)
CREATE TABLE INTERNSHIP_SKILLS (
    INTERNSHIP_ID   INTEGER NOT NULL,
    SKILL_ID        INTEGER NOT NULL,
    CONSTRAINT PK_INTERNSHIP_SKILLS PRIMARY KEY (INTERNSHIP_ID, SKILL_ID),
    CONSTRAINT FK_IS_INTERNSHIP FOREIGN KEY (INTERNSHIP_ID)
        REFERENCES INTERNSHIPS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_IS_SKILL FOREIGN KEY (SKILL_ID)
        REFERENCES SKILLS (ID) ON DELETE CASCADE
);

-- 5. APPLICATIONS TRACKER TABLE
CREATE TABLE APPLICATIONS (
    ID              INTEGER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    INTERNSHIP_ID   INTEGER NOT NULL,
    USER_IDENTIFIER VARCHAR(100) DEFAULT 'local_user',
    STATUS          VARCHAR(25) DEFAULT 'WISHLIST' 
                    CHECK (STATUS IN ('WISHLIST', 'APPLIED', 'ONLINE_ASSESSMENT', 'INTERVIEWING', 'OFFER', 'REJECTED')),
    APPLIED_DATE    DATE,
    FOLLOW_UP_DATE  DATE,
    NOTES           VARCHAR(2000),
    CREATED_AT      TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    UPDATED_AT      TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_APPLICATIONS PRIMARY KEY (ID),
    CONSTRAINT FK_APP_INTERNSHIP FOREIGN KEY (INTERNSHIP_ID)
        REFERENCES INTERNSHIPS (ID) ON DELETE CASCADE,
    CONSTRAINT UQ_USER_INTERNSHIP UNIQUE (USER_IDENTIFIER, INTERNSHIP_ID)
);

-- ========================================================================
-- Db2 PERFORMANCE INDEXES
-- ========================================================================
CREATE INDEX IX_INT_COMPANY ON INTERNSHIPS (COMPANY_ID);
CREATE INDEX IX_INT_DEADLINE ON INTERNSHIPS (DEADLINE);
CREATE INDEX IX_INT_REMOTE ON INTERNSHIPS (IS_REMOTE);
CREATE INDEX IX_INT_STATUS ON INTERNSHIPS (STATUS);
CREATE INDEX IX_APP_STATUS ON APPLICATIONS (STATUS);
CREATE INDEX IX_APP_FOLLOWUP ON APPLICATIONS (FOLLOW_UP_DATE);
