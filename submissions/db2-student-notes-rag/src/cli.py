"""
Interactive Student Study Assistant CLI.
Query student exam notes stored in IBM Db2 with native Vector Similarity Search.
"""

import sys
import argparse
from pathlib import Path

from config import Db2RAGConfig
from db2_client import verify_db2_connection
from rag_engine import StudentNotesRAG
from ingest import run_ingestion


def print_banner():
    banner = r"""
  ___ ____  __  __   ____  _     ____ 
 |_ _| __ )|  \/  | |  _ \| |__ |___ \
  | ||  _ \| |\/| | | | | | '_ \  __) |
  | || |_) | |  | | | |_| | |_) |/ __/ 
 |___|____/|_|  |_| |____/|_.__/|_____|
  IBM Db2 Native Vector Search Study Assistant
    """
    print(banner)


def cmd_status():
    print("\n--- IBM Db2 Connection & System Diagnostics ---")
    is_up, msg = verify_db2_connection()
    status_icon = "🟢" if is_up else "🟡"
    print(f"Status:        {status_icon} {msg}")
    print(f"Db2 Host:      {Db2RAGConfig.DB2_HOST}:{Db2RAGConfig.DB2_PORT}")
    print(f"Database:      {Db2RAGConfig.DB2_DATABASE}")
    print(f"Vector Table:  {Db2RAGConfig.DB2_TABLE_NAME}")
    print(f"Embedding:     {Db2RAGConfig.EMBEDDING_MODEL} ({Db2RAGConfig.EMBEDDING_DIM}-dim)")
    print(f"Distance:      {Db2RAGConfig.DISTANCE_STRATEGY}")
    print(f"Top-K Chunks:  {Db2RAGConfig.TOP_K}")
    print("-----------------------------------------------\n")


def cmd_search(query: str, k: int):
    print(f"\n🔍 Searching IBM Db2 Vector Store for: '{query}' (top {k} hits)...")
    rag = StudentNotesRAG()
    results = rag.retrieve_relevant_notes(query, k=k)

    if not results:
        print("No matching notes found.")
        return

    for i, res in enumerate(results, 1):
        meta = res.get("metadata", {})
        title = meta.get("section_title", "Untitled Section")
        topic = meta.get("topic", "General")
        score = res.get("score")
        score_str = f" [Cosine Score: {score:.4f}]" if score is not None else ""
        print(f"\n[{i}] {title}{score_str}")
        print(f"    Topic: {topic} | Doc ID: {meta.get('doc_id')}")
        snippet = res["content"].strip().replace("\n", "\n    ")
        print(f"    Content:\n    {snippet}\n")


def cmd_ask(question: str):
    print(f"\n🎓 Student Question: {question}")
    print("⏳ Searching IBM Db2 vector embeddings and synthesizing answer...\n")
    rag = StudentNotesRAG()
    res = rag.answer_question(question)

    print("=" * 65)
    print(res["answer"])
    print("=" * 65)

    print(f"\n📚 Citations & Context ({res['retrieved_count']} chunks retrieved from Db2):")
    for s in res["sources"]:
        formula_badge = " [Formulas Included]" if s["has_formula"] else ""
        score_badge = f" (Score: {s['score']})" if s['score'] else ""
        print(f" • {s['section_title']} ({s['topic']}){score_badge}{formula_badge}")

    print(f"\nGenerated by: {res['provider']}")


def cmd_chat():
    print_banner()
    print("Welcome to your IBM Db2 Student Notes Assistant!")
    print("Type your questions below. Type 'exit' or 'quit' to end.\n")

    rag = StudentNotesRAG()
    while True:
        try:
            q = input("\nStudent > ").strip()
            if not q:
                continue
            if q.lower() in ["exit", "quit", "q"]:
                print("Happy studying! Goodbye.")
                break

            res = rag.answer_question(q)
            print("\nProfessor AI >\n")
            print(res["answer"])
            print("\n--- Citations from Db2 Notes ---")
            for s in res["sources"]:
                print(f" • {s['section_title']} (Topic: {s['topic']})")
        except (KeyboardInterrupt, EOFError):
            print("\nExiting. Goodbye!")
            break


def main():
    parser = argparse.ArgumentParser(
        description="IBM Db2 LangChain Vector Search Study Assistant CLI"
    )
    subparsers = parser.add_subparsers(dest="command", help="Subcommand to run")

    # Ask
    ask_parser = subparsers.add_parser("ask", help="Ask a question against your notes")
    ask_parser.add_argument("question", type=str, help="Question text")

    # Search
    search_parser = subparsers.add_parser("search", help="Raw vector similarity search")
    search_parser.add_argument("query", type=str, help="Search query")
    search_parser.add_argument("-k", type=int, default=3, help="Number of results")

    # Ingest
    ingest_parser = subparsers.add_parser("ingest", help="Ingest notes file into Db2")
    ingest_parser.add_argument(
        "--file",
        "-f",
        default=str(Path(__file__).resolve().parent.parent / "data" / "notes.md"),
        help="Path to markdown notes file",
    )
    ingest_parser.add_argument("--table", "-t", default=Db2RAGConfig.DB2_TABLE_NAME)

    # Status
    subparsers.add_parser("status", help="Check IBM Db2 connection status")

    # Interactive Chat
    subparsers.add_parser("chat", help="Start interactive student study session")

    args = parser.parse_args()

    if args.command == "ask":
        cmd_ask(args.question)
    elif args.command == "search":
        cmd_search(args.query, args.k)
    elif args.command == "ingest":
        run_ingestion(args.file, args.table)
    elif args.command == "status":
        cmd_status()
    elif args.command == "chat":
        cmd_chat()
    else:
        print_banner()
        cmd_status()
        print("Usage Examples:")
        print("  python cli.py ingest --file ../data/notes.md")
        print('  python cli.py ask "Explain Friis transmission equation"')
        print('  python cli.py search "RAKE receiver"')
        print("  python cli.py chat")


if __name__ == "__main__":
    main()

