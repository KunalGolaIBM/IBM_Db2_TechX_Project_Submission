-- 1. Create dedicated least-privilege database roles
CREATE ROLE BAKEBOX_APP_ROLE;
CREATE ROLE BAKEBOX_READER_ROLE;

-- 2. Reader Role: Read-only catalog & masked view access (NO raw PII table access)
GRANT CONNECT ON DATABASE TO ROLE BAKEBOX_READER_ROLE;
GRANT SELECT ON TABLE BB_CAKES TO ROLE BAKEBOX_READER_ROLE;
GRANT SELECT ON TABLE BB_INVENTORY TO ROLE BAKEBOX_READER_ROLE;
GRANT SELECT ON TABLE BB_RECIPES TO ROLE BAKEBOX_READER_ROLE;
GRANT SELECT ON TABLE BB_INGREDIENT_COMPONENTS TO ROLE BAKEBOX_READER_ROLE;
GRANT SELECT ON VIEW V_ACTIVE_BAKERY_ORDERS TO ROLE BAKEBOX_READER_ROLE;
GRANT SELECT ON VIEW V_MASKED_BAKERY_ORDERS TO ROLE BAKEBOX_READER_ROLE;

-- 3. Application Role: Minimum operational DML (NO DROP/ALTER, NO audit tampering)
GRANT CONNECT ON DATABASE TO ROLE BAKEBOX_APP_ROLE;
GRANT SELECT, INSERT, UPDATE ON TABLE BB_ORDERS TO ROLE BAKEBOX_APP_ROLE;
GRANT SELECT, INSERT ON TABLE BB_ORDER_ITEMS TO ROLE BAKEBOX_APP_ROLE;
GRANT SELECT, UPDATE ON TABLE BB_CAKES TO ROLE BAKEBOX_APP_ROLE;
GRANT SELECT, UPDATE ON TABLE BB_INVENTORY TO ROLE BAKEBOX_APP_ROLE;
GRANT SELECT ON TABLE BB_RECIPES TO ROLE BAKEBOX_APP_ROLE;
GRANT SELECT ON TABLE BB_INGREDIENT_COMPONENTS TO ROLE BAKEBOX_APP_ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE BB_CHUNKS_VECTOR TO ROLE BAKEBOX_APP_ROLE;
GRANT SELECT, INSERT, DELETE ON TABLE BB_USER_CONVERSATION_BUFFER TO ROLE BAKEBOX_APP_ROLE;
GRANT SELECT ON VIEW V_ACTIVE_BAKERY_ORDERS TO ROLE BAKEBOX_APP_ROLE;
GRANT SELECT ON VIEW V_MASKED_BAKERY_ORDERS TO ROLE BAKEBOX_APP_ROLE;
GRANT USAGE ON SEQUENCE SEQ_BB_ORDER_ID TO ROLE BAKEBOX_APP_ROLE;
GRANT EXECUTE ON PROCEDURE SP_RESERVE_CAKE_STOCK TO ROLE BAKEBOX_APP_ROLE;

-- 4. Enforce Append-Only Immutability on Cryptographic Audit Trail (BB_AUDIT_LOG)
--    Application service receives SELECT and INSERT ONLY; UPDATE and DELETE are intentionally omitted.
GRANT SELECT, INSERT ON TABLE BB_AUDIT_LOG TO ROLE BAKEBOX_APP_ROLE;

-- 5. Safe Masked Operational View (protects short phone values from SQL0138N)
CREATE OR REPLACE VIEW V_MASKED_BAKERY_ORDERS AS
SELECT
    order_id,
    SUBSTR(customer_name, 1, 1) || '****' AS masked_customer_name,
    CASE
        WHEN LENGTH(COALESCE(phone_last10, '')) >= 4
        THEN '+91 ******' || RIGHT(phone_last10, 4)
        ELSE '******'
    END AS masked_phone,
    order_type,
    order_status,
    total_amount,
    created_at
FROM BB_ORDERS;

GRANT SELECT ON VIEW V_MASKED_BAKERY_ORDERS TO ROLE BAKEBOX_READER_ROLE;
GRANT SELECT ON VIEW V_MASKED_BAKERY_ORDERS TO ROLE BAKEBOX_APP_ROLE;

