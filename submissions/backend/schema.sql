CREATE TABLE SCHOLARSHIPS (
  ID VARCHAR(32) NOT NULL PRIMARY KEY,
  NAME VARCHAR(200) NOT NULL,
  PROVIDER VARCHAR(200),
  COUNTRY VARCHAR(100),
  STUDY_LEVELS VARCHAR(500),
  FIELDS VARCHAR(500),
  MIN_GPA DOUBLE,
  FUNDING VARCHAR(120),
  DEADLINE VARCHAR(20),
  DESCRIPTION VARCHAR(2000),
  REQUIREMENTS VARCHAR(1000),
  SOURCE_URL VARCHAR(500)
);
