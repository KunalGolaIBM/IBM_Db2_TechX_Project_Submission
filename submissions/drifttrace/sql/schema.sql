-- DriftTrace schema (IBM Db2 LUW). Created in the connection's current schema.
-- seed.py splits on ';' and runs each CREATE only when the object is absent
-- (idempotent; never drops or clears data).

CREATE TABLE DT_INSTRUMENTS (
  ID VARCHAR(32) NOT NULL PRIMARY KEY,
  NAME VARCHAR(120) NOT NULL,
  LAST_VERIFIED_AT TIMESTAMP,
  VERIFICATION_REF VARCHAR(64)
);

CREATE TABLE DT_LOTS (
  ID VARCHAR(32) NOT NULL PRIMARY KEY,
  PRODUCT_NAME VARCHAR(120) NOT NULL,
  PRODUCED_QUANTITY INTEGER NOT NULL,
  CONSTRAINT DT_LOTS_QTY_CK CHECK (PRODUCED_QUANTITY > 0)
);

CREATE TABLE DT_INSPECTIONS (
  ID VARCHAR(32) NOT NULL PRIMARY KEY,
  INSTRUMENT_ID VARCHAR(32) NOT NULL,
  LOT_ID VARCHAR(32) NOT NULL,
  MEASURED_AT TIMESTAMP,
  FUNCTION_CODE VARCHAR(40) NOT NULL,
  UNIT VARCHAR(8),
  RECORDED_VALUE DECIMAL(12,4),
  LOWER_LIMIT DECIMAL(12,4),
  UPPER_LIMIT DECIMAL(12,4),
  ORIGINAL_DECISION VARCHAR(16) NOT NULL,
  CONSTRAINT DT_INSP_INSTR_FK FOREIGN KEY (INSTRUMENT_ID) REFERENCES DT_INSTRUMENTS (ID),
  CONSTRAINT DT_INSP_LOT_FK FOREIGN KEY (LOT_ID) REFERENCES DT_LOTS (ID),
  CONSTRAINT DT_INSP_LIMITS_CK CHECK (LOWER_LIMIT <= UPPER_LIMIT),
  CONSTRAINT DT_INSP_DECISION_CK CHECK (ORIGINAL_DECISION IN ('ACCEPTED', 'REJECTED'))
);

CREATE INDEX DT_INSP_TRACE_IX ON DT_INSPECTIONS (INSTRUMENT_ID, FUNCTION_CODE, MEASURED_AT);

CREATE TABLE DT_SHIPMENTS (
  ID VARCHAR(32) NOT NULL PRIMARY KEY,
  LOT_ID VARCHAR(32) NOT NULL,
  CUSTOMER_NAME VARCHAR(120) NOT NULL,
  SHIPPED_QUANTITY INTEGER NOT NULL,
  SHIPPED_AT TIMESTAMP NOT NULL,
  CONSTRAINT DT_SHIP_LOT_FK FOREIGN KEY (LOT_ID) REFERENCES DT_LOTS (ID),
  CONSTRAINT DT_SHIP_QTY_CK CHECK (SHIPPED_QUANTITY > 0)
);

CREATE INDEX DT_SHIP_LOT_IX ON DT_SHIPMENTS (LOT_ID);

CREATE TABLE DT_CASES (
  ID VARCHAR(36) NOT NULL PRIMARY KEY,
  CLIENT_SUBMISSION_ID VARCHAR(64) NOT NULL,
  NOTICE_TEXT CLOB(1M) NOT NULL,
  EXTRACTED_JSON CLOB(1M) NOT NULL,
  INSTRUMENT_ID VARCHAR(32) NOT NULL,
  FUNCTION_CODE VARCHAR(40) NOT NULL,
  REVIEW_START TIMESTAMP NOT NULL,
  REVIEW_END TIMESTAMP NOT NULL,
  ASSUMPTION_BOUND DECIMAL(12,4),
  SCOPE_JSON CLOB(1M) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT DT_CASES_SUB_UQ UNIQUE (CLIENT_SUBMISSION_ID),
  CONSTRAINT DT_CASES_INSTR_FK FOREIGN KEY (INSTRUMENT_ID) REFERENCES DT_INSTRUMENTS (ID),
  CONSTRAINT DT_CASES_WINDOW_CK CHECK (REVIEW_END >= REVIEW_START),
  CONSTRAINT DT_CASES_BOUND_CK CHECK (ASSUMPTION_BOUND IS NULL OR ASSUMPTION_BOUND >= 0)
);

CREATE TABLE DT_FINDINGS (
  CASE_ID VARCHAR(36) NOT NULL,
  INSPECTION_ID VARCHAR(32) NOT NULL,
  CLASSIFICATION VARCHAR(24) NOT NULL,
  REASON VARCHAR(400) NOT NULL,
  EVIDENCE_SNAPSHOT CLOB(1M) NOT NULL,
  CONSTRAINT DT_FINDINGS_PK PRIMARY KEY (CASE_ID, INSPECTION_ID),
  CONSTRAINT DT_FIND_CASE_FK FOREIGN KEY (CASE_ID) REFERENCES DT_CASES (ID),
  CONSTRAINT DT_FIND_INSP_FK FOREIGN KEY (INSPECTION_ID) REFERENCES DT_INSPECTIONS (ID),
  CONSTRAINT DT_FIND_CLASS_CK CHECK (CLASSIFICATION IN ('REVIEW_SCOPE', 'OUTSIDE_SCOPE', 'INSUFFICIENT_DATA'))
);

CREATE INDEX DT_FIND_CASE_IX ON DT_FINDINGS (CASE_ID);

CREATE TABLE DT_AUDIT (
  ID VARCHAR(36) NOT NULL PRIMARY KEY,
  CASE_ID VARCHAR(36) NOT NULL,
  EVENT_TYPE VARCHAR(40) NOT NULL,
  DETAILS CLOB(1M) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT DT_AUDIT_CASE_FK FOREIGN KEY (CASE_ID) REFERENCES DT_CASES (ID)
);

-- Manager review outcomes per open finding (append-only history; latest event = current status).
CREATE TABLE DT_REVIEW_EVENTS (
  ID VARCHAR(36) NOT NULL PRIMARY KEY,
  CASE_ID VARCHAR(36) NOT NULL,
  INSPECTION_ID VARCHAR(32) NOT NULL,
  DISPOSITION VARCHAR(32) NOT NULL,
  REMEASURED_VALUE DECIMAL(12,4),
  NOTE VARCHAR(500) NOT NULL,
  REVIEWER VARCHAR(80) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT DT_REV_FINDING_FK FOREIGN KEY (CASE_ID, INSPECTION_ID) REFERENCES DT_FINDINGS (CASE_ID, INSPECTION_ID),
  CONSTRAINT DT_REV_DISP_CK CHECK (DISPOSITION IN ('REMEASURED_CONFORMS', 'REMEASURED_NONCONFORMING',
                                                  'NOT_AVAILABLE_FOR_REMEASURE', 'REVIEWED_NO_FURTHER_ACTION')),
  CONSTRAINT DT_REV_VALUE_CK CHECK (
    (DISPOSITION IN ('REMEASURED_CONFORMS', 'REMEASURED_NONCONFORMING') AND REMEASURED_VALUE IS NOT NULL)
    OR (DISPOSITION NOT IN ('REMEASURED_CONFORMS', 'REMEASURED_NONCONFORMING') AND REMEASURED_VALUE IS NULL))
);

CREATE INDEX DT_REV_CASE_IX ON DT_REVIEW_EVENTS (CASE_ID, INSPECTION_ID, CREATED_AT);

-- Db2-side aggregate: shipped quantity per lot (LEFT JOIN keeps unshipped lots).
-- Used to cross-check the application's distinct-lot totals inside Db2.
CREATE VIEW DT_LOT_EXPOSURE_V AS
  SELECT l.ID AS LOT_ID, l.PRODUCED_QUANTITY,
         COALESCE(SUM(s.SHIPPED_QUANTITY), 0) AS SHIPPED_QUANTITY,
         COUNT(s.ID) AS SHIPMENT_COUNT
  FROM DT_LOTS l LEFT JOIN DT_SHIPMENTS s ON s.LOT_ID = l.ID
  GROUP BY l.ID, l.PRODUCED_QUANTITY;

-- Append-only investigation record: Db2 itself rejects UPDATE/DELETE of saved
-- cases, findings and audit events, for every user including the app.
CREATE TRIGGER DT_CASES_NO_UPD NO CASCADE BEFORE UPDATE ON DT_CASES
  FOR EACH ROW SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'DT_CASES is append-only';

CREATE TRIGGER DT_CASES_NO_DEL NO CASCADE BEFORE DELETE ON DT_CASES
  FOR EACH ROW SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'DT_CASES is append-only';

CREATE TRIGGER DT_FIND_NO_UPD NO CASCADE BEFORE UPDATE ON DT_FINDINGS
  FOR EACH ROW SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'DT_FINDINGS is append-only';

CREATE TRIGGER DT_FIND_NO_DEL NO CASCADE BEFORE DELETE ON DT_FINDINGS
  FOR EACH ROW SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'DT_FINDINGS is append-only';

CREATE TRIGGER DT_AUDIT_NO_UPD NO CASCADE BEFORE UPDATE ON DT_AUDIT
  FOR EACH ROW SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'DT_AUDIT is append-only';

CREATE TRIGGER DT_AUDIT_NO_DEL NO CASCADE BEFORE DELETE ON DT_AUDIT
  FOR EACH ROW SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'DT_AUDIT is append-only';

CREATE TRIGGER DT_REV_NO_UPD NO CASCADE BEFORE UPDATE ON DT_REVIEW_EVENTS
  FOR EACH ROW SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'DT_REVIEW_EVENTS is append-only';

CREATE TRIGGER DT_REV_NO_DEL NO CASCADE BEFORE DELETE ON DT_REVIEW_EVENTS
  FOR EACH ROW SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'DT_REVIEW_EVENTS is append-only';
