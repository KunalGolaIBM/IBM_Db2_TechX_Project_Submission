-- IBM Db2 schema for the single-user TechX demo.
-- ${SCHEMA} is replaced only after strict identifier validation by init_db.py.

CREATE TABLE ${SCHEMA}.CHESS_GAMES (
    GAME_ID CHAR(36) NOT NULL,
    PGN CLOB(2M) NOT NULL,
    RESULT VARCHAR(7) NOT NULL,
    TERMINATION VARCHAR(32) NOT NULL,
    PLAYER_COLOR VARCHAR(7) NOT NULL,
    PLAYER_OUTCOME VARCHAR(7) NOT NULL,
    OPENING_CODE VARCHAR(16),
    OPENING_NAME VARCHAR(255) NOT NULL,
    PLAYED_AT TIMESTAMP NOT NULL,
    OPPONENT_ELO INTEGER,
    TIME_CONTROL VARCHAR(32) NOT NULL,
    SOURCE VARCHAR(32) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_CHESS_GAMES PRIMARY KEY (GAME_ID),
    CONSTRAINT CK_CHESS_GAMES_RESULT CHECK (RESULT IN ('1-0', '0-1', '1/2-1/2', '*')),
    CONSTRAINT CK_CHESS_GAMES_COLOR CHECK (PLAYER_COLOR IN ('white', 'black', 'unknown')),
    CONSTRAINT CK_CHESS_GAMES_OUTCOME CHECK (PLAYER_OUTCOME IN ('win', 'loss', 'draw', 'unknown')),
    CONSTRAINT CK_CHESS_GAMES_ELO CHECK (OPPONENT_ELO IS NULL OR OPPONENT_ELO BETWEEN 100 AND 4000)
);

CREATE TABLE ${SCHEMA}.CHESS_MOVES (
    GAME_ID CHAR(36) NOT NULL,
    PLY_NUMBER INTEGER NOT NULL,
    SAN VARCHAR(32) NOT NULL,
    UCI VARCHAR(8) NOT NULL,
    FEN_AFTER VARCHAR(255) NOT NULL,
    CONSTRAINT PK_CHESS_MOVES PRIMARY KEY (GAME_ID, PLY_NUMBER),
    CONSTRAINT FK_CHESS_MOVES_GAME FOREIGN KEY (GAME_ID)
        REFERENCES ${SCHEMA}.CHESS_GAMES (GAME_ID) ON DELETE CASCADE,
    CONSTRAINT CK_CHESS_MOVES_PLY CHECK (PLY_NUMBER > 0)
);

CREATE TABLE ${SCHEMA}.CHESS_GAME_ANALYSIS (
    GAME_ID CHAR(36) NOT NULL,
    PLY_NUMBER INTEGER NOT NULL,
    FEN VARCHAR(255) NOT NULL,
    CP INTEGER,
    MATE INTEGER,
    WIN_PROBABILITY DECIMAL(5, 2),
    CLASSIFICATION VARCHAR(32),
    ENGINE VARCHAR(64) NOT NULL,
    DEPTH SMALLINT,
    STATUS VARCHAR(16) NOT NULL,
    CONSTRAINT PK_CHESS_GAME_ANALYSIS PRIMARY KEY (GAME_ID, PLY_NUMBER),
    CONSTRAINT FK_CHESS_ANALYSIS_GAME FOREIGN KEY (GAME_ID)
        REFERENCES ${SCHEMA}.CHESS_GAMES (GAME_ID) ON DELETE CASCADE,
    CONSTRAINT CK_CHESS_ANALYSIS_PLY CHECK (PLY_NUMBER >= 0),
    CONSTRAINT CK_CHESS_ANALYSIS_WIN CHECK (WIN_PROBABILITY IS NULL OR WIN_PROBABILITY BETWEEN 0 AND 100),
    CONSTRAINT CK_CHESS_ANALYSIS_STATUS CHECK (STATUS IN ('evaluated', 'timeout', 'error'))
);

CREATE TABLE ${SCHEMA}.CHESS_OPENING_STATISTICS (
    OPENING_KEY VARCHAR(300) NOT NULL,
    OPENING_CODE VARCHAR(16),
    OPENING_NAME VARCHAR(255) NOT NULL,
    TOTAL_GAMES INTEGER NOT NULL,
    WINS INTEGER NOT NULL,
    LOSSES INTEGER NOT NULL,
    DRAWS INTEGER NOT NULL,
    UNKNOWN_GAMES INTEGER NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_CHESS_OPENING_STATS PRIMARY KEY (OPENING_KEY),
    CONSTRAINT CK_CHESS_OPENING_TOTAL CHECK (TOTAL_GAMES >= 0),
    CONSTRAINT CK_CHESS_OPENING_WINS CHECK (WINS >= 0),
    CONSTRAINT CK_CHESS_OPENING_LOSSES CHECK (LOSSES >= 0),
    CONSTRAINT CK_CHESS_OPENING_DRAWS CHECK (DRAWS >= 0),
    CONSTRAINT CK_CHESS_OPENING_UNKNOWN CHECK (UNKNOWN_GAMES >= 0),
    CONSTRAINT CK_CHESS_OPENING_SUM CHECK (TOTAL_GAMES = WINS + LOSSES + DRAWS + UNKNOWN_GAMES)
);
