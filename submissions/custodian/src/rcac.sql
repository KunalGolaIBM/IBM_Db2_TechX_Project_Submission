-- Row and Column Access Control (RCAC). Applied by seed.py AFTER the data is loaded.
-- Enforced by the Db2 engine for every access path (the agent, a BI tool, the CLP...).
-- Even DATAACCESS / DBADM does not bypass it. Only SECADM can change it.

-- Rows: admins see everyone; support agents see only RETAIL customers (no private banking).
CREATE PERMISSION BANK.CUSTOMERS_ROWS ON BANK.CUSTOMERS
  FOR ROWS WHERE VERIFY_ROLE_FOR_USER(SESSION_USER, 'ADMINS') = 1
              OR (VERIFY_ROLE_FOR_USER(SESSION_USER, 'SUPPORT') = 1 AND SEGMENT = 'RETAIL')
  ENFORCED FOR ALL ACCESS ENABLE;

-- Columns: card number, PAN and e-mail are masked for anyone who is not an admin.
CREATE MASK BANK.CUSTOMERS_CARD_MASK ON BANK.CUSTOMERS FOR COLUMN CARD_NUMBER RETURN
  CASE WHEN VERIFY_ROLE_FOR_USER(SESSION_USER, 'ADMINS') = 1 THEN CARD_NUMBER
       ELSE CAST('XXXX-XXXX-XXXX-' || SUBSTR(CARD_NUMBER, 16, 4) AS CHAR(19)) END
  ENABLE;

CREATE MASK BANK.CUSTOMERS_PAN_MASK ON BANK.CUSTOMERS FOR COLUMN PAN RETURN
  CASE WHEN VERIFY_ROLE_FOR_USER(SESSION_USER, 'ADMINS') = 1 THEN PAN
       ELSE CAST('XXXXX' || SUBSTR(PAN, 6, 4) || 'X' AS CHAR(10)) END
  ENABLE;

CREATE MASK BANK.CUSTOMERS_EMAIL_MASK ON BANK.CUSTOMERS FOR COLUMN EMAIL RETURN
  CASE WHEN VERIFY_ROLE_FOR_USER(SESSION_USER, 'ADMINS') = 1 THEN EMAIL
       ELSE CAST(SUBSTR(EMAIL, 1, 1) || '***' || SUBSTR(EMAIL, LOCATE('@', EMAIL)) AS VARCHAR(120)) END
  ENABLE;

ALTER TABLE BANK.CUSTOMERS ACTIVATE ROW ACCESS CONTROL ACTIVATE COLUMN ACCESS CONTROL;
