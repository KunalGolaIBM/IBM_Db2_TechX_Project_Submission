-- Create Schema
CREATE SCHEMA ENTERPRISE;

-- 1. CUSTOMER_MST: Master record of commercial & retail clients
CREATE TABLE ENTERPRISE.CUSTOMER_MST (
    CUST_ID         BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 10001 INCREMENT BY 1),
    CUST_NAME       VARCHAR(120) NOT NULL,
    CUST_TYPE_CD    CHAR(3) NOT NULL DEFAULT 'RET',
    CUST_EMAIL      VARCHAR(255) NOT NULL,
    TAX_ID          VARCHAR(32),
    STATUS_CD       CHAR(2) NOT NULL DEFAULT 'AC',
    CREATED_TS      TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_CUSTOMER_MST PRIMARY KEY (CUST_ID),
    CONSTRAINT CK_CUST_STATUS CHECK (STATUS_CD IN ('AC', 'SU', 'CL'))
);

CREATE UNIQUE INDEX ENTERPRISE.IX_CUST_EMAIL ON ENTERPRISE.CUSTOMER_MST (CUST_EMAIL);

COMMENT ON TABLE ENTERPRISE.CUSTOMER_MST IS 'Master record of registered commercial and retail clients.';
COMMENT ON COLUMN ENTERPRISE.CUSTOMER_MST.CUST_ID IS 'Surrogate primary key for customer';
COMMENT ON COLUMN ENTERPRISE.CUSTOMER_MST.CUST_TYPE_CD IS 'Customer classification: B2B or RET';

-- 2. PRODUCT_MST: Merchandise catalog & SKU specifications
CREATE TABLE ENTERPRISE.PRODUCT_MST (
    PROD_ID         BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 5001 INCREMENT BY 1),
    SKU_CODE        VARCHAR(32) NOT NULL,
    PROD_NAME       VARCHAR(160) NOT NULL,
    CATEGORY_ID     INTEGER,
    BASE_PRICE      DECIMAL(10, 2) NOT NULL,
    WEIGHT_KG       DECIMAL(7, 3),
    IS_ACTIVE       CHAR(1) NOT NULL DEFAULT 'Y',
    CONSTRAINT PK_PRODUCT_MST PRIMARY KEY (PROD_ID),
    CONSTRAINT CK_PROD_PRICE_POS CHECK (BASE_PRICE >= 0.00)
);

CREATE UNIQUE INDEX ENTERPRISE.IX_PROD_SKU ON ENTERPRISE.PRODUCT_MST (SKU_CODE);

COMMENT ON TABLE ENTERPRISE.PRODUCT_MST IS 'Global catalog of salable merchandise and SKU specifications.';
COMMENT ON COLUMN ENTERPRISE.PRODUCT_MST.CATEGORY_ID IS 'Legacy category classification number (undocumented master)';

-- 3. SUPPLIER_MST: Wholesale supplier registry
CREATE TABLE ENTERPRISE.SUPPLIER_MST (
    SUPP_ID         BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 101 INCREMENT BY 1),
    SUPP_NAME       VARCHAR(120) NOT NULL,
    CONTACT_EMAIL   VARCHAR(255) NOT NULL,
    COUNTRY_CD      CHAR(3) NOT NULL,
    RATING_SCORE    DECIMAL(3, 2),
    ACTIVE_IND      CHAR(1) NOT NULL DEFAULT 'Y',
    CONSTRAINT PK_SUPPLIER_MST PRIMARY KEY (SUPP_ID)
);

COMMENT ON TABLE ENTERPRISE.SUPPLIER_MST IS 'Vendor and wholesale supplier registry.';

-- 4. WAREHOUSE_MST: Regional distribution hubs
CREATE TABLE ENTERPRISE.WAREHOUSE_MST (
    WH_ID           INTEGER NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    WH_CODE         VARCHAR(16) NOT NULL,
    WH_NAME         VARCHAR(80) NOT NULL,
    REGION_CD       VARCHAR(10) NOT NULL,
    MAX_CAPACITY    INTEGER NOT NULL,
    OPERATIONAL_STS VARCHAR(16) NOT NULL DEFAULT 'ONLINE',
    CONSTRAINT PK_WAREHOUSE_MST PRIMARY KEY (WH_ID)
);

CREATE UNIQUE INDEX ENTERPRISE.IX_WH_CODE ON ENTERPRISE.WAREHOUSE_MST (WH_CODE);

COMMENT ON TABLE ENTERPRISE.WAREHOUSE_MST IS 'Physical distribution facilities and regional storage hubs.';

-- 5. ORD_HDR: Purchase order transactions header
CREATE TABLE ENTERPRISE.ORD_HDR (
    ORDER_ID        BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 90001 INCREMENT BY 1),
    CUST_ID         BIGINT NOT NULL,
    ORDER_DT        DATE NOT NULL,
    ORDER_STATUS_CD CHAR(4) NOT NULL DEFAULT 'NEW',
    TOTAL_AMT       DECIMAL(12, 2) NOT NULL,
    CURRENCY_CD     CHAR(3) NOT NULL DEFAULT 'USD',
    CHANNEL_CD      VARCHAR(12) NOT NULL DEFAULT 'WEB',
    CREATED_TS      TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_ORD_HDR PRIMARY KEY (ORDER_ID),
    CONSTRAINT FK_ORD_HDR_CUST FOREIGN KEY (CUST_ID)
        REFERENCES ENTERPRISE.CUSTOMER_MST (CUST_ID) ON DELETE RESTRICT,
    CONSTRAINT CK_ORD_TOTAL_NONNEG CHECK (TOTAL_AMT >= 0.00)
);

CREATE INDEX ENTERPRISE.IX_ORD_CUST ON ENTERPRISE.ORD_HDR (CUST_ID);
CREATE INDEX ENTERPRISE.IX_ORD_STATUS ON ENTERPRISE.ORD_HDR (ORDER_STATUS_CD, ORDER_DT);

COMMENT ON TABLE ENTERPRISE.ORD_HDR IS 'Order header records containing transactional totals and customer references.';

-- 6. ORD_LINE: Itemized purchase order line items
CREATE TABLE ENTERPRISE.ORD_LINE (
    LINE_ID         BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ORDER_ID        BIGINT NOT NULL,
    PROD_ID         BIGINT NOT NULL,
    LINE_NUM        SMALLINT NOT NULL,
    ORDER_QTY       INTEGER NOT NULL,
    UNIT_PRICE      DECIMAL(10, 2) NOT NULL,
    DISCOUNT_AMT    DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    NET_AMT         DECIMAL(10, 2) NOT NULL,
    CONSTRAINT PK_ORD_LINE PRIMARY KEY (LINE_ID),
    CONSTRAINT FK_ORD_LINE_HDR FOREIGN KEY (ORDER_ID)
        REFERENCES ENTERPRISE.ORD_HDR (ORDER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ORD_LINE_PROD FOREIGN KEY (PROD_ID)
        REFERENCES ENTERPRISE.PRODUCT_MST (PROD_ID) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX ENTERPRISE.IX_LINE_ORD_SEQ ON ENTERPRISE.ORD_LINE (ORDER_ID, LINE_NUM);
CREATE INDEX ENTERPRISE.IX_LINE_PROD ON ENTERPRISE.ORD_LINE (PROD_ID);

COMMENT ON TABLE ENTERPRISE.ORD_LINE IS 'Itemized purchase order line entries detailing SKUs and quantities.';

-- 7. INVENTORY: Physical on-hand stock balances
CREATE TABLE ENTERPRISE.INVENTORY (
    INV_ID          BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    PROD_ID         BIGINT NOT NULL,
    WH_ID           INTEGER NOT NULL,
    ON_HAND_QTY     INTEGER NOT NULL DEFAULT 0,
    REORDER_POINT   INTEGER NOT NULL DEFAULT 10,
    LAST_COUNT_DT   DATE,
    CONSTRAINT PK_INVENTORY PRIMARY KEY (INV_ID),
    CONSTRAINT FK_INV_PROD FOREIGN KEY (PROD_ID)
        REFERENCES ENTERPRISE.PRODUCT_MST (PROD_ID),
    CONSTRAINT FK_INV_WH FOREIGN KEY (WH_ID)
        REFERENCES ENTERPRISE.WAREHOUSE_MST (WH_ID)
);

CREATE UNIQUE INDEX ENTERPRISE.IX_INV_PROD_WH ON ENTERPRISE.INVENTORY (PROD_ID, WH_ID);

COMMENT ON TABLE ENTERPRISE.INVENTORY IS 'Current physical on-hand stock balances across warehouse locations.';

-- 8. INVENTORY_RESERVATION: Stock holds allocated to pending orders
CREATE TABLE ENTERPRISE.INVENTORY_RESERVATION (
    RESV_ID         BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ORDER_ID        BIGINT NOT NULL,
    PROD_ID         BIGINT NOT NULL,
    WH_ID           INTEGER NOT NULL,
    RESV_QTY        INTEGER NOT NULL,
    RESV_STATUS     VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    EXPIRE_TS       TIMESTAMP NOT NULL,
    CONSTRAINT PK_INV_RESV PRIMARY KEY (RESV_ID),
    CONSTRAINT FK_RESV_ORD FOREIGN KEY (ORDER_ID)
        REFERENCES ENTERPRISE.ORD_HDR (ORDER_ID),
    CONSTRAINT FK_RESV_PROD FOREIGN KEY (PROD_ID)
        REFERENCES ENTERPRISE.PRODUCT_MST (PROD_ID),
    CONSTRAINT FK_RESV_WH FOREIGN KEY (WH_ID)
        REFERENCES ENTERPRISE.WAREHOUSE_MST (WH_ID)
);

CREATE INDEX ENTERPRISE.IX_RESV_ORD ON ENTERPRISE.INVENTORY_RESERVATION (ORDER_ID);

COMMENT ON TABLE ENTERPRISE.INVENTORY_RESERVATION IS 'Temporary stock holds allocated to unfulfilled orders to prevent double-selling.';

-- 9. PAYMENT_METHOD: Customer wallet instruments
CREATE TABLE ENTERPRISE.PAYMENT_METHOD (
    PM_ID           BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    CUST_ID         BIGINT NOT NULL,
    PM_TYPE_CD      VARCHAR(16) NOT NULL,
    TOKENIZED_ACCT  VARCHAR(64) NOT NULL,
    EXPIRY_MON_YR   CHAR(7),
    IS_DEFAULT      CHAR(1) NOT NULL DEFAULT 'N',
    CONSTRAINT PK_PAYMENT_METHOD PRIMARY KEY (PM_ID),
    CONSTRAINT FK_PM_CUST FOREIGN KEY (CUST_ID)
        REFERENCES ENTERPRISE.CUSTOMER_MST (CUST_ID)
);

CREATE INDEX ENTERPRISE.IX_PM_CUST ON ENTERPRISE.PAYMENT_METHOD (CUST_ID);

COMMENT ON TABLE ENTERPRISE.PAYMENT_METHOD IS 'Stored customer billing instrument tokens and wallet identifiers.';

-- 10. PAYMENT_TXN: Financial settlement transactions
CREATE TABLE ENTERPRISE.PAYMENT_TXN (
    TXN_ID          BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 70001 INCREMENT BY 1),
    ORDER_ID        BIGINT NOT NULL,
    PM_ID           BIGINT NOT NULL,
    TXN_AMT         DECIMAL(12, 2) NOT NULL,
    TXN_STATUS_CD   CHAR(4) NOT NULL,
    GATEWAY_REF_NO  VARCHAR(64) NOT NULL,
    AUTH_CODE       VARCHAR(32),
    TXN_TS          TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_PAYMENT_TXN PRIMARY KEY (TXN_ID),
    CONSTRAINT FK_TXN_ORD FOREIGN KEY (ORDER_ID)
        REFERENCES ENTERPRISE.ORD_HDR (ORDER_ID),
    CONSTRAINT FK_TXN_PM FOREIGN KEY (PM_ID)
        REFERENCES ENTERPRISE.PAYMENT_METHOD (PM_ID)
);

CREATE INDEX ENTERPRISE.IX_TXN_ORD ON ENTERPRISE.PAYMENT_TXN (ORDER_ID);

COMMENT ON TABLE ENTERPRISE.PAYMENT_TXN IS 'Settled and attempted gateway authorization transactions.';

-- 11. SHIPMENT_HDR: Carrier dispatch manifests
CREATE TABLE ENTERPRISE.SHIPMENT_HDR (
    SHIPMENT_ID     BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 30001 INCREMENT BY 1),
    ORDER_ID        BIGINT NOT NULL,
    WH_ID           INTEGER NOT NULL,
    CARRIER_CD      VARCHAR(16) NOT NULL,
    TRACKING_NO     VARCHAR(64) NOT NULL,
    SHIP_DT         DATE NOT NULL,
    DELIVERY_STS    VARCHAR(16) NOT NULL DEFAULT 'IN_TRANSIT',
    CONSTRAINT PK_SHIPMENT_HDR PRIMARY KEY (SHIPMENT_ID),
    CONSTRAINT FK_SHIP_ORD FOREIGN KEY (ORDER_ID)
        REFERENCES ENTERPRISE.ORD_HDR (ORDER_ID),
    CONSTRAINT FK_SHIP_WH FOREIGN KEY (WH_ID)
        REFERENCES ENTERPRISE.WAREHOUSE_MST (WH_ID)
);

CREATE UNIQUE INDEX ENTERPRISE.IX_SHIP_TRACK ON ENTERPRISE.SHIPMENT_HDR (TRACKING_NO);

COMMENT ON TABLE ENTERPRISE.SHIPMENT_HDR IS 'Carrier dispatch manifests and consignment tracking records.';

-- 12. SHIPMENT_ITEM: Packed box line items
CREATE TABLE ENTERPRISE.SHIPMENT_ITEM (
    SHIP_ITEM_ID    BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    SHIPMENT_ID     BIGINT NOT NULL,
    LINE_ID         BIGINT NOT NULL,
    PACKED_QTY      INTEGER NOT NULL,
    INSPECTION_STS  VARCHAR(16) NOT NULL DEFAULT 'PASSED',
    CONSTRAINT PK_SHIPMENT_ITEM PRIMARY KEY (SHIP_ITEM_ID),
    CONSTRAINT FK_ITEM_SHIP FOREIGN KEY (SHIPMENT_ID)
        REFERENCES ENTERPRISE.SHIPMENT_HDR (SHIPMENT_ID),
    CONSTRAINT FK_ITEM_LINE FOREIGN KEY (LINE_ID)
        REFERENCES ENTERPRISE.ORD_LINE (LINE_ID)
);

CREATE UNIQUE INDEX ENTERPRISE.IX_ITEM_SHIP_LINE ON ENTERPRISE.SHIPMENT_ITEM (SHIPMENT_ID, LINE_ID);

COMMENT ON TABLE ENTERPRISE.SHIPMENT_ITEM IS 'Line items physically packed into an outbound consignment carton.';

-- 13. RETURN_HDR: Merchandise authorization returns (Intentionally Ambiguous for Inference Discovery!)
-- NOTE: Intentionally missing foreign key constraint on ORDER_ID!
-- NOTE: Uses CUST_REF_NO instead of CUST_ID to demonstrate inferred relationship discovery!
CREATE TABLE ENTERPRISE.RETURN_HDR (
    RET_ID          BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 8001 INCREMENT BY 1),
    ORDER_ID        BIGINT NOT NULL,
    CUST_REF_NO     BIGINT NOT NULL,
    RET_REASON_CD   VARCHAR(16) NOT NULL,
    RET_STATUS_CD   CHAR(4) NOT NULL DEFAULT 'INIT',
    REFUND_AMT      DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    REQUEST_DT      DATE NOT NULL,
    CONSTRAINT PK_RETURN_HDR PRIMARY KEY (RET_ID)
);

CREATE INDEX ENTERPRISE.IX_RET_ORD_ID ON ENTERPRISE.RETURN_HDR (ORDER_ID);

COMMENT ON TABLE ENTERPRISE.RETURN_HDR IS 'Customer merchandise authorization returns and RMA restitution filings.';
COMMENT ON COLUMN ENTERPRISE.RETURN_HDR.ORDER_ID IS 'Legacy order reference number without explicit foreign key constraint';
COMMENT ON COLUMN ENTERPRISE.RETURN_HDR.CUST_REF_NO IS 'Customer account reference number (undocumented link to CUST_ID)';

-- 14. V_ACTIVE_ORDERS: Reporting View
CREATE VIEW ENTERPRISE.V_ACTIVE_ORDERS AS
SELECT
    O.ORDER_ID,
    C.CUST_NAME,
    O.ORDER_DT,
    O.ORDER_STATUS_CD,
    O.TOTAL_AMT,
    T.TXN_STATUS_CD
FROM ENTERPRISE.ORD_HDR O
JOIN ENTERPRISE.CUSTOMER_MST C ON O.CUST_ID = C.CUST_ID
LEFT JOIN ENTERPRISE.PAYMENT_TXN T ON O.ORDER_ID = T.ORDER_ID
WHERE O.ORDER_STATUS_CD IN ('NEW', 'PAID', 'PROC');

-- 15. V_INVENTORY_VALUATION: Reporting View
CREATE VIEW ENTERPRISE.V_INVENTORY_VALUATION AS
SELECT
    W.WH_CODE,
    P.SKU_CODE,
    P.PROD_NAME,
    I.ON_HAND_QTY,
    P.BASE_PRICE,
    (I.ON_HAND_QTY * P.BASE_PRICE) AS TOTAL_ASSET_VALUE
FROM ENTERPRISE.INVENTORY I
JOIN ENTERPRISE.PRODUCT_MST P ON I.PROD_ID = P.PROD_ID
JOIN ENTERPRISE.WAREHOUSE_MST W ON I.WH_ID = W.WH_ID;
