"""
IBM Db2 LUW System Catalog Queries.
All queries target the standard IBM Db2 SYSCAT views:
- SYSCAT.SCHEMATA
- SYSCAT.TABLES
- SYSCAT.COLUMNS
- SYSCAT.TABCONST
- SYSCAT.KEYCOLUSE
- SYSCAT.REFERENCES
- SYSCAT.INDEXES
- SYSCAT.VIEWS
- SYSCAT.TABDEP
"""

# Retrieve available non-system schemas
SQL_LIST_SCHEMAS = """
SELECT RTRIM(SCHEMANAME) AS SCHEMANAME
FROM SYSCAT.SCHEMATA
WHERE SCHEMANAME NOT LIKE 'SYS%'
  AND SCHEMANAME NOT IN ('NULLID', 'SQLJ')
ORDER BY SCHEMANAME
"""

# Retrieve tables and views in a specific schema
SQL_GET_TABLES_AND_VIEWS = """
SELECT
    RTRIM(TABNAME) AS TABNAME,
    RTRIM(TABSCHEMA) AS TABSCHEMA,
    RTRIM(TYPE) AS TYPE,
    COALESCE(REMARKS, '') AS REMARKS,
    CARD,
    COLCOUNT
FROM SYSCAT.TABLES
WHERE TABSCHEMA = ?
  AND TYPE IN ('T', 'V')
ORDER BY TABNAME
"""

# Retrieve all columns for a specific table or across a schema
SQL_GET_COLUMNS_BY_SCHEMA = """
SELECT
    RTRIM(TABNAME) AS TABNAME,
    RTRIM(COLNAME) AS COLNAME,
    RTRIM(TYPENAME) AS TYPENAME,
    LENGTH,
    SCALE,
    RTRIM(NULLS) AS NULLS,
    DEFAULT AS DEFAULT_VAL,
    COLNO,
    COALESCE(REMARKS, '') AS REMARKS,
    KEYSEQ
FROM SYSCAT.COLUMNS
WHERE TABSCHEMA = ?
ORDER BY TABNAME, COLNO
"""

# Retrieve primary keys via SYSCAT.TABCONST & SYSCAT.KEYCOLUSE
SQL_GET_PRIMARY_KEYS = """
SELECT
    RTRIM(TC.TABNAME) AS TABNAME,
    RTRIM(TC.CONSTNAME) AS CONSTNAME,
    RTRIM(KCU.COLNAME) AS COLNAME,
    KCU.COLSEQ
FROM SYSCAT.TABCONST TC
JOIN SYSCAT.KEYCOLUSE KCU
  ON TC.TABSCHEMA = KCU.TABSCHEMA
 AND TC.CONSTNAME = KCU.CONSTNAME
WHERE TC.TABSCHEMA = ?
  AND TC.TYPE = 'P'
ORDER BY TC.TABNAME, KCU.COLSEQ
"""

# Retrieve declared foreign keys via SYSCAT.REFERENCES & SYSCAT.KEYCOLUSE
SQL_GET_FOREIGN_KEYS = """
SELECT
    RTRIM(R.CONSTNAME) AS CONSTNAME,
    RTRIM(R.TABNAME) AS SOURCE_TABLE,
    RTRIM(R.REFTABNAME) AS TARGET_TABLE,
    RTRIM(R.DELETERULE) AS DELETE_RULE,
    RTRIM(R.UPDATERULE) AS UPDATE_RULE,
    RTRIM(KCU.COLNAME) AS SOURCE_COL,
    KCU.COLSEQ
FROM SYSCAT.REFERENCES R
JOIN SYSCAT.KEYCOLUSE KCU
  ON R.TABSCHEMA = KCU.TABSCHEMA
 AND R.CONSTNAME = KCU.CONSTNAME
WHERE R.TABSCHEMA = ?
ORDER BY R.TABNAME, R.CONSTNAME, KCU.COLSEQ
"""

# Retrieve target primary key columns for referenced foreign keys
SQL_GET_REFERENCED_PK_COLUMNS = """
SELECT
    RTRIM(R.CONSTNAME) AS CONSTNAME,
    RTRIM(KCU.COLNAME) AS TARGET_COL,
    KCU.COLSEQ
FROM SYSCAT.REFERENCES R
JOIN SYSCAT.KEYCOLUSE KCU
  ON R.REFTABSCHEMA = KCU.TABSCHEMA
 AND R.REFKEYNAME = KCU.CONSTNAME
WHERE R.TABSCHEMA = ?
ORDER BY R.CONSTNAME, KCU.COLSEQ
"""

# Retrieve table indexes
SQL_GET_INDEXES = """
SELECT
    RTRIM(INDNAME) AS INDNAME,
    RTRIM(TABNAME) AS TABNAME,
    RTRIM(UNIQUERULE) AS UNIQUERULE,
    RTRIM(COLNAMES) AS COLNAMES
FROM SYSCAT.INDEXES
WHERE TABSCHEMA = ?
ORDER BY TABNAME, INDNAME
"""

# Retrieve table constraints (Check, Unique)
SQL_GET_CONSTRAINTS = """
SELECT
    RTRIM(CONSTNAME) AS CONSTNAME,
    RTRIM(TABNAME) AS TABNAME,
    RTRIM(TYPE) AS TYPE
FROM SYSCAT.TABCONST
WHERE TABSCHEMA = ?
  AND TYPE IN ('U', 'K')
ORDER BY TABNAME, CONSTNAME
"""

# Retrieve View Definitions
SQL_GET_VIEW_DEFINITIONS = """
SELECT
    RTRIM(VIEWNAME) AS VIEWNAME,
    TEXT AS VIEW_DEFINITION
FROM SYSCAT.VIEWS
WHERE VIEWSCHEMA = ?
ORDER BY VIEWNAME
"""

# Retrieve View/Table Dependencies
SQL_GET_DEPENDENCIES = """
SELECT
    RTRIM(TABNAME) AS OBJECT_NAME,
    RTRIM(BNAME) AS DEPENDS_ON_OBJECT,
    RTRIM(BTYPE) AS DEPENDS_ON_TYPE
FROM SYSCAT.TABDEP
WHERE TABSCHEMA = ?
ORDER BY TABNAME, BNAME
"""
