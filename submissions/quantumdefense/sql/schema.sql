
-- QuantumDefense IBM Db2 Database Schema

CREATE TABLE SECURITY_EVENTS (
    EVENT_ID INTEGER
        GENERATED ALWAYS AS IDENTITY
        PRIMARY KEY,
    EVENT_TYPE VARCHAR(100) NOT NULL,
    SOURCE_IP VARCHAR(45) NOT NULL,
    SEVERITY VARCHAR(20) NOT NULL,
    DESCRIPTION VARCHAR(500),
    DETECTED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE SECURITY_ALERTS (
    ALERT_ID INTEGER
        GENERATED ALWAYS AS IDENTITY
        PRIMARY KEY,
    EVENT_ID INTEGER NOT NULL,
    ALERT_MESSAGE VARCHAR(500) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    FOREIGN KEY (EVENT_ID)
        REFERENCES SECURITY_EVENTS(EVENT_ID)
);

CREATE TABLE SECURITY_AUDIT (
    AUDIT_ID INTEGER
        GENERATED ALWAYS AS IDENTITY
        PRIMARY KEY,
    ACTION_NAME VARCHAR(100) NOT NULL,
    DETAILS VARCHAR(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

-- Indexes for faster event searches

CREATE INDEX IDX_SECURITY_EVENT_TYPE
ON SECURITY_EVENTS(EVENT_TYPE);

CREATE INDEX IDX_SECURITY_SEVERITY
ON SECURITY_EVENTS(SEVERITY);

CREATE INDEX IDX_SECURITY_DETECTED_AT
ON SECURITY_EVENTS(DETECTED_AT);



-- Machine Learning Analysis Results

CREATE TABLE ML_ANALYSIS_RESULTS (
    ANALYSIS_ID INTEGER
        GENERATED ALWAYS AS IDENTITY
        PRIMARY KEY,

    EVENT_ID INTEGER NOT NULL,

    ANOMALY_DETECTED SMALLINT NOT NULL,

    ANOMALY_SCORE DOUBLE NOT NULL,

    ALGORITHM VARCHAR(100) NOT NULL,

    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,

    FOREIGN KEY (EVENT_ID)
        REFERENCES SECURITY_EVENTS(EVENT_ID)
);
