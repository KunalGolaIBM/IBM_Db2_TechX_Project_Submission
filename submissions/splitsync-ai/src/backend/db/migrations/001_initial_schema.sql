-- 1. APP_USERS
CREATE TABLE APP_USERS (
    USER_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    DISPLAY_NAME VARCHAR(255) NOT NULL,
    EMAIL VARCHAR(255) NOT NULL,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IDX_USERS_EMAIL ON APP_USERS (EMAIL);

-- 2. GROUPS
CREATE TABLE GROUPS (
    GROUP_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    NAME VARCHAR(255) NOT NULL,
    DESCRIPTION VARCHAR(2000),
    CURRENCY VARCHAR(10) NOT NULL DEFAULT 'INR',
    SPLIT_METHOD VARCHAR(20) NOT NULL DEFAULT 'EQUAL',
    ACCOUNTING_MODE VARCHAR(20) NOT NULL DEFAULT 'DIRECT',
    STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    CREATED_BY VARCHAR(36) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (CREATED_BY) REFERENCES APP_USERS (USER_ID)
);
CREATE INDEX IDX_GROUPS_CREATED_BY ON GROUPS (CREATED_BY);

-- 3. GROUP_MEMBERS
CREATE TABLE GROUP_MEMBERS (
    GROUP_MEMBER_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    GROUP_ID VARCHAR(36) NOT NULL,
    USER_ID VARCHAR(36) NOT NULL,
    ROLE VARCHAR(20) NOT NULL DEFAULT 'MEMBER',
    STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    JOINED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (GROUP_ID) REFERENCES GROUPS (GROUP_ID),
    FOREIGN KEY (USER_ID) REFERENCES APP_USERS (USER_ID)
);
CREATE UNIQUE INDEX IDX_MEMBERS_GROUP_USER ON GROUP_MEMBERS (GROUP_ID, USER_ID);
CREATE INDEX IDX_MEMBERS_USER ON GROUP_MEMBERS (USER_ID);

-- 4. PAYMENT_EVENTS
CREATE TABLE PAYMENT_EVENTS (
    PAYMENT_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    GROUP_ID VARCHAR(36) NOT NULL,
    MEMBER_ID VARCHAR(36),
    PROVIDER VARCHAR(50) NOT NULL,
    PROVIDER_TXN_ID VARCHAR(255),
    AMOUNT_MINOR BIGINT NOT NULL,
    CURRENCY VARCHAR(10) NOT NULL DEFAULT 'INR',
    STATUS VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    SOURCE VARCHAR(10) NOT NULL DEFAULT 'DEMO',
    IDEMPOTENCY_KEY VARCHAR(255) NOT NULL,
    PAID_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (GROUP_ID) REFERENCES GROUPS (GROUP_ID),
    FOREIGN KEY (MEMBER_ID) REFERENCES GROUP_MEMBERS (GROUP_MEMBER_ID)
);
CREATE UNIQUE INDEX IDX_PAYMENTS_IDEMPOTENCY ON PAYMENT_EVENTS (IDEMPOTENCY_KEY);
CREATE INDEX IDX_PAYMENTS_GROUP ON PAYMENT_EVENTS (GROUP_ID);
CREATE INDEX IDX_PAYMENTS_MEMBER ON PAYMENT_EVENTS (MEMBER_ID);

-- 5. CASH_CONTRIBUTIONS
CREATE TABLE CASH_CONTRIBUTIONS (
    CASH_CONTRIBUTION_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    GROUP_ID VARCHAR(36) NOT NULL,
    MEMBER_ID VARCHAR(36) NOT NULL,
    AMOUNT_MINOR BIGINT NOT NULL,
    DESCRIPTION VARCHAR(500),
    STATUS VARCHAR(20) NOT NULL DEFAULT 'PENDING_APPROVAL',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (GROUP_ID) REFERENCES GROUPS (GROUP_ID),
    FOREIGN KEY (MEMBER_ID) REFERENCES GROUP_MEMBERS (GROUP_MEMBER_ID)
);
CREATE INDEX IDX_CASH_GROUP ON CASH_CONTRIBUTIONS (GROUP_ID);
CREATE INDEX IDX_CASH_STATUS ON CASH_CONTRIBUTIONS (STATUS);

-- 6. EXPENSES
CREATE TABLE EXPENSES (
    EXPENSE_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    GROUP_ID VARCHAR(36) NOT NULL,
    PAID_BY_MEMBER_ID VARCHAR(36) NOT NULL,
    AMOUNT_MINOR BIGINT NOT NULL,
    DESCRIPTION VARCHAR(500) NOT NULL,
    CATEGORY VARCHAR(50) NOT NULL DEFAULT 'OTHER',
    PAYMENT_METHOD VARCHAR(20) NOT NULL DEFAULT 'DIGITAL',
    STATUS VARCHAR(20) NOT NULL DEFAULT 'VERIFIED',
    EXPENSE_DATE DATE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (GROUP_ID) REFERENCES GROUPS (GROUP_ID),
    FOREIGN KEY (PAID_BY_MEMBER_ID) REFERENCES GROUP_MEMBERS (GROUP_MEMBER_ID)
);
CREATE INDEX IDX_EXPENSES_GROUP ON EXPENSES (GROUP_ID);

-- 7. EXPENSE_SPLITS
CREATE TABLE EXPENSE_SPLITS (
    SPLIT_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    EXPENSE_ID VARCHAR(36) NOT NULL,
    MEMBER_ID VARCHAR(36) NOT NULL,
    SHARE_MINOR BIGINT NOT NULL,
    FOREIGN KEY (EXPENSE_ID) REFERENCES EXPENSES (EXPENSE_ID),
    FOREIGN KEY (MEMBER_ID) REFERENCES GROUP_MEMBERS (GROUP_MEMBER_ID)
);
CREATE INDEX IDX_SPLITS_EXPENSE ON EXPENSE_SPLITS (EXPENSE_ID);
CREATE INDEX IDX_SPLITS_MEMBER ON EXPENSE_SPLITS (MEMBER_ID);

-- 8. CASH_APPROVALS
CREATE TABLE CASH_APPROVALS (
    APPROVAL_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    ENTITY_TYPE VARCHAR(30) NOT NULL,
    ENTITY_ID VARCHAR(36) NOT NULL,
    APPROVER_MEMBER_ID VARCHAR(36) NOT NULL,
    DECISION VARCHAR(20) NOT NULL,
    COMMENT VARCHAR(500),
    DECIDED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (APPROVER_MEMBER_ID) REFERENCES GROUP_MEMBERS (GROUP_MEMBER_ID)
);
CREATE INDEX IDX_APPROVALS_ENTITY ON CASH_APPROVALS (ENTITY_TYPE, ENTITY_ID);

-- 9. LEDGER_ENTRIES
CREATE TABLE LEDGER_ENTRIES (
    LEDGER_ENTRY_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    GROUP_ID VARCHAR(36) NOT NULL,
    MEMBER_ID VARCHAR(36),
    ENTITY_TYPE VARCHAR(30) NOT NULL,
    ENTITY_ID VARCHAR(36) NOT NULL,
    ENTRY_TYPE VARCHAR(10) NOT NULL,
    AMOUNT_MINOR BIGINT NOT NULL,
    CURRENCY VARCHAR(10) NOT NULL DEFAULT 'INR',
    STATUS VARCHAR(20) NOT NULL DEFAULT 'POSTED',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (GROUP_ID) REFERENCES GROUPS (GROUP_ID),
    FOREIGN KEY (MEMBER_ID) REFERENCES GROUP_MEMBERS (GROUP_MEMBER_ID)
);
CREATE INDEX IDX_LEDGER_GROUP ON LEDGER_ENTRIES (GROUP_ID);
CREATE INDEX IDX_LEDGER_MEMBER ON LEDGER_ENTRIES (MEMBER_ID);
CREATE INDEX IDX_LEDGER_ENTITY ON LEDGER_ENTRIES (ENTITY_TYPE, ENTITY_ID);

-- 10. SETTLEMENT_RUNS
CREATE TABLE SETTLEMENT_RUNS (
    RUN_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    GROUP_ID VARCHAR(36) NOT NULL,
    TOTAL_MINOR BIGINT NOT NULL,
    CURRENCY VARCHAR(10) NOT NULL DEFAULT 'INR',
    STATUS VARCHAR(20) NOT NULL DEFAULT 'CALCULATED',
    CALCULATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CALCULATED_BY VARCHAR(36) NOT NULL,
    FOREIGN KEY (GROUP_ID) REFERENCES GROUPS (GROUP_ID),
    FOREIGN KEY (CALCULATED_BY) REFERENCES APP_USERS (USER_ID)
);
CREATE INDEX IDX_SETTLEMENT_GROUP ON SETTLEMENT_RUNS (GROUP_ID);

-- 11. SETTLEMENT_ITEMS
CREATE TABLE SETTLEMENT_ITEMS (
    ITEM_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    RUN_ID VARCHAR(36) NOT NULL,
    FROM_MEMBER_ID VARCHAR(36) NOT NULL,
    TO_MEMBER_ID VARCHAR(36) NOT NULL,
    AMOUNT_MINOR BIGINT NOT NULL,
    STATUS VARCHAR(20) NOT NULL DEFAULT 'RECOMMENDED',
    FOREIGN KEY (RUN_ID) REFERENCES SETTLEMENT_RUNS (RUN_ID),
    FOREIGN KEY (FROM_MEMBER_ID) REFERENCES GROUP_MEMBERS (GROUP_MEMBER_ID),
    FOREIGN KEY (TO_MEMBER_ID) REFERENCES GROUP_MEMBERS (GROUP_MEMBER_ID)
);
CREATE INDEX IDX_ITEMS_RUN ON SETTLEMENT_ITEMS (RUN_ID);

-- 12. AUDIT_EVENTS
CREATE TABLE AUDIT_EVENTS (
    EVENT_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    GROUP_ID VARCHAR(36),
    ACTOR_ID VARCHAR(36),
    EVENT_TYPE VARCHAR(50) NOT NULL,
    ENTITY_TYPE VARCHAR(50),
    ENTITY_ID VARCHAR(36),
    DETAILS_JSON VARCHAR(4000),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IDX_AUDIT_GROUP ON AUDIT_EVENTS (GROUP_ID);
CREATE INDEX IDX_AUDIT_TYPE ON AUDIT_EVENTS (EVENT_TYPE);
