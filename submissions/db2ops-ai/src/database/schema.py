"""Db2 DDL for the demo business schema."""

DDL = [
    """CREATE TABLE CUSTOMERS (
        CUSTOMER_ID INTEGER NOT NULL PRIMARY KEY,
        CUSTOMER_NAME VARCHAR(120) NOT NULL,
        EMAIL VARCHAR(180) NOT NULL UNIQUE,
        CITY VARCHAR(80) NOT NULL,
        STATE VARCHAR(80) NOT NULL,
        COUNTRY VARCHAR(60) NOT NULL DEFAULT 'India',
        CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP)""",
    """CREATE TABLE PRODUCTS (
        PRODUCT_ID INTEGER NOT NULL PRIMARY KEY,
        PRODUCT_NAME VARCHAR(140) NOT NULL,
        CATEGORY VARCHAR(80) NOT NULL,
        UNIT_PRICE DECIMAL(12,2) NOT NULL CHECK (UNIT_PRICE >= 0),
        STOCK_QUANTITY INTEGER NOT NULL CHECK (STOCK_QUANTITY >= 0))""",
    """CREATE TABLE ORDERS (
        ORDER_ID INTEGER NOT NULL PRIMARY KEY,
        CUSTOMER_ID INTEGER NOT NULL REFERENCES CUSTOMERS(CUSTOMER_ID),
        ORDER_DATE DATE NOT NULL,
        ORDER_STATUS VARCHAR(24) NOT NULL CHECK (ORDER_STATUS IN ('PLACED','PROCESSING','SHIPPED','DELIVERED','CANCELLED')),
        TOTAL_AMOUNT DECIMAL(12,2) NOT NULL CHECK (TOTAL_AMOUNT >= 0))""",
    """CREATE TABLE ORDER_ITEMS (
        ITEM_ID INTEGER NOT NULL PRIMARY KEY,
        ORDER_ID INTEGER NOT NULL REFERENCES ORDERS(ORDER_ID),
        PRODUCT_ID INTEGER NOT NULL REFERENCES PRODUCTS(PRODUCT_ID),
        QUANTITY INTEGER NOT NULL CHECK (QUANTITY > 0),
        UNIT_PRICE DECIMAL(12,2) NOT NULL CHECK (UNIT_PRICE >= 0),
        SUBTOTAL DECIMAL(12,2) NOT NULL CHECK (SUBTOTAL >= 0))""",
    """CREATE TABLE PAYMENTS (
        PAYMENT_ID INTEGER NOT NULL PRIMARY KEY,
        ORDER_ID INTEGER NOT NULL REFERENCES ORDERS(ORDER_ID),
        PAYMENT_METHOD VARCHAR(32) NOT NULL,
        PAYMENT_STATUS VARCHAR(24) NOT NULL CHECK (PAYMENT_STATUS IN ('PAID','PENDING','FAILED','REFUNDED')),
        PAYMENT_DATE DATE NOT NULL,
        AMOUNT DECIMAL(12,2) NOT NULL CHECK (AMOUNT >= 0))""",
    "CREATE INDEX IX_ORDERS_CUSTOMER_DATE ON ORDERS(CUSTOMER_ID, ORDER_DATE)",
    "CREATE INDEX IX_ORDER_ITEMS_PRODUCT ON ORDER_ITEMS(PRODUCT_ID)",
    "CREATE INDEX IX_PAYMENTS_STATUS_DATE ON PAYMENTS(PAYMENT_STATUS, PAYMENT_DATE)",
]

TABLES = ("CUSTOMERS", "PRODUCTS", "ORDERS", "ORDER_ITEMS", "PAYMENTS")
