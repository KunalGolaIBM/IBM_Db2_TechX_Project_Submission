-- Every question-box request, append-only. It also lets the app reuse SQL that Granite wrote and the checker
-- passed for an identical earlier question (Db2 still runs it live); visitors can always ask Granite afresh.
CREATE TABLE AQ.ASK_LOG (
  ID        BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ASKED_AT  TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  QUESTION  VARCHAR(300) NOT NULL,
  QNORM     VARCHAR(300) NOT NULL,
  SQL_TEXT  VARCHAR(4000),
  OUTCOME   VARCHAR(12) NOT NULL CHECK (OUTCOME IN ('ANSWERED', 'REFUSED', 'BLOCKED', 'DB2_ERROR')),
  SOURCE    VARCHAR(8) NOT NULL CHECK (SOURCE IN ('GRANITE', 'REUSED', 'GUARD')),
  MS_MODEL  INTEGER,
  MS_DB2    INTEGER,
  N_ROWS    INTEGER
)@
CREATE INDEX AQ.ASK_LOG_Q ON AQ.ASK_LOG (QNORM, OUTCOME, SOURCE)@
CREATE TRIGGER AQ.ASK_LOG_NO_UPDATE NO CASCADE BEFORE UPDATE ON AQ.ASK_LOG
 FOR EACH ROW SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'The question log is append-only'@
CREATE TRIGGER AQ.ASK_LOG_NO_DELETE NO CASCADE BEFORE DELETE ON AQ.ASK_LOG
 FOR EACH ROW SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'The question log is append-only'@
GRANT SELECT, INSERT ON AQ.ASK_LOG TO USER AQAPP@
