-- Verifiable AQI receipts. Every verdict Db2 writes gets a receipt, issued by a trigger in the same transaction:
-- a SHA-256 of the exact readings the verdict judged, a SHA-256 of the rules in force (breakpoints, plausibility
-- limits, settings), and a hash chained to the previous receipt. AQ.VERIFY_RECEIPT later replays the inputs with
-- FOR SYSTEM_TIME AS OF the issue time and says whether the data, the rules or the chain changed since.
-- SHA-256 is Db2's HASH(expr, 2).

CREATE TABLE AQ.RECEIPT (
  RECEIPT_ID   BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  RUN_ID       BIGINT NOT NULL REFERENCES AQ.VERDICT,
  STATION_ID   INTEGER NOT NULL,
  DAY          DATE NOT NULL,
  STATUS       VARCHAR(16) NOT NULL,
  AQI          SMALLINT,
  N_READINGS   INTEGER NOT NULL,            -- readings in the inputs window at issue time
  INPUT_HASH   CHAR(64) NOT NULL,           -- SHA-256 of those readings (parameter, time, value)
  RULES_HASH   CHAR(64) NOT NULL,           -- SHA-256 of AQ.BREAKPOINT, AQ.PLAUSIBLE and AQ.SETTING
  PREV_HASH    CHAR(64) NOT NULL,           -- RECEIPT_HASH of the receipt before this one
  RECEIPT_HASH CHAR(64) NOT NULL,           -- SHA-256 over PREV_HASH and every field above
  ISSUED_AT    TIMESTAMP(12) NOT NULL       -- = VERDICT.DATA_AS_OF
)@
CREATE INDEX AQ.RECEIPT_DAY ON AQ.RECEIPT (STATION_ID, DAY, RECEIPT_ID DESC)@
CREATE TRIGGER AQ.RECEIPT_NO_UPDATE NO CASCADE BEFORE UPDATE ON AQ.RECEIPT
 FOR EACH ROW SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'Receipts are append-only'@
CREATE TRIGGER AQ.RECEIPT_NO_DELETE NO CASCADE BEFORE DELETE ON AQ.RECEIPT
 FOR EACH ROW SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'Receipts are append-only'@

-- The inputs of a station-day verdict: every reading from 17:00 the evening before (the first 8-hour O3/CO window
-- ending 01:00 starts there) to midnight, as stored now (P_AS_OF NULL) or as Db2 held them at P_AS_OF.
CREATE OR REPLACE FUNCTION AQ.INPUTS (P_STATION INTEGER, P_DAY DATE, P_AS_OF TIMESTAMP(12))
 RETURNS TABLE (PARAM VARCHAR(12), TS TIMESTAMP(0), VALUE DOUBLE)
 LANGUAGE SQL READS SQL DATA NO EXTERNAL ACTION NOT DETERMINISTIC
RETURN
  SELECT R.PARAM, R.TS, R.VALUE FROM AQ.READING R
   WHERE P_AS_OF IS NULL AND R.STATION_ID = P_STATION
     AND R.TS >= TIMESTAMP(P_DAY) - 7 HOURS AND R.TS < TIMESTAMP(P_DAY) + 1 DAY
  UNION ALL
  SELECT R.PARAM, R.TS, R.VALUE FROM AQ.READING FOR SYSTEM_TIME AS OF COALESCE(P_AS_OF, TIMESTAMP('0001-01-01')) R
   WHERE P_AS_OF IS NOT NULL AND R.STATION_ID = P_STATION
     AND R.TS >= TIMESTAMP(P_DAY) - 7 HOURS AND R.TS < TIMESTAMP(P_DAY) + 1 DAY@

-- SHA-256 of the inputs: one hash per pollutant over its "time=value" list, then a hash over those
-- (keeps each LISTAGG well inside its 32 KB limit).
CREATE OR REPLACE FUNCTION AQ.INPUT_HASH (P_STATION INTEGER, P_DAY DATE, P_AS_OF TIMESTAMP(12))
 RETURNS CHAR(64) LANGUAGE SQL READS SQL DATA NO EXTERNAL ACTION NOT DETERMINISTIC
RETURN
  WITH P AS (
    SELECT I.PARAM, COUNT(*) AS N,
           HEX(HASH(LISTAGG(VARCHAR_FORMAT(I.TS, 'YYYY-MM-DD HH24:MI') || '=' || COALESCE(VARCHAR(DECIMAL(I.VALUE, 31, 6)), 'null'), ';')
                     WITHIN GROUP (ORDER BY I.TS), 2)) AS H
      FROM TABLE(AQ.INPUTS(P_STATION, P_DAY, P_AS_OF)) I GROUP BY I.PARAM)
  SELECT HEX(HASH(COALESCE(LISTAGG(P.PARAM || ':' || RTRIM(CHAR(P.N)) || ':' || P.H, '|') WITHIN GROUP (ORDER BY P.PARAM), 'none'), 2))
    FROM P@

-- SHA-256 of the rules in force: CPCB breakpoints, plausibility limits and audit settings.
CREATE OR REPLACE FUNCTION AQ.RULES_HASH ()
 RETURNS CHAR(64) LANGUAGE SQL READS SQL DATA NO EXTERNAL ACTION NOT DETERMINISTIC
RETURN
  VALUES HEX(HASH(
    (SELECT LISTAGG(PARAM || ',' || VARCHAR(BP_LO) || ',' || VARCHAR(BP_HI) || ',' || RTRIM(CHAR(I_LO)) || ',' || RTRIM(CHAR(I_HI)) || ',' || RTRIM(CHAR(AVG_HOURS)), ';')
              WITHIN GROUP (ORDER BY PARAM, BP_LO) FROM AQ.BREAKPOINT) || '#' ||
    (SELECT LISTAGG(PARAM || ',' || VARCHAR(MIN_V) || ',' || VARCHAR(MAX_V) || ',' || VARCHAR(MAX_JUMP) || ',' || RTRIM(CHAR(FLAT_HOURS)), ';')
              WITHIN GROUP (ORDER BY PARAM) FROM AQ.PLAUSIBLE) || '#' ||
    (SELECT LISTAGG(NAME || '=' || VARCHAR(NUM_VALUE), ';') WITHIN GROUP (ORDER BY NAME) FROM AQ.SETTING), 2))@

-- The receipt's own hash: the previous receipt's hash plus every field, in a fixed text form.
CREATE OR REPLACE FUNCTION AQ.RECEIPT_HASH (P_PREV CHAR(64), P_RUN BIGINT, P_STATION INTEGER, P_DAY DATE, P_STATUS VARCHAR(16),
                                            P_AQI SMALLINT, P_N INTEGER, P_IN CHAR(64), P_RULES CHAR(64), P_AT TIMESTAMP(12))
 RETURNS CHAR(64) LANGUAGE SQL DETERMINISTIC NO EXTERNAL ACTION CONTAINS SQL
RETURN HEX(HASH(P_PREV || '|' || RTRIM(CHAR(P_RUN)) || '|' || RTRIM(CHAR(P_STATION)) || '|' || CHAR(P_DAY, ISO) || '|' || P_STATUS
                || '|' || COALESCE(RTRIM(CHAR(P_AQI)), '-') || '|' || RTRIM(CHAR(P_N)) || '|' || P_IN || '|' || P_RULES
                || '|' || VARCHAR_FORMAT(P_AT, 'YYYY-MM-DD HH24:MI:SS.FF6'), 2))@

-- Issue the receipt in the same transaction as the verdict, whoever inserts it. SECURED: AQ.VERDICT is under row
-- access control. The chain is global; the receipt before is the one with the highest id.
CREATE TRIGGER AQ.VERDICT_RECEIPT AFTER INSERT ON AQ.VERDICT
 REFERENCING NEW AS N FOR EACH ROW SECURED
BEGIN ATOMIC
  DECLARE V_PREV CHAR(64); DECLARE V_IN CHAR(64); DECLARE V_RULES CHAR(64); DECLARE V_N INTEGER;
  SET V_PREV = COALESCE((SELECT RECEIPT_HASH FROM AQ.RECEIPT ORDER BY RECEIPT_ID DESC FETCH FIRST 1 ROW ONLY), REPEAT('0', 64));
  SET V_IN = AQ.INPUT_HASH(N.STATION_ID, N.DAY, CAST(NULL AS TIMESTAMP(12)));
  SET V_RULES = AQ.RULES_HASH();
  SET V_N = (SELECT COUNT(*) FROM TABLE(AQ.INPUTS(N.STATION_ID, N.DAY, CAST(NULL AS TIMESTAMP(12)))) I);
  INSERT INTO AQ.RECEIPT (RUN_ID, STATION_ID, DAY, STATUS, AQI, N_READINGS, INPUT_HASH, RULES_HASH, PREV_HASH, RECEIPT_HASH, ISSUED_AT)
  VALUES (N.RUN_ID, N.STATION_ID, N.DAY, N.STATUS, N.AQI, V_N, V_IN, V_RULES, V_PREV,
          AQ.RECEIPT_HASH(V_PREV, N.RUN_ID, N.STATION_ID, N.DAY, N.STATUS, N.AQI, V_N, V_IN, V_RULES, N.DATA_AS_OF), N.DATA_AS_OF);
END@

-- Verify the latest receipt of a station-day:
--   CHAIN_OK    the receipt's hash recomputes from its fields, and PREV_HASH is the hash of the receipt before it
--   HISTORY_OK  the readings Db2 returns FOR SYSTEM_TIME AS OF the issue time hash to INPUT_HASH (history intact)
--   DATA_SAME   the readings stored now hash to INPUT_HASH; if not, CHANGED counts them and EXAMPLE shows one
--   RULES_SAME  the rules in force now hash to RULES_HASH
-- RESULT: CHAIN_BROKEN, HISTORY_BROKEN, DATA_CHANGED, RULES_CHANGED or MATCH (first that applies).
CREATE OR REPLACE FUNCTION AQ.VERIFY_RECEIPT (P_STATION INTEGER, P_DAY DATE)
 RETURNS TABLE (RESULT VARCHAR(16), RECEIPT_ID BIGINT, RUN_ID BIGINT, STATUS VARCHAR(16), AQI SMALLINT, ISSUED_AT TIMESTAMP(12),
                RECEIPT_HASH CHAR(64), PREV_HASH CHAR(64), INPUT_HASH CHAR(64), N_READINGS INTEGER, N_NOW INTEGER,
                CHAIN_OK SMALLINT, HISTORY_OK SMALLINT, DATA_SAME SMALLINT, RULES_SAME SMALLINT, CHANGED INTEGER, EXAMPLE VARCHAR(200))
 LANGUAGE SQL READS SQL DATA NO EXTERNAL ACTION NOT DETERMINISTIC
BEGIN
  DECLARE V_ID BIGINT; DECLARE V_RUN BIGINT; DECLARE V_STATUS VARCHAR(16); DECLARE V_AQI SMALLINT; DECLARE V_N INTEGER;
  DECLARE V_IN CHAR(64); DECLARE V_RULES CHAR(64); DECLARE V_PREV CHAR(64); DECLARE V_HASH CHAR(64); DECLARE V_AT TIMESTAMP(12);
  DECLARE V_PRIOR CHAR(64); DECLARE V_COK SMALLINT; DECLARE V_HOK SMALLINT; DECLARE V_DOK SMALLINT; DECLARE V_ROK SMALLINT;
  DECLARE V_NNOW INTEGER; DECLARE V_CHANGED INTEGER DEFAULT 0; DECLARE V_EX VARCHAR(200);
  DECLARE V_FROM TIMESTAMP(0); DECLARE V_TO TIMESTAMP(0);
  DECLARE V_P VARCHAR(12); DECLARE V_T TIMESTAMP(0); DECLARE V_OLD DOUBLE; DECLARE V_NEW DOUBLE;
  SELECT R.RECEIPT_ID, R.RUN_ID, R.STATUS, R.AQI, R.N_READINGS, R.INPUT_HASH, R.RULES_HASH, R.PREV_HASH, R.RECEIPT_HASH, R.ISSUED_AT
    INTO V_ID, V_RUN, V_STATUS, V_AQI, V_N, V_IN, V_RULES, V_PREV, V_HASH, V_AT
    FROM AQ.RECEIPT R WHERE R.STATION_ID = P_STATION AND R.DAY = P_DAY ORDER BY R.RECEIPT_ID DESC FETCH FIRST 1 ROW ONLY;
  IF V_ID IS NULL THEN RETURN; END IF;
  SET V_FROM = TIMESTAMP(P_DAY) - 7 HOURS; SET V_TO = TIMESTAMP(P_DAY) + 1 DAY;
  SET V_PRIOR = COALESCE((SELECT X.RECEIPT_HASH FROM AQ.RECEIPT X WHERE X.RECEIPT_ID < V_ID ORDER BY X.RECEIPT_ID DESC FETCH FIRST 1 ROW ONLY), REPEAT('0', 64));
  SET V_COK = CASE WHEN V_HASH = AQ.RECEIPT_HASH(V_PREV, V_RUN, P_STATION, P_DAY, V_STATUS, V_AQI, V_N, V_IN, V_RULES, V_AT)
                    AND V_PREV = V_PRIOR THEN 1 ELSE 0 END;
  SET V_HOK = CASE WHEN AQ.INPUT_HASH(P_STATION, P_DAY, V_AT) = V_IN THEN 1 ELSE 0 END;
  SET V_DOK = CASE WHEN AQ.INPUT_HASH(P_STATION, P_DAY, CAST(NULL AS TIMESTAMP(12))) = V_IN THEN 1 ELSE 0 END;
  SET V_ROK = CASE WHEN AQ.RULES_HASH() = V_RULES THEN 1 ELSE 0 END;
  SET V_NNOW = (SELECT COUNT(*) FROM AQ.READING R WHERE R.STATION_ID = P_STATION AND R.TS >= V_FROM AND R.TS < V_TO);
  IF V_DOK = 0 THEN
    -- Readings that differ between now and the issue time (changed, added or withdrawn), keyed by pollutant and time.
    SET V_CHANGED = (SELECT COUNT(*) FROM (
        SELECT PARAM, TS FROM (SELECT PARAM, TS, VALUE FROM AQ.READING WHERE STATION_ID = P_STATION AND TS >= V_FROM AND TS < V_TO
                               EXCEPT SELECT PARAM, TS, VALUE FROM AQ.READING FOR SYSTEM_TIME AS OF V_AT
                                       WHERE STATION_ID = P_STATION AND TS >= V_FROM AND TS < V_TO) A
        UNION
        SELECT PARAM, TS FROM (SELECT PARAM, TS, VALUE FROM AQ.READING FOR SYSTEM_TIME AS OF V_AT
                                WHERE STATION_ID = P_STATION AND TS >= V_FROM AND TS < V_TO
                               EXCEPT SELECT PARAM, TS, VALUE FROM AQ.READING WHERE STATION_ID = P_STATION AND TS >= V_FROM AND TS < V_TO) B) D);
    SELECT PARAM, TS INTO V_P, V_T FROM (
        SELECT PARAM, TS, VALUE FROM AQ.READING WHERE STATION_ID = P_STATION AND TS >= V_FROM AND TS < V_TO
        EXCEPT SELECT PARAM, TS, VALUE FROM AQ.READING FOR SYSTEM_TIME AS OF V_AT WHERE STATION_ID = P_STATION AND TS >= V_FROM AND TS < V_TO) A
     ORDER BY TS FETCH FIRST 1 ROW ONLY;
    IF V_P IS NOT NULL THEN
      SET V_NEW = (SELECT VALUE FROM AQ.READING WHERE STATION_ID = P_STATION AND PARAM = V_P AND TS = V_T);
      SET V_OLD = (SELECT VALUE FROM AQ.READING FOR SYSTEM_TIME AS OF V_AT WHERE STATION_ID = P_STATION AND PARAM = V_P AND TS = V_T);
      SET V_EX = V_P || ' ' || VARCHAR_FORMAT(V_T, 'YYYY-MM-DD HH24:MI') || ': ' || COALESCE(VARCHAR(DECIMAL(V_OLD, 14, 2)), 'none')
                 || ' at issue (from history), ' || COALESCE(VARCHAR(DECIMAL(V_NEW, 14, 2)), 'none') || ' now';
    END IF;
  END IF;
  PIPE (CASE WHEN V_COK = 0 THEN 'CHAIN_BROKEN' WHEN V_HOK = 0 THEN 'HISTORY_BROKEN' WHEN V_DOK = 0 THEN 'DATA_CHANGED'
             WHEN V_ROK = 0 THEN 'RULES_CHANGED' ELSE 'MATCH' END,
        V_ID, V_RUN, V_STATUS, V_AQI, V_AT, V_HASH, V_PREV, V_IN, V_N, V_NNOW, V_COK, V_HOK, V_DOK, V_ROK, V_CHANGED, V_EX);
  RETURN;
END@

-- A safe tamper demonstration for visitors: inside a savepoint, overwrite one reading of the day (x10), verify the
-- receipt (it reports DATA_CHANGED and shows the old value from history), roll the change back, verify again.
-- Runs with the definer's authority, so AQAPP can call it without holding UPDATE on AQ.READING.
CREATE OR REPLACE PROCEDURE AQ.TAMPER_TEST (IN P_STATION INTEGER, IN P_DAY DATE,
       OUT P_TOUCHED VARCHAR(200), OUT P_DURING VARCHAR(16), OUT P_DURING_DETAIL VARCHAR(200), OUT P_AFTER VARCHAR(16))
LANGUAGE SQL MODIFIES SQL DATA
BEGIN
  DECLARE V_PARAM VARCHAR(12); DECLARE V_TS TIMESTAMP(0); DECLARE V_VAL DOUBLE;
  SELECT PARAM, TS, VALUE INTO V_PARAM, V_TS, V_VAL FROM AQ.READING
   WHERE STATION_ID = P_STATION AND TS >= TIMESTAMP(P_DAY) + 12 HOURS AND TS < TIMESTAMP(P_DAY) + 1 DAY AND VALUE > 0
   ORDER BY CASE PARAM WHEN 'pm25' THEN 1 WHEN 'pm10' THEN 2 ELSE 3 END, TS FETCH FIRST 1 ROW ONLY;
  SET P_TOUCHED = V_PARAM || ' ' || VARCHAR_FORMAT(V_TS, 'YYYY-MM-DD HH24:MI') || ': ' || VARCHAR(DECIMAL(V_VAL, 12, 2))
                  || ' changed to ' || VARCHAR(DECIMAL(V_VAL * 10, 12, 2));
  SAVEPOINT TAMPER ON ROLLBACK RETAIN CURSORS;
  UPDATE AQ.READING SET VALUE = VALUE * 10 WHERE STATION_ID = P_STATION AND PARAM = V_PARAM AND TS = V_TS;
  SELECT RESULT, EXAMPLE INTO P_DURING, P_DURING_DETAIL FROM TABLE(AQ.VERIFY_RECEIPT(P_STATION, P_DAY)) X;
  ROLLBACK TO SAVEPOINT TAMPER;
  RELEASE SAVEPOINT TAMPER;
  SELECT RESULT INTO P_AFTER FROM TABLE(AQ.VERIFY_RECEIPT(P_STATION, P_DAY)) X;
END@

-- Whole-chain check: how many receipts fail to recompute or do not link to the one before.
CREATE OR REPLACE VIEW AQ.V_RECEIPT_CHAIN AS
SELECT COUNT(*) AS RECEIPTS,
       SUM(CASE WHEN R.RECEIPT_HASH <> AQ.RECEIPT_HASH(R.PREV_HASH, R.RUN_ID, R.STATION_ID, R.DAY, R.STATUS, R.AQI, R.N_READINGS,
                                                        R.INPUT_HASH, R.RULES_HASH, R.ISSUED_AT)
                  OR R.PREV_HASH <> COALESCE(R.PRIOR, REPEAT('0', 64)) THEN 1 ELSE 0 END) AS BROKEN
  FROM (SELECT X.*, LAG(X.RECEIPT_HASH) OVER (ORDER BY X.RECEIPT_ID) AS PRIOR FROM AQ.RECEIPT X) R@

