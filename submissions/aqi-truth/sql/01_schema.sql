-- AQI Truth schema (IBM Db2 12.1). Statement terminator: @
CREATE SCHEMA AQ@

-- Stations (OpenAQ location ids, CPCB/DPCC/IMD/IITM operated)
CREATE TABLE AQ.STATION (
  STATION_ID   INTEGER NOT NULL PRIMARY KEY,
  NAME         VARCHAR(120) NOT NULL,
  OPERATOR     VARCHAR(20),
  LAT          DECIMAL(9,6),
  LON          DECIMAL(9,6)
)@

-- Hourly readings as published. System-period temporal: every later revision or deletion
-- of a published hour is kept in READING_HIST and can be queried AS OF any past time.
CREATE TABLE AQ.READING (
  STATION_ID   INTEGER NOT NULL,
  PARAM        VARCHAR(12) NOT NULL,
  TS           TIMESTAMP(0) NOT NULL,      -- reading timestamp (IST, CPCB 15-minute cadence)
  VALUE        DOUBLE,
  UNIT_SRC     VARCHAR(10),
  SYS_START    TIMESTAMP(12) NOT NULL GENERATED ALWAYS AS ROW BEGIN,
  SYS_END      TIMESTAMP(12) NOT NULL GENERATED ALWAYS AS ROW END,
  TRANS_ID     TIMESTAMP(12) GENERATED ALWAYS AS TRANSACTION START ID,
  PERIOD SYSTEM_TIME (SYS_START, SYS_END),
  PRIMARY KEY (STATION_ID, PARAM, TS)
)
PARTITION BY RANGE (TS)
 (STARTING '2025-01-01' ENDING '2026-12-31 23:59:59' EVERY 1 MONTH)@

CREATE TABLE AQ.READING_HIST LIKE AQ.READING
PARTITION BY RANGE (TS)
 (STARTING '2025-01-01' ENDING '2026-12-31 23:59:59' EVERY 1 MONTH)@
ALTER TABLE AQ.READING ADD VERSIONING USE HISTORY TABLE AQ.READING_HIST@

-- Staging for bulk loads; MERGE moves it into READING idempotently.
CREATE TABLE AQ.STAGE_READING (
  STATION_ID INTEGER NOT NULL, PARAM VARCHAR(12) NOT NULL, TS TIMESTAMP(0) NOT NULL,
  VALUE DOUBLE, UNIT_SRC VARCHAR(10)
)@

-- CPCB National AQI breakpoints (CPCB, "National Air Quality Index", 2014).
CREATE TABLE AQ.BREAKPOINT (
  PARAM VARCHAR(12) NOT NULL, BP_LO DOUBLE NOT NULL, BP_HI DOUBLE NOT NULL,
  I_LO SMALLINT NOT NULL, I_HI SMALLINT NOT NULL, AVG_HOURS SMALLINT NOT NULL,
  PRIMARY KEY (PARAM, BP_LO)
)@

-- Physical plausibility limits used by the fault detectors.
CREATE TABLE AQ.PLAUSIBLE (
  PARAM VARCHAR(12) NOT NULL PRIMARY KEY, MIN_V DOUBLE NOT NULL, MAX_V DOUBLE NOT NULL,
  MAX_JUMP DOUBLE NOT NULL, FLAT_HOURS SMALLINT NOT NULL
)@

-- One verdict per station-day audit run.
CREATE TABLE AQ.VERDICT (
  RUN_ID       BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  STATION_ID   INTEGER NOT NULL,
  DAY          DATE NOT NULL,
  STATUS       VARCHAR(16) NOT NULL CHECK (STATUS IN ('VALID','NOT_COMPUTABLE','SUSPECT')),
  AQI          SMALLINT,
  NAIVE_AQI    SMALLINT,          -- what a dashboard would show using every value it has
  PROMINENT    VARCHAR(12),
  VALID_PARAMS SMALLINT NOT NULL,
  REASON       VARCHAR(400) NOT NULL,
  DATA_AS_OF   TIMESTAMP(12) NOT NULL,   -- when the audit ran: READING FOR SYSTEM_TIME AS OF DATA_AS_OF returns the inputs it saw
  CREATED_AT   TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
)@

-- Append-only evidence ledger: one row per check per parameter.
CREATE TABLE AQ.EVIDENCE (
  RUN_ID     BIGINT NOT NULL REFERENCES AQ.VERDICT,
  PARAM      VARCHAR(12) NOT NULL,
  CHECK_CODE VARCHAR(20) NOT NULL,
  OBSERVED   VARCHAR(200) NOT NULL,
  RULE_REF   VARCHAR(40) NOT NULL,
  PASSED     SMALLINT NOT NULL,
  PRIMARY KEY (RUN_ID, PARAM, CHECK_CODE)
)@

CREATE TRIGGER AQ.EVIDENCE_NO_UPDATE NO CASCADE BEFORE UPDATE ON AQ.EVIDENCE
 FOR EACH ROW SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'Evidence ledger is append-only'@
CREATE TRIGGER AQ.EVIDENCE_NO_DELETE NO CASCADE BEFORE DELETE ON AQ.EVIDENCE
 FOR EACH ROW SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'Evidence ledger is append-only'@
CREATE TRIGGER AQ.VERDICT_NO_UPDATE NO CASCADE BEFORE UPDATE ON AQ.VERDICT
 FOR EACH ROW SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'Verdicts are append-only; re-run the audit instead'@
CREATE TRIGGER AQ.VERDICT_NO_DELETE NO CASCADE BEFORE DELETE ON AQ.VERDICT
 FOR EACH ROW SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'Verdicts are append-only; re-run the audit instead'@
-- Triggers do not fire on TRUNCATE, so the app connects as AQAPP, which holds no DELETE, ALTER or CONTROL
-- privilege on these tables (05_views.sql). Only the schema owner (the loader) could truncate them.

-- Latest verdict per station-day (V_DAY) and AS OF lookups on the history table.
CREATE INDEX AQ.VERDICT_DAY ON AQ.VERDICT (STATION_ID, DAY, RUN_ID DESC)@
CREATE INDEX AQ.READING_HIST_IX ON AQ.READING_HIST (STATION_ID, PARAM, TS, SYS_END)@

-- Rule texts (CPCB AQI method, CAG audit findings) with embeddings for citation lookup.
CREATE TABLE AQ.RULE_TEXT (
  RULE_REF  VARCHAR(40) NOT NULL PRIMARY KEY,
  SOURCE    VARCHAR(200) NOT NULL,
  URL       VARCHAR(400) NOT NULL,
  BODY      VARCHAR(2000) NOT NULL,
  EMBEDDING VECTOR(768, FLOAT32)   -- IBM granite-embedding-278m-multilingual
)@
