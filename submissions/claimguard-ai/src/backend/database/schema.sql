-- Table 1: CUSTOMER_DETAILS
-- Holds policyholders and claimant profile information
CREATE TABLE CUSTOMER_DETAILS (
    CUSTOMER_ID VARCHAR(50) NOT NULL PRIMARY KEY,
    FIRST_NAME VARCHAR(100) NOT NULL,
    LAST_NAME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(150) NOT NULL UNIQUE,
    PHONE VARCHAR(30),
    DATE_OF_BIRTH DATE,
    NATIONAL_ID VARCHAR(50),
    ADDRESS VARCHAR(255),
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

-- Table 2: POLICY_DETAILS
-- Holds active insurance policies, coverage limits, and deductibles
CREATE TABLE POLICY_DETAILS (
    POLICY_ID VARCHAR(50) NOT NULL PRIMARY KEY,
    CUSTOMER_ID VARCHAR(50) NOT NULL,
    POLICY_NUMBER VARCHAR(100) NOT NULL UNIQUE,
    POLICY_TYPE VARCHAR(50) NOT NULL,
    STATUS VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    START_DATE DATE NOT NULL,
    END_DATE DATE NOT NULL,
    MAX_COVERAGE_AMOUNT DECIMAL(12,2) NOT NULL,
    REMAINING_COVERAGE DECIMAL(12,2) NOT NULL,
    DEDUCTIBLE DECIMAL(10,2) DEFAULT 0.00,
    COPAY_PERCENTAGE DECIMAL(5,2) DEFAULT 0.00,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_POLICY_CUSTOMER FOREIGN KEY (CUSTOMER_ID) 
        REFERENCES CUSTOMER_DETAILS (CUSTOMER_ID) ON DELETE CASCADE
);

-- Table 3: CLAIM_RECORDS
-- Core insurance claims submitted for verification and adjudication
CREATE TABLE CLAIM_RECORDS (
    CLAIM_ID VARCHAR(50) NOT NULL PRIMARY KEY,
    POLICY_ID VARCHAR(50) NOT NULL,
    CUSTOMER_ID VARCHAR(50) NOT NULL,
    CLAIM_NUMBER VARCHAR(100) NOT NULL UNIQUE,
    INCIDENT_DATE DATE NOT NULL,
    ADMISSION_DATE DATE,
    DISCHARGE_DATE DATE,
    CLAIM_AMOUNT DECIMAL(12,2) NOT NULL,
    APPROVED_AMOUNT DECIMAL(12,2) DEFAULT 0.00,
    HOSPITAL_NAME VARCHAR(200),
    HOSPITAL_INVOICE_NUMBER VARCHAR(100),
    DIAGNOSIS_CODE VARCHAR(50),
    DIAGNOSIS_DESCRIPTION VARCHAR(500),
    STATUS VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    RISK_SCORE DECIMAL(5,2) DEFAULT 0.00,
    RISK_LEVEL VARCHAR(20) DEFAULT 'LOW',
    DECISION_NOTES VARCHAR(1000),
    REVIEWED_BY VARCHAR(50),
    SUBMITTED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_CLAIM_POLICY FOREIGN KEY (POLICY_ID) 
        REFERENCES POLICY_DETAILS (POLICY_ID) ON DELETE CASCADE,
    CONSTRAINT FK_CLAIM_CUSTOMER FOREIGN KEY (CUSTOMER_ID) 
        REFERENCES CUSTOMER_DETAILS (CUSTOMER_ID) ON DELETE CASCADE
);

-- Table 4: DOCUMENT_RECORDS
-- Uploaded claim evidence (medical bills, discharge summaries, prescriptions)
CREATE TABLE DOCUMENT_RECORDS (
    DOCUMENT_ID VARCHAR(50) NOT NULL PRIMARY KEY,
    CLAIM_ID VARCHAR(50) NOT NULL,
    DOCUMENT_NAME VARCHAR(255) NOT NULL,
    DOCUMENT_TYPE VARCHAR(50) NOT NULL,
    FILE_PATH VARCHAR(500) NOT NULL,
    FILE_HASH VARCHAR(64) NOT NULL,
    FILE_SIZE_BYTES BIGINT NOT NULL,
    MIME_TYPE VARCHAR(100) NOT NULL,
    EXTRACTED_DATA CLOB,
    UPLOADED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_DOC_CLAIM FOREIGN KEY (CLAIM_ID) 
        REFERENCES CLAIM_RECORDS (CLAIM_ID) ON DELETE CASCADE
);

-- Table 5: FRAUD_ALERTS
-- Detected fraud indicators and rule-based anomaly flags
CREATE TABLE FRAUD_ALERTS (
    ALERT_ID VARCHAR(50) NOT NULL PRIMARY KEY,
    CLAIM_ID VARCHAR(50) NOT NULL,
    ALERT_TYPE VARCHAR(100) NOT NULL,
    SEVERITY VARCHAR(20) NOT NULL,
    DESCRIPTION VARCHAR(1000) NOT NULL,
    EVIDENCE_DETAILS CLOB,
    IS_RESOLVED SMALLINT DEFAULT 0,
    RESOLVED_BY VARCHAR(50),
    RESOLUTION_NOTES VARCHAR(1000),
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_ALERT_CLAIM FOREIGN KEY (CLAIM_ID) 
        REFERENCES CLAIM_RECORDS (CLAIM_ID) ON DELETE CASCADE
);

-- Table 6: VERIFICATION_LOGS
-- Comprehensive audit trail for agent actions and verification steps
CREATE TABLE VERIFICATION_LOGS (
    LOG_ID VARCHAR(50) NOT NULL PRIMARY KEY,
    CLAIM_ID VARCHAR(50) NOT NULL,
    AGENT_NAME VARCHAR(50) NOT NULL,
    ACTION VARCHAR(100) NOT NULL,
    STATUS VARCHAR(30) NOT NULL,
    DETAILS CLOB,
    EXECUTION_TIME_MS INTEGER,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_LOG_CLAIM FOREIGN KEY (CLAIM_ID) 
        REFERENCES CLAIM_RECORDS (CLAIM_ID) ON DELETE CASCADE
);

-- Table 7: USERS
-- Internal claims examiners, investigators, and admin accounts
CREATE TABLE USERS (
    USER_ID VARCHAR(50) NOT NULL PRIMARY KEY,
    USERNAME VARCHAR(50) NOT NULL UNIQUE,
    EMAIL VARCHAR(150) NOT NULL UNIQUE,
    HASHED_PASSWORD VARCHAR(255) NOT NULL,
    FULL_NAME VARCHAR(100) NOT NULL,
    ROLE VARCHAR(30) NOT NULL DEFAULT 'REVIEWER',
    IS_ACTIVE SMALLINT DEFAULT 1,
    CREATED_AT TIMESTAMP DEFAULT CURRENT TIMESTAMP
);

-- ============================================================================
-- PERFORMANCE & INTEGRITY INDEXES
-- ============================================================================
CREATE INDEX IDX_POLICY_CUST ON POLICY_DETAILS (CUSTOMER_ID);
CREATE INDEX IDX_CLAIM_POL ON CLAIM_RECORDS (POLICY_ID);
CREATE INDEX IDX_CLAIM_CUST ON CLAIM_RECORDS (CUSTOMER_ID);
CREATE INDEX IDX_CLAIM_INVOICE ON CLAIM_RECORDS (HOSPITAL_INVOICE_NUMBER);
CREATE INDEX IDX_DOC_HASH ON DOCUMENT_RECORDS (FILE_HASH);
CREATE INDEX IDX_DOC_CLAIM ON DOCUMENT_RECORDS (CLAIM_ID);
CREATE INDEX IDX_ALERT_CLAIM ON FRAUD_ALERTS (CLAIM_ID);
CREATE INDEX IDX_LOG_CLAIM ON VERIFICATION_LOGS (CLAIM_ID);

