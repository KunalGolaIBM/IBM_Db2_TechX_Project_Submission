-- Bitemporal consent ledger
-- Tracks "what consent was valid when" (business time) and "what we knew when" (system time)

CREATE TABLE CONSENT (
    PATIENT_ID     INT NOT NULL,
    PURPOSE        VARCHAR(40) NOT NULL,
    GRANTED        CHAR(1) NOT NULL CHECK (GRANTED IN ('Y', 'N')),
    BUS_START      DATE NOT NULL,
    BUS_END        DATE NOT NULL,
    SYS_START      TIMESTAMP(12) NOT NULL GENERATED ALWAYS AS ROW BEGIN,
    SYS_END        TIMESTAMP(12) NOT NULL GENERATED ALWAYS AS ROW END,
    TRANS_ID       TIMESTAMP(12) GENERATED ALWAYS AS TRANSACTION START ID,
    PERIOD BUSINESS_TIME (BUS_START, BUS_END),
    PERIOD SYSTEM_TIME (SYS_START, SYS_END),
    PRIMARY KEY (PATIENT_ID, PURPOSE, BUSINESS_TIME WITHOUT OVERLAPS)
);

CREATE TABLE CONSENT_HISTORY LIKE CONSENT;

ALTER TABLE CONSENT ADD VERSIONING USE HISTORY TABLE CONSENT_HISTORY;

-- Create indexes for common queries
CREATE INDEX IDX_CONSENT_PATIENT ON CONSENT(PATIENT_ID);
CREATE INDEX IDX_CONSENT_PURPOSE ON CONSENT(PURPOSE);
CREATE INDEX IDX_CONSENT_HIST_PATIENT ON CONSENT_HISTORY(PATIENT_ID);
