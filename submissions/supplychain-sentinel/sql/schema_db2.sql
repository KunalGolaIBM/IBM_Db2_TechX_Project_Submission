CREATE TABLE SUPPLIER (
  SUPPLIER_ID VARCHAR(20) NOT NULL PRIMARY KEY,
  SUPPLIER_NAME VARCHAR(120) NOT NULL,
  ON_TIME_RATE DECIMAL(5,2) NOT NULL,
  STATUS VARCHAR(20) NOT NULL
);

CREATE TABLE COMPONENT (
  COMPONENT_ID VARCHAR(20) NOT NULL PRIMARY KEY,
  COMPONENT_NAME VARCHAR(120) NOT NULL,
  CRITICALITY VARCHAR(20) NOT NULL,
  DAILY_DEMAND INTEGER NOT NULL
);

CREATE TABLE INVENTORY (
  COMPONENT_ID VARCHAR(20) NOT NULL PRIMARY KEY,
  ON_HAND_QTY INTEGER NOT NULL,
  RESERVED_QTY INTEGER NOT NULL,
  FOREIGN KEY (COMPONENT_ID) REFERENCES COMPONENT(COMPONENT_ID)
);

CREATE TABLE PURCHASE_ORDER (
  PO_ID VARCHAR(20) NOT NULL PRIMARY KEY,
  SUPPLIER_ID VARCHAR(20) NOT NULL,
  COMPONENT_ID VARCHAR(20) NOT NULL,
  ORDER_QTY INTEGER NOT NULL,
  EXPECTED_DATE DATE NOT NULL,
  STATUS VARCHAR(20) NOT NULL,
  FOREIGN KEY (SUPPLIER_ID) REFERENCES SUPPLIER(SUPPLIER_ID),
  FOREIGN KEY (COMPONENT_ID) REFERENCES COMPONENT(COMPONENT_ID)
);

CREATE TABLE SHIPMENT_EVENT (
  SHIPMENT_ID VARCHAR(20) NOT NULL PRIMARY KEY,
  PO_ID VARCHAR(20) NOT NULL,
  EVENT_STATUS VARCHAR(30) NOT NULL,
  ORIGINAL_ETA DATE NOT NULL,
  REVISED_ETA DATE NOT NULL,
  EVENT_NOTE VARCHAR(500),
  FOREIGN KEY (PO_ID) REFERENCES PURCHASE_ORDER(PO_ID)
);

CREATE TABLE QUALITY_INSPECTION (
  INSPECTION_ID VARCHAR(20) NOT NULL PRIMARY KEY,
  COMPONENT_ID VARCHAR(20) NOT NULL,
  QUALITY_STATUS VARCHAR(20) NOT NULL,
  INSPECTION_DATE DATE NOT NULL,
  FOREIGN KEY (COMPONENT_ID) REFERENCES COMPONENT(COMPONENT_ID)
);

CREATE TABLE PRODUCTION_ORDER (
  PRODUCTION_ORDER_ID VARCHAR(20) NOT NULL PRIMARY KEY,
  COMPONENT_ID VARCHAR(20) NOT NULL,
  REQUIRED_QTY INTEGER NOT NULL,
  REQUIRED_DATE DATE NOT NULL,
  ORDER_STATUS VARCHAR(20) NOT NULL,
  FOREIGN KEY (COMPONENT_ID) REFERENCES COMPONENT(COMPONENT_ID)
);

CREATE TABLE RISK_CASE (
  CASE_ID VARCHAR(40) NOT NULL PRIMARY KEY,
  SHIPMENT_ID VARCHAR(20) NOT NULL,
  COMPONENT_ID VARCHAR(20) NOT NULL,
  SEVERITY VARCHAR(20) NOT NULL,
  SUMMARY VARCHAR(1000) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
);

CREATE TABLE RECOMMENDATION (
  RECOMMENDATION_ID VARCHAR(40) NOT NULL PRIMARY KEY,
  CASE_ID VARCHAR(40) NOT NULL,
  OPTION_NAME VARCHAR(120) NOT NULL,
  RATIONALE VARCHAR(1000) NOT NULL,
  STATUS VARCHAR(20) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  FOREIGN KEY (CASE_ID) REFERENCES RISK_CASE(CASE_ID)
);

CREATE TABLE APPROVAL_AUDIT (
  AUDIT_ID VARCHAR(40) NOT NULL PRIMARY KEY,
  CASE_ID VARCHAR(40) NOT NULL,
  RECOMMENDATION_ID VARCHAR(40) NOT NULL,
  DECISION VARCHAR(20) NOT NULL,
  APPROVER VARCHAR(120) NOT NULL,
  RATIONALE VARCHAR(1000),
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  FOREIGN KEY (CASE_ID) REFERENCES RISK_CASE(CASE_ID),
  FOREIGN KEY (RECOMMENDATION_ID) REFERENCES RECOMMENDATION(RECOMMENDATION_ID)
);
